using DshPanel.Server;
using Xunit;

namespace DshPanel.Tests;

/// <summary>
/// СЛУШАЮЩАЯ СТРОКА ТАБЛИЦЫ ПОРТОВ — РЕШЕНИЕ БЕЗ ЖИВОЙ ТАБЛИЦЫ (DEF-074, §4.1).
///
/// **Зачем отдельный класс.** Корень дефекта 2.4.4 жил в фильтре, который стоял ВНУТРИ разбора
/// `GetExtendedTcpTable`: проверку «это слушатель?» нельзя было ни подать строкой, ни доказать
/// иначе, чем живой машиной. Здесь проверяется ровно решение, а числа взяты с живого замера
/// 30.10.2026: у порта 3080 (живой сервер DSH, pid 21008) слушающая таблица отдавала
/// <c>dwState = 6</c>, а не 2, — и прежний фильтр `dwState == 2` выбрасывал живого слушателя.
///
/// ⚠️ Проверка НЕ занимает 3080 и вообще ничего не связывает: это чистая функция. Порт и номер
/// процесса — просто числа из замера.
/// </summary>
public sealed class PortTableTests
{
    /// <summary>
    /// ЖИВОЙ СЛУШАТЕЛЬ С СОСТОЯНИЕМ 6 ПРИЗНАЁТСЯ СЛУШАТЕЛЕМ — ровно тот случай, из-за которого
    /// панель 2.4.4 снимала свою же запись о сервере (DEF-074).
    ///
    /// Мутация, которая обязана упасть здесь: **вернуть фильтр `state == 2`** — тогда строка 3080
    /// перестанет быть слушателем, `GetListenerPid(3080)` вернёт 0, и весь дефект вернётся.
    /// </summary>
    [Fact]
    public void Слушатель_с_состоянием_6_остаётся_слушателем()
    {
        // Замер 30.10.2026: порт 3080, pid 21008, dwState = 6, удалённый порт 0.
        Assert.True(PortTable.RowIsListener(state: 6, localPort: 3080, remotePort: 0, pid: 21008));
    }

    /// <summary>
    /// СОСТОЯНИЕ НЕ УЧАСТВУЕТ ВООБЩЕ: в слушающей таблице настоящие слушатели приходят с 0, 1, 2
    /// и 6 (тот же замер), и все они — слушатели.
    ///
    /// Мутация: **считать слушателем только состояние 2** — упадёт на 0, 1 и 6.
    /// </summary>
    [Theory]
    [InlineData(0)]
    [InlineData(1)]
    [InlineData(2)]
    [InlineData(6)]
    public void Любое_состояние_строки_слушающей_таблицы_не_мешает(int state)
    {
        Assert.True(PortTable.RowIsListener(state, localPort: 43127, remotePort: 0, pid: 20644));
    }

    /// <summary>
    /// У СЛУШАТЕЛЯ УДАЛЁННОГО ПОРТА НЕТ. Строка с удалённым портом — соединение, а не слушатель:
    /// по ней панель нашла бы «процесс» там, где сервера нет.
    ///
    /// Мутация: **убрать проверку удалённого порта** — упадёт здесь.
    /// </summary>
    [Fact]
    public void Строка_с_удалённым_портом_слушателем_не_считается()
    {
        Assert.False(PortTable.RowIsListener(state: 2, localPort: 3080, remotePort: 50123, pid: 21008));
    }

    /// <summary>
    /// НУЛЕВОЙ НОМЕР ПРОЦЕССА — НЕ СЛУШАТЕЛЬ. Такой строкой панель нашла бы «дырку» вместо сервера
    /// (урок v1, из-за которого фильтр и появился).
    ///
    /// Мутация: **убрать проверку номера процесса** — упадёт здесь.
    /// </summary>
    [Fact]
    public void Строка_без_процесса_слушателем_не_считается()
    {
        Assert.False(PortTable.RowIsListener(state: 2, localPort: 3080, remotePort: 0, pid: 0));
    }

    /// <summary>
    /// НУЛЕВОЙ ЛОКАЛЬНЫЙ ПОРТ — НЕ СЛУШАТЕЛЬ: порт 0 у слушателя не бывает (система выдаёт
    /// настоящий номер при связывании).
    ///
    /// Мутация: **убрать проверку локального порта** — упадёт здесь.
    /// </summary>
    [Fact]
    public void Строка_без_порта_слушателем_не_считается()
    {
        Assert.False(PortTable.RowIsListener(state: 2, localPort: 0, remotePort: 0, pid: 21008));
    }

    /// <summary>
    /// ТАБЛИЦУ НЕ ПРОЧИТАЛИ — ЭТО <b>-1</b>, А НЕ «СЛУШАТЕЛЕЙ НЕТ»: различать эти два ответа
    /// обязательно, иначе «не смог узнать» показывается человеку как «порт свободен».
    ///
    /// ⚠️ Здесь проверяется только форма ответа при живом вызове: на машине проверки он всегда
    /// читается, а «не прочитали» подставляется делегатом в проверках контроллера
    /// (<see cref="OwnServerTests.Непрочитанная_таблица_портов_запись_не_снимает"/>).
    /// </summary>
    [Fact]
    public void Непрочитанная_таблица_отвечает_минус_единицей_а_не_нулём()
    {
        // Порт 0 не слушает никто и слушать не может: ответ обязан быть «никто» (0), а не «ошибка».
        Assert.Equal(0, PortTable.GetListenerPid(0));
    }
}
