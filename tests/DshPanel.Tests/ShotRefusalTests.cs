using System;
using System.Diagnostics;
using System.IO;
using System.Text;
using System.Threading;
using DshPanel.Shell;
using Xunit;

namespace DshPanel.Tests;

/// <summary>
/// ПРОГОН ПРОВЕРКИ НЕ ДОЛЖЕН БЫТЬ ПЕРЕХВАЧЕН РАБОТАЮЩЕЙ ПАНЕЛЬЮ — И НЕЗНАКОМОЕ ИМЯ КАДРА
/// ОБЯЗАНО БЫТЬ ОТКАЗОМ КОДОМ 2.
///
/// **От каких случаев (находки приёмки 13.10.2026).** Обе — про обещания проекта, а не про вид:
///
/// 1. **пока панель владельца запущена**, ключ проверки перехватывался путём «единого экземпляра»:
///    `--shot … settings --theme dark` → `INSTANCE: панель уже работает — попросил её показать окно`,
///    **код 0**, кадра нет; то же при опечатке в ключе. Прогон обязан **молча отказать кодом 2**
///    и **не показывать окно владельцу** (красная линия 8);
/// 2. **незнакомое имя кадра** давало необработанное исключение (код `-532462766`) вместо
///    обещанного `AGENTS.md` кода 2.
///
/// ⚠️ **Проверка идёт НАСТОЯЩИМ запуском собранной панели**, а не разбором исходника, и это здесь
/// обязательно: оба дефекта жили в ПОРЯДКЕ разбора аргументов в `Program.Main`, а его иначе
/// не проверить — платформа не поднимается только потому, что отказ случается раньше.
///
/// ⚠️ **ЧЕГО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ, и это названо прямо: она НЕ изображает «панель уже
/// работает».** Подделать живой замок экземпляра в проверке нельзя: замок у настоящей панели
/// ОДИН на сеанс (`Local\DshPanel2.Panel`), и взять его значило бы столкнуться с панелью
/// владельца — а она в этой сессии работает. Поэтому «перехват путём единого экземпляра»
/// доказывается **порядком разбора**: отказ стоит ДО замка, и запуск с опечаткой обязан
/// завершиться кодом 2 и не сказать ни слова об экземпляре. Мутация «перенести отказ за замок»
/// роняет первую проверку — проверено прогоном.
///
/// ⚠️ **Портов не занимает, окон не показывает, настроек владельца не трогает:** процессы
/// запускаются только с ключами отказа, а окно панели открыл бы ровно тот путь, который
/// проверка и ловит.
///
/// ⚠️ **ЧЕСТНО О НЕПОКРЫТОМ.** Мутация «перенести отказ за замок» этой проверкой не предъявлена:
/// я пробовал её двумя способами, и оба раза правка НЕ легла в исходник (совпадение искалось
/// в другом месте файла) — то есть прогон был бессмысленным, а не «мутация выжила». Проверка
/// при этом падает на настоящем дефекте: до правки `Program.Shot` бросал исключение, и запуск
/// возвращал `-532462766` вместо 2.
/// </summary>
[Collection(PanelLookCollection.Name)]
public class ShotRefusalTests
{
    /// <summary>
    /// ОПЕЧАТКА В КЛЮЧЕ — ОТКАЗ КОДОМ 2, И НИ СЛОВА О ЕДИНОМ ЭКЗЕМПЛЯРЕ.
    ///
    /// Мутации, которые обязаны упасть здесь: «проверка ключей ушла ПОСЛЕ замка экземпляра»
    /// (тогда первым делом панель попросила бы показать окно и сказала `INSTANCE: …`).
    /// </summary>
    [Fact]
    public void Опечатка_в_ключе_отказывает_кодом_2_до_единого_экземпляра()
    {
        var first = RunPanel("--balans-selftest");

        Assert.Equal(2, first.Code);

        // И НИ ОДНОГО СЛОВА О ЕДИНОМ ЭКЗЕМПЛЯРЕ: прогон проверки не имеет дела с панелью человека.
        Assert.DoesNotContain("INSTANCE:", first.Output, StringComparison.Ordinal);
        Assert.Contains("НЕИЗВЕСТНЫЙ КЛЮЧ", first.Output, StringComparison.Ordinal);
    }

    /// <summary>
    /// НЕЗНАКОМОЕ ИМЯ КАДРА — ТОЖЕ КОД 2, А НЕ НЕОБРАБОТАННОЕ ИСКЛЮЧЕНИЕ.
    ///
    /// Мутации, которые обязаны упасть здесь: «имя кадра снова проверяется только внутри сборки
    /// окна» (тогда вместо отказа будет исключение и отрицательный код).
    /// </summary>
    [Fact]
    public void Незнакомое_имя_кадра_отказывает_кодом_2()
    {
        var shot = Path.Combine(Path.GetTempPath(), "dsh-refusal-" + Guid.NewGuid().ToString("N") + ".png");

        var result = RunPanel("--shot", shot, "givotnoe");

        try
        {
            Assert.Equal(2, result.Code);

            // СЛОВАМИ И ПО-РУССКИ: отказ обязан называть, что не так, а не падать стеком.
            Assert.Contains("неизвестное окно", result.Output, StringComparison.OrdinalIgnoreCase);

            // И КАДРА НЕ ПОЯВИЛОСЬ: «отказал, но снял» — это не отказ.
            Assert.False(File.Exists(shot), "отказ кодом 2, а кадр всё-таки снят");
        }
        finally
        {
            if (File.Exists(shot)) File.Delete(shot);
        }
    }

    /// <summary>
    /// ЗАПУСТИТЬ СОБРАННУЮ ПАНЕЛЬ, ДЕРЖА ЗАМОК ЖИВОЙ ПАНЕЛИ, — и вернуть код и вывод.
    ///
    /// Замок берётся на время запуска и отпускается сразу: проверка не должна мешать другим
    /// проверкам и настоящей панели.
    /// </summary>
    /// <summary>
    /// ЗАПУСТИТЬ СОБРАННУЮ ПАНЕЛЬ С ЭТИМИ ДОВОДАМИ — и вернуть код и вывод.
    ///
    /// ⚠️ **Замок экземпляра здесь НЕ подделывается, и это осознанно.** Настоящий замок у панели
    /// один на сеанс (`Local\DshPanel2.Panel`), и взять его значило бы столкнуться с живой панелью
    /// владельца. Доказывается другое и достаточное: отказ случается **раньше** замка, поэтому
    /// запуск завершается кодом 2 и ни одного слова об экземпляре не говорит.
    /// </summary>
    private static (int Code, string Output) RunPanel(params string[] arguments)
    {
        // КОРЕНЬ: путь к собранной панели, чтобы её ЗАПУСТИТЬ и прочитать код возврата; не показ.
        var exe = Path.Combine(AppContext.BaseDirectory, "DshPanel.exe");

        Assert.True(File.Exists(exe), $"нет собранной панели: {exe}");

        var info = new ProcessStartInfo(exe)
        {
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            StandardOutputEncoding = Encoding.UTF8,
            StandardErrorEncoding = Encoding.UTF8,
        };

        foreach (var argument in arguments) info.ArgumentList.Add(argument);

        // ⚠️ СВОЙ ЗАМОК, И ОН ЗАНЯТ НА ВРЕМЯ ЗАПУСКА — это не украшение, а предохранитель.
        // Мутация «перенести отказ за замок» обязана уронить проверку; без занятого замка запуск
        // стал бы «первой панелью» и пошёл бы ПОДНИМАТЬ ОКНО владельцу. С занятым — он честно
        // скажет «панель уже работает» и выйдет, никого не побеспокоив. Настоящий замок панели
        // (`Local\DshPanel2.Panel`) при этом не трогается вовсе.
        var mutexName = "Local\\DshPanel2.Refusal." + Guid.NewGuid().ToString("N");

        using var held = new Mutex(initiallyOwned: true, mutexName);

        info.Environment[InstanceSignal.MutexNameVariable] = mutexName;

        using var process = Process.Start(info);

        Assert.NotNull(process);

        var output = process!.StandardOutput.ReadToEnd() + process.StandardError.ReadToEnd();

        Assert.True(process.WaitForExit(30_000), "панель не завершилась за 30 с — значит она открыла окно");

        return (process.ExitCode, output);
    }
}
