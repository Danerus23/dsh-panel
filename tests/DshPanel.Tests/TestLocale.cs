using System.Globalization;
using System.Runtime.CompilerServices;
using DshPanel.Localization;

namespace DshPanel.Tests;

/// <summary>
/// Язык и КУЛЬТУРА проверок заданы ЯВНО — и это не формальность.
///
/// На машине разработки язык системы русский, поэтому тесты «сходились бы» и без этого:
/// строки интерфейса на русском, и сравнение с русским литералом проходит. Стоило бы языку
/// машины стать английским — и половина проверок покраснела бы не от дефекта, а от локали
/// сборочной машины. Проверка, зависящая от машины, ничего не стоит.
///
/// Поэтому язык выставляется ОДИН раз, до первого обращения к строкам (модульный инициализатор),
/// и больше не меняется: проверки других языков идут через <see cref="Loc.TIn"/>, который
/// глобального состояния не трогает (xunit гоняет классы параллельно).
///
/// ⚠️ **Язык строк — НЕ то же самое, что культура форматирования, и одной <c>Loc.Init("ru")</c>
/// мало.** <c>Loc</c> задаёт, на каком языке панель ГОВОРИТ; культура решает, как .NET пишет
/// числа, даты и деньги. Культура прогона не была задана вовсе — бралась у машины, а ожидания
/// в проверках написаны под русскую. Культура ставится здесь же, рядом с языком, и так же ОДИН
/// раз — в одном месте, а не в каждой проверке по отдельности.
///
/// ⚠️ **Честно о причине падений CI (замер 30.09.2026).** Прогон падал НЕ из-за языка ответов
/// Windows и НЕ из-за культуры: семь из восьми падений дал ЧАСОВОЙ ПОЯС — сборочный раннер идёт
/// по UTC, машина владельца по UTC+3, а проверки сверяли момент со смещением +03:00, вписанным
/// руками. Закрепление культуры здесь всё равно нужно — но само по себе оно тех падений НЕ лечит:
/// прогон с закреплением на en-US и поясом UTC падал ровно так же. Поэтому в наборе ДВА
/// независимых закрепления, и путать их нельзя: культура — здесь, пояс — в самих проверках,
/// у каждой свой (<c>TimeZoneInfo.Local.GetUtcOffset</c>). Подмена одного другим выглядит как
/// починка, а починкой не является.
///
/// **Почему <see cref="CultureInfo.InvariantCulture"/>, а не ru-RU.** Панель — русскоязычный
/// продукт, но работать обязана в любой локали, и прогон проверок обязан быть детерминированным
/// на ЛЮБОЙ машине. Приколотая ru-RU сделала бы прогон зелёным на машине владельца просто
/// потому, что она русская, — то есть повторила бы ровно ту беду, ради которой правило и
/// заведено (проверка, сходящаяся «потому что машина такая», ничего не стоит). Инвариантная
/// культура не совпадает ни с одной машиной и потому честно показывает, что проверка не
/// опирается на локаль. А «панель говорит по-русски» стерегут словари и <see cref="Loc"/> —
/// у них для этого свои проверки, и они этой правкой не тронуты.
///
/// Обе культуры ставятся вместе, и это не дублирование: <c>CurrentUICulture</c> живёт отдельно
/// от <c>CurrentCulture</c>, и оставь её английской — проверки, спрашивающие у .NET строку
/// интерфейса, снова зависели бы от машины.
/// </summary>
public static class TestLocale
{
    private static int _done;

    /// <summary>Повторный вызов безопасен и НИЧЕГО не переписывает: язык задаётся один раз.</summary>
    [ModuleInitializer]
    public static void Initialize()
    {
        if (Interlocked.Exchange(ref _done, 1) != 0) return;

        // Порядок не случаен: культура ставится ДО Loc.Init — так состояние словарей и состояние
        // культур задаются одной точкой входа и не могут разъехаться.
        CultureInfo.DefaultThreadCurrentCulture = CultureInfo.InvariantCulture;
        CultureInfo.DefaultThreadCurrentUICulture = CultureInfo.InvariantCulture;
        CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
        CultureInfo.CurrentUICulture = CultureInfo.InvariantCulture;

        Loc.Init("ru");
    }
}
