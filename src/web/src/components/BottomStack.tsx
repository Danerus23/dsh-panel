// НИЖНИЙ СТЕК ЭКРАНА СЕССИИ (D11 §1.1): одна `fixed`-поверхность у низа, в которой живут
// вопрос (W10) → очередь (W12) → зацеп шторки ввода (W11). Порядок задаёт РАЗМЕТКА, а не z-index:
// своего слоя внутри стека нет ни у кого, поэтому раскрытие очереди ПОДНИМАЕТ вопрос, а не накрывает.
//
// Почему портал в `body`, а не последний ребёнок `<main>`: поднятый лист ввода делает `<main>`
// инертным (`inert`), а стек обязан остаться живым — он и есть свёрнутое состояние ввода. Плюс
// `position: fixed` внутри прокручиваемой страницы считается по её координатам; в `body` — по окну.
// ⚠️ Оборотная сторона портала (найдено при W10): `inert` на `<main>` стек НЕ накрывает, а с W10
// в нём живёт ФОРМА вопроса — под скримом она оставалась бы в дереве доступности. Поэтому, пока
// лист поднят, экран сессии ставит `inert` и на сам стек (`inert` ниже); лист — отдельный портал.
//
// Ширина (D16, 13.11.2026): поверхность живёт в px, текст — в `ch`: колонка страницы — min(vw, 720px),
// поэтому карточки стека (вопрос, очередь) получают `max-width: 720px; margin-inline: auto`, а зацеп
// и лист тянутся до 720 px и выше центруются (на телефоне — во всю ширину, как было); текстовые
// блоки внутри держат `max-width: 60ch`. Media queries нет — ширину пересчитывает сам CSS.
//
// Сам стек — `.dp-bottom`: `pointer-events: none`, чтобы его отбивка и пустые места не ели нажатия по
// ленте; органы включают события себе обратно. Высоту стека измеряет `useBottomReserve` и пишет в
// `--dp-bottom-reserve` — по ней живут `scroll-padding`, отступ страницы, пара «вверх/вниз» и
// допуск автоскролла (D11 §1.2).

import { createPortal } from "react-dom";
import type { ReactNode } from "react";

export type BottomStackProps = {
  children: ReactNode;
  /**
   * Поднятый лист ввода запирает и СТЕК: он портал в `body`, и `inert` на `<main>` его не накрывает,
   * а в стеке с W10 живёт форма вопроса. `false`/`undefined` — стек живой (обычное состояние).
   */
  inert?: boolean;
};

export function BottomStack({ children, inert = false }: BottomStackProps) {
  return createPortal(
    <div className="dp-bottom" inert={inert}>
      {children}
    </div>,
    document.body,
  );
}
