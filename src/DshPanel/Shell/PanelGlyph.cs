using Avalonia.Media;

namespace DshPanel.Shell;

/// <summary>
/// ЗНАЧКИ РАЗДЕЛОВ НАСТРОЕК — векторная геометрия, без картинок, шрифтовых значков и чужих пакетов.
///
/// Зачем вообще. Решение владельца 27.09.2026 (шаг 2 вида, «стиль как в harness»): у каждого
/// раздела списка слева — СВОЙ ЗНАЧОК, а выбранный раздел — скруглённая подложка, а не только
/// полужирная подпись. Список из четырёх слов читается медленно: глаз ищет строку по форме,
/// а не по буквам.
///
/// **Почему геометрия, а не файл.** Значок окна уже лежит в сборке картинкой
/// (<see cref="PanelIcon"/>), и второй такой путь завёл бы вторую опечатку в адресе ресурса,
/// второй размер и вторую тему. Здесь формы описаны данными пути (<see cref="Geometry.Parse"/>):
/// они ЧЁРНО-БЕЛЫЕ по определению — краску даёт тема через <c>Foreground</c> значка
/// (<c>Views\SettingsWindow.axaml.cs</c>), поэтому и в светлой, и в тёмной теме значки выглядят
/// правильно сами.
///
/// ⚠️ **Значок — украшение, а не смысл.** Он ничего не сообщает, чего нет в подписи рядом:
/// раздел, у которого значка нет, всё равно остаётся читаемым. Поэтому неизвестный номер даёт
/// ЗНАЧОК ПО УМОЛЧАНИЮ, а не пустое место и не исключение: список разделов у панели растёт,
/// и «пятый раздел уронил окно» — недопустимая цена за картинку.
/// </summary>
public static class PanelGlyph
{
    /// <summary>
    /// Данные значков в порядке разделов: 0 — «Общее», 1 — «Резервное копирование»,
    /// 2 — «Баланс и тариф», 3 — «Сервер», 4 — «Обновление».
    ///
    /// Сетка у всех общая — 16×16, как размер значка в списке; формы простые и узнаваемые:
    /// полоски-регуляторы, коробка-архив, столбики-график, стойки-сервер, стрелка вниз
    /// в подставку. Ни одной картинки
    /// и ни одного шрифтового значка: файл рядом с панелью не лежит (панель раздаётся одним exe),
    /// а шрифтовой значок зависит от шрифта и на чужой машине окажется пустым квадратом.
    /// </summary>
    public static IReadOnlyList<string> SectionPaths { get; } = new[]
    {
        // «Общее» — три полоски-регулятора: у каждой пропуск там, где стоит бегунок.
        "M1,3 H6 V5 H1 Z M8,3 H15 V5 H8 Z " +
        "M1,7 H10 V9 H1 Z M12,7 H15 V9 H12 Z " +
        "M1,11 H4 V13 H1 Z M6,11 H15 V13 H6 Z",

        // «Резервное копирование» — коробка-архив: крышка, ящик и ручка замка.
        "M1,3 H15 V6 H1 Z M2.5,6 H13.5 V14.5 H2.5 Z M6,8 H10 V10 H6 Z",

        // «Баланс и тариф» — столбики-график: три столбца разной высоты на общей подставке.
        "M1,14.5 H15 V16 H1 Z M2,9 H5 V13.5 H2 Z M6.5,4 H9.5 V13.5 H6.5 Z M11,6.5 H14 V13.5 H11 Z",

        // «Сервер» — стойки: два блока и полка под ними.
        "M1,2 H15 V7 H1 Z M1,9 H15 V14 H1 Z M3,4 H5 V5 H3 Z M3,11 H5 V12 H3 Z",

        // «Обновление» — новая версия приходит и встаёт на место: стрелка вниз в подставку.
        // Ни одной буквы и ни одного завитка: значок читается и в 16 точках, как остальные четыре
        // (решение владельца 28.09.2026 — обновление стало разделом, а не кнопкой-дверью).
        "M7,1 H9 V7 H12 L8,11 L4,7 H7 Z M4,12 H12 V14 H4 Z",
    };

    /// <summary>
    /// Значки разделов: по одному на раздел, в порядке списка настроек. Готовые объекты, а не
    /// «разобрать строку при каждом показе»: список перестраивается при каждом открытии окна,
    /// и разбор одних и тех же путей каждый раз — работа впустую.
    /// </summary>
    /// <remarks>
    /// ⚠️ **Значки разбираются ПРИ ПЕРВОМ ПОКАЗЕ, а не при загрузке типа.** Разбор пути спрашивает
    /// у каркаса его графическую часть (<c>IPlatformRenderInterface</c>), а та существует только
    /// у работающего приложения Avalonia. Разбор в статическом поле уронил бы ВЕСЬ тип
    /// (<c>TypeInitializationException</c> на каждом следующем обращении) — и уронил бы по причине,
    /// к значкам не относящейся: окно без графической части падало бы из-за картинки.
    /// </remarks>
    public static IReadOnlyList<Geometry> Sections
    {
        get
        {
            var all = new Geometry[SectionPaths.Count];

            for (var index = 0; index < all.Length; index++) all[index] = Section(index);

            return all;
        }
    }

    /// <summary>Разобранные значки: по одному на раздел (пусто — ещё не разбирали).</summary>
    private static readonly Geometry?[] Cache = new Geometry?[SectionPaths.Count];

    /// <summary>
    /// Значок раздела по его номеру. Номер вне списка — значок первого раздела (см. оговорку
    /// в описании класса): список разделов растёт, а окно падать из-за картинки не должно.
    /// </summary>
    public static Geometry Section(int index)
    {
        var at = index >= 0 && index < SectionPaths.Count ? index : 0;

        return Cache[at] ??= Geometry.Parse(SectionPaths[at]);
    }

    // ------------------------------------------------------------------ значки кнопок

    /// <summary>
    /// ЗНАЧКИ КНОПОК ГЛАВНОГО ОКНА (запрос владельца 28.09.2026: *«Можно ли на кнопках основного
    /// окна как то приукрасить? Может значки какие то предложишь»*).
    ///
    /// Та же сетка 16×16 и тот же способ, что у разделов настроек: данные пути разбираются при
    /// первом показе, ни картинки, ни шрифтового значка. Формы выбраны так, чтобы читались
    /// в 16 точках и не спорили со словом рядом:
    /// <list type="bullet">
    /// <item><description><see cref="Play"/> — «Запустить»: треугольник;</description></item>
    /// <item><description><see cref="Stop"/> — «Остановить»: квадрат;</description></item>
    /// <item><description><see cref="Circle"/> — «Перезапустить» и «Обновить баланс»: круговая
    /// стрелка, то есть «сделать заново»;</description></item>
    /// <item><description><see cref="External"/> — «Открыть панель»: стрелка из рамки, то есть
    /// «наружу, в браузер».</description></item>
    /// </list>
    /// </summary>
    private static readonly Geometry?[] ButtonCache = new Geometry?[5];

    /// <summary>«Запустить» — треугольник воспроизведения.</summary>
    public static Geometry Play => Cached(0, "M3,2 L14,8 L3,14 Z");

    /// <summary>«Остановить» — квадрат.</summary>
    public static Geometry Stop => Cached(1, "M3.5,3.5 H12.5 V12.5 H3.5 Z");

    /// <summary>
    /// «Перезапустить» — ДВА ЗНАКА РЯДОМ: треугольник запуска и квадрат остановки. Так эта кнопка
    /// и устроена («ровно эти два действия подряд»), а круговая стрелка у неё была бы неотличима
    /// от «Обновить баланс» — проверка `Значки_разных_действий_различаются` поймала это на первом
    /// же прогоне.
    /// </summary>
    public static Geometry Restart => Cached(
        4,
        "M2,3 L7,8 L2,13 Z M9,3 H14 V13 H9 Z");

    /// <summary>«Обновить баланс» — круговая стрелка: «сделать заново».</summary>
    public static Geometry Circle => Cached(
        2,
        "M12.5,4.6 A6,6 0 1 0 14,8 H11.6 A3.7,3.7 0 1 1 10.6,5.8 V2.6 L15,5.4 L10.6,8.2 Z");

    /// <summary>«Открыть панель» — стрелка из рамки: открыть в браузере, то есть наружу.</summary>
    public static Geometry External => Cached(
        3,
        "M9,1.5 H14.5 V7 H12.5 V5 L8,9.5 L6.5,8 L11,3.5 H9 Z M2,5 H6 V7 H4 V12 H9 V10 H11 V14 H2 Z");

    private static Geometry Cached(int slot, string path) =>
        ButtonCache[slot] ??= Geometry.Parse(path);
}
