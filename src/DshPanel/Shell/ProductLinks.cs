using System;

namespace DshPanel.Shell;

/// <summary>
/// Ссылки продукта: поддержка проекта и (пока пустая) страница репозитория 2.0.
///
/// Взято у панели v1 (<c>dsh-tray\AppLinks.cs</c>) вместе с её правилом: **пустой адрес —
/// это «возможности нет»**. Строка ссылки в окне тогда исчезает совсем: лучше ничего, чем
/// кнопка, ведущая в никуда. Показывать ли строку, решает <see cref="ShouldShow"/>, и это
/// ЧИСТЫЙ предикат — его проверяют тесты, им пользуется окно.
///
/// Класс НИЧЕГО не показывает: <see cref="Open"/> возвращает текст ошибки или пустую строку,
/// а показывает её то окно, из которого человек щёлкнул. Так «ссылка не открылась» не
/// превращается в модальное окно поверх окна.
/// </summary>
public static class ProductLinks
{
    /// <summary>
    /// Ссылка на страницу поддержки — та же, что была в панели 1.x; владелец подтвердил её
    /// для 2.0 (решение 26.09.2026). Меняешь адрес — поправь его и в описании выпуска.
    /// </summary>
    public const string DonateUrl = "https://app.lava.top/3686297587";

    /// <summary>
    /// Страница репозитория 2.0. **Заполнена 29.09.2026 при выпуске** — ровно так, как и было
    /// задумано (26.09.2026 адрес был пуст: репозиторий закрыт, вести человека некуда, и строка
    /// «Исходники и выпуски на GitHub» просто не показывалась — лучше ничего, чем кнопка в никуда).
    ///
    /// Адрес — ПУБЛИЧНЫЙ <c>Danerus23/dsh-panel</c>: он же отдаёт выпуски
    /// (<see cref="ReleasesRepository"/>) и принимает отчёты о проблеме
    /// (<see cref="IssuesNewUrl"/>). Один репозиторий на всё — иначе человек уходил бы за
    /// исходниками в одно место, а за обновлениями в другое.
    /// </summary>
    public const string RepositoryUrl = "https://github.com/" + ReleasesRepository;

    /// <summary>
    /// ПУБЛИЧНЫЙ репозиторий, у которого панель спрашивает выпуски, — <c>Danerus23/dsh-panel</c>.
    ///
    /// ⚠️ **Это НЕ репозиторий 2.0** (<see cref="RepositoryUrl"/> — про него, и он пока пуст).
    /// Решение владельца: панель проверяет выпуски ПУБЛИЧНОГО репозитория — того самого, где
    /// лежит работающая панель 1.x и куда придёт выпуск 2.0. Репозиторий 2.0 остаётся приватным,
    /// поэтому адрес выпусков берётся у публичного и живёт здесь, рядом с остальными адресами
    /// продукта: **адрес — не строка внутри клиента**, иначе смена репозитория искалась бы
    /// в коде сетевого запроса.
    /// </summary>
    public const string ReleasesRepository = "Danerus23/dsh-panel";

    /// <summary>
    /// Адрес последнего выпуска — тот, куда ходит <c>Update\HttpUpdateClient</c>.
    /// Один на панель: второй такой адрес однажды разошёлся бы с первым.
    /// </summary>
    public const string ReleasesApiUrl =
        "https://api.github.com/repos/" + ReleasesRepository + "/releases/latest";

    /// <summary>
    /// Переменная окружения, которой ПОДМЕНЯЮТ адрес выпусков. Приём взят у панели 1.x
    /// (<c>DSH_PANEL_API</c>) — и он не украшение: без рычага **лабораторный прогон самообновления
    /// невозможен**. Прогон идёт на копии панели с подставным выпуском на местной заглушке, и без
    /// подмены адреса панель пошла бы в настоящий GitHub и увидела там настоящий выпуск — то есть
    /// прогон стал бы либо бессмысленным, либо опасным (`docs\LAB-UPDATE.md` §1).
    /// </summary>
    public const string UpdateApiVariable = "DSH_PANEL_UPDATE_API";

    /// <summary>
    /// Адрес выпусков, которым пользуется панель СЕЙЧАС: значение <see cref="UpdateApiVariable"/>,
    /// если оно задано, иначе <see cref="ReleasesApiUrl"/>.
    ///
    /// ⚠️ **Читается ОДИН раз и в одном месте** — здесь, рядом с прочими адресами продукта.
    /// В клиенте адреса нет: иначе подмена искалась бы в коде сетевого запроса, а второй способ
    /// узнать адрес однажды разошёлся бы с первым.
    ///
    /// ⚠️ **Пустое значение переменной — это «не задана», а не «адреса нет»**: так же устроена
    /// <see cref="Donate"/>. Иначе пустая переменная молча выключила бы проверку обновлений.
    /// </summary>
    public static string UpdateApi =>
        Environment.GetEnvironmentVariable(UpdateApiVariable) is { } custom
        && !string.IsNullOrWhiteSpace(custom)
            ? custom.Trim()
            : ReleasesApiUrl;

    /// <summary>
    /// ЧЕЛОВЕЧЕСКАЯ страница выпусков — её показывают человеку. Отдельно от адреса API
    /// намеренно: <c>api.github.com</c> отдаёт JSON, и открывать его в браузере человеку незачем.
    /// </summary>
    public const string ReleasesPageUrl =
        "https://github.com/" + ReleasesRepository + "/releases";

    /// <summary>
    /// Страница НОВОГО отчёта о проблеме с заполненным текстом. Требование владельца 29.09.2026
    /// («блок issue в окне „О программе“», `DESIGN.md` п. 38).
    ///
    /// ⚠️ Адрес собирается из ТОГО ЖЕ имени репозитория, что и выпуски, и это не мелочь:
    /// отчёт о проблеме обязан идти туда, откуда панель обновляется, — иначе человек написал бы
    /// в один репозиторий, а обновления получал из другого. Второго имени здесь не будет.
    ///
    /// ⚠️ **Панель сама по этому адресу НЕ ходит.** Он открывается в браузере по щелчку человека
    /// (тем же путём, что «Открыть агента» и страница выпусков): панель не отправляет отчёт ни по
    /// API, ни молча — только показывает текст и открывает страницу по просьбе.
    /// </summary>
    public const string IssuesNewUrl =
        "https://github.com/" + ReleasesRepository + "/issues/new";

    /// <summary>
    /// Имя, которым панель представляется GitHub. Без <c>User-Agent</c> GitHub отвечает 403
    /// на любой запрос, поэтому он обязателен, а не желателен.
    /// </summary>
    public const string UserAgent = "DshPanel";

    /// <summary>
    /// Переменная окружения, которой подменяют адрес донатов. Приём взят у v1: так проверяют,
    /// что ссылка доехала до окна, не трогая продукт и не открывая браузер у владельца.
    /// </summary>
    public const string DonateVariable = "DSH_PANEL_DONATE";

    /// <summary>
    /// Ссылка на донаты: значение <see cref="DonateVariable"/>, если оно задано, иначе
    /// <see cref="DonateUrl"/>. Пустое значение переменной — это «не задана», а не «ссылки нет»:
    /// иначе пустая переменная молча убрала бы строку из окна.
    /// </summary>
    public static string Donate
    {
        get
        {
            var custom = Environment.GetEnvironmentVariable(DonateVariable);
            return string.IsNullOrWhiteSpace(custom) ? DonateUrl : custom.Trim();
        }
    }

    /// <summary>
    /// Показывать ли строку этой ссылки. Пусто (и пробелы) — не показывать: это «возможности
    /// нет», а не «адрес странный».
    /// </summary>
    public static bool ShouldShow(string? url) => !string.IsNullOrWhiteSpace(url);

    /// <summary>
    /// Открыть ссылку в браузере. Возвращает **текст ошибки или пустую строку** и никогда
    /// не показывает окон сам: окно живёт в окне.
    ///
    /// Пустой адрес — не исключение и не молчание: возвращается <see cref="PanelStrings.AboutNoLink"/>,
    /// то есть человеку есть что прочитать. Ровно этот случай в v1 показывал имя ключа
    /// (<c>about.noLink</c>) вместо объяснения — см. <c>docs\LOCALIZATION.md</c> §4.
    /// </summary>
    public static string Open(string? url)
    {
        if (!ShouldShow(url)) return PanelStrings.AboutNoLink;

        try
        {
            System.Diagnostics.Process.Start(
                new System.Diagnostics.ProcessStartInfo(url!.Trim()) { UseShellExecute = true });
            return string.Empty;
        }
        catch (Exception error)
        {
            // Отдаём причину как есть — вызывающий покажет её строкой состояния.
            return error.Message;
        }
    }
}
