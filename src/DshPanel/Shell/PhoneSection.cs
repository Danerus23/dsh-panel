using DshPanel.Pricing;
using DshPanel.Server;
using DshPanel.Settings;

namespace DshPanel.Shell;

/// <summary>
/// ЧТО ОКНО ЗНАЕТ О ТЕЛЕФОНЕ прямо сейчас: разрешён ли, слушает ли калитка, сколько устройств
/// сопряжено, кто они, когда выпущен код, по какому адресу подключался телефон и когда его видели.
///
/// Отдельной записью, а не десятком доводов, по той же причине, что у <c>UpdateTraces</c>: всё это —
/// один ответ на вопрос «что у меня с телефоном», и по частям он однажды разошёлся бы сам с собой
/// (например «слушает» без «сколько устройств»).
/// </summary>
public sealed record PhoneSectionInfo(
    bool Allowed,
    bool Listening,
    int DeviceCount,
    IReadOnlyList<PhoneDeviceView> Devices,
    bool LiveCode,
    string ConsentText,
    string LastAddress,
    string ChosenAddress,
    string LastSeenText,
    bool EngineLinked = true);

/// <summary>
/// ДВЕРЬ РАЗДЕЛА «ТЕЛЕФОН» В ОКНЕ НАСТРОЕК (этап F1.d).
///
/// **Зачем дверь, а не прямое обращение к калитке.** Ровно по той же причине, что у копий,
/// обновления и сервера: окно не знает ни про файл пропуска, ни про слушатель — оно показывает
/// готовое и просит сделать то, что человек нажал. С дверью проверка подставляет свой ответ
/// и перебирает состояния («калитка слушает» · «телефон разрешён, а калитка закрыта» · «устройств
/// нет» · «есть живой код»), не поднимая ни порта, ни движка, ни файла владельца.
///
/// ⚠️ **Ни одного решения о двери наружу здесь нет.** Годится ли адрес телефону — решает
/// <see cref="NetworkAddresses"/> и <see cref="Server.PhoneDecisions.Suitable"/>; открывается ли
/// калитка — решает право (<c>RunRights.MayOpenPhoneGate</c>) внутри <c>PhoneGate.Start</c>.
/// Дверь только ИСПОЛНЯЕТ то, что человек нажал, и говорит, вышло ли.
/// </summary>
public interface IPhoneSection
{
    /// <summary>Свежий ответ о телефоне — для отрисовки раздела.</summary>
    PhoneSectionInfo PhoneInfo();

    /// <summary>
    /// РАЗРЕШИТЬ ИЛИ ЗАПРЕТИТЬ ТЕЛЕФОН — рубильник.
    ///
    /// Включение записывает <see cref="PanelSettings.PhoneConsentAt"/> («когда разрешил»): сам факт
    /// «включено» на вопрос «когда это решено» не отвечает. **Выключение стирает согласие
    /// и ОТВЯЗЫВАЕТ ВСЕ УСТРОЙСТВА** — иначе выключение ничего бы не значило: старые cookie
    /// продолжали бы пускать, а список «кто подключён» пережил бы запрет. И, если калитка была
    /// открыта, она ГАСНЕТ: выключенный телефон не имеет права держать порт в сети.
    ///
    /// ⚠️ **ВКЛЮЧЕНИЕ КАЛИТКУ НЕ ПОДНИМАЕТ** (уточнение владельца 11.10.2026, живой прогон):
    /// сначала панель обязана поставить узкое правило брандмауэра — иначе Windows задаёт свой
    /// вопрос и открывает ШИРОКИЕ правила (то, что владелец и увидел живьём). Поднимает калитку
    /// отдельное действие — <see cref="StartPhoneGate"/>, и его зовёт окно, когда правило готово.
    ///
    /// Возвращает, записалось ли: сделать вид, что телефон разрешён, значило бы обещать дверь,
    /// которой нет.
    /// </summary>
    bool SetPhoneAllowed(bool allowed);

    /// <summary>
    /// ПОДНЯТЬ КАЛИТКУ — ОТДЕЛЬНЫМ ДЕЙСТВИЕМ, ПОСЛЕ ПРАВИЛА БРАНДМАУЭРА (уточнение владельца
    /// 11.10.2026).
    ///
    /// Возвращает, ВСТАЛА ли она: «телефон разрешён» и «дверь открыта» — разные вещи, и вторая
    /// может не получиться (нет адреса, порт занят, права нет). Калитка при этом уже существует
    /// (владеет ею запуск человеком — <c>RunRights.MayOwnPhoneGate</c>), поэтому щелчок рубильника
    /// поднимает ЕЁ ЖЕ, а не заводит вторую.
    /// </summary>
    bool StartPhoneGate();

    /// <summary>ВЫПУСТИТЬ НОВЫЙ КОД сопряжения. Пусто — выпустить не удалось (калитки нет).</summary>
    string NewPhoneCode();

    /// <summary>ЖИВОЙ КОД, какой уже выпущен. Пусто — живого кода нет; выдумывать его нельзя.</summary>
    string PhoneCode();

    /// <summary>ОТВЯЗАТЬ ОДНО УСТРОЙСТВО по имени. Остальные обязаны остаться в списке.</summary>
    bool ForgetPhoneDevice(string deviceId);

    /// <summary>
    /// ЗАПОМНИТЬ АДРЕС, ВЫБРАННЫЙ ЧЕЛОВЕКОМ, когда подходящих оказалось несколько
    /// (решение владельца: гадать нельзя, выбирает человек). Выбор обязан пережить перезапуск.
    /// </summary>
    bool ChoosePhoneAddress(string address);

    /// <summary>
    /// НАРИСОВАТЬ QR С ЭТОЙ СТРОКОЙ — байтами PNG. Пусто — нарисовать не удалось.
    ///
    /// ⚠️ **Дверь получает ГОТОВУЮ строку и ничего к ней не добавляет** — ни порта, ни схемы,
    /// ни цифр кода сопряжения (код человек вводит руками, решение владельца 10.10.2026).
    /// Строку собирает окно, и собирает её ОДНИМ решением —
    /// <see cref="Server.PhoneDecisions.QrText"/>: `http://` + ровно тот адрес, который раздел
    /// показывает, + `:` + порт калитки, который раздел показывает рядом (решение владельца
    /// 11.10.2026: камера обязана открывать страницу, а не показывать текст).
    ///
    /// Почему дверью, а не прямо в окне: так «нарисован ли QR и что именно в нём» проверяется
    /// БЕЗ библиотеки и без картинок — проверка подставляет свою дверь и запоминает строку.
    /// Настоящая реализация — <see cref="Server.PhoneQr.Png"/> (библиотека QRCoder).
    /// </summary>
    byte[] QrPng(string address);
}

/// <summary>
/// РАЗДЕЛ «ТЕЛЕФОН» В ОКНЕ НАСТРОЕК: рубильник, порт, код, список устройств и выбор адреса.
///
/// **Зачем отдельным классом, а не прямо в `App`.** Здесь живут ЧЕТЫРЕ решения, и каждое —
/// с причиной:
///
/// 1. **Включение записывает время согласия**, а выключение его СТИРАЕТ: «включено сейчас»
///    и «когда это было решено» — разные вопросы, и второй нужен человеку словами.
/// 2. **Выключение отвязывает ВСЕ устройства** (пропуск забывается целиком). Иначе выключение
///    ничего бы не значило: подписи считаются от пропуска, и без его смены старые cookie
///    продолжали бы пускать — то есть «выключил» было бы неправдой.
/// 3. **Выключение гасит открытую калитку** (<see cref="PhoneGate.Stop"/>): выключенный телефон
///    не имеет права держать порт в сети владельца.
/// 4. **Адрес запоминается отдельным полем** (<see cref="PanelSettings.PhoneChosenAddress"/>),
///    а не тем, где лежит след «по какому адресу приходил телефон»: решение человека
///    и наблюдение панели — разные вещи, и показывать одно как другое значит гадать о нём.
///
/// ⚠️ **Ничего не решается здесь о том, КОМУ можно.** Открывается ли калитка — решает право
/// (`RunRights.MayOpenPhoneGate`) внутри <c>PhoneGate.Start</c>; здесь только исполнение
/// нажатия и честный ответ, вышло ли.
/// </summary>
public sealed class PhoneSection : IPhoneSection
{
    private readonly ISettingsControl _settings;
    private readonly Func<PhoneGate?> _gate;
    private readonly Action<string> _log;
    private readonly Func<DateTimeOffset> _clock;

    /// <summary>
    /// ЧЕМ РИСУЕТСЯ QR. По умолчанию — <see cref="Server.PhoneQr.Png"/>: библиотека QRCoder,
    /// лицензия MIT, в сеть не ходит (решение владельца 11.10.2026: QR — маленькой библиотекой,
    /// а не своим генератором).
    ///
    /// ⚠️ Доводом, а не вызовом по месту, ровно затем, чтобы «нарисован ли QR и **что именно**
    /// в нём закодировано» проверялось без библиотеки и без картинок: проверка подставляет
    /// свою дверь, запоминает строку и отвечает непустыми байтами. Без двери такое утверждение
    /// пришлось бы доказывать расшифровкой PNG.
    /// </summary>
    private readonly Func<string, byte[]> _qr;

    public PhoneSection(
        ISettingsControl settings,
        Func<PhoneGate?> gate,
        Action<string> log,
        Func<DateTimeOffset>? clock = null,
        Func<string, byte[]>? qr = null)
    {
        _settings = settings ?? throw new ArgumentNullException(nameof(settings));
        _gate = gate ?? throw new ArgumentNullException(nameof(gate));
        _log = log ?? throw new ArgumentNullException(nameof(log));
        _clock = clock ?? (() => DateTimeOffset.Now);
        _qr = qr ?? Server.PhoneQr.Png;
    }

    /// <summary>
    /// ЧТО ОКНО ПОКАЗЫВАЕТ ПРЯМО СЕЙЧАС. Калитки нет (телефон выключен, права нет, прогон
    /// проверки) — «не слушает» и ноль устройств: выдумывать состояние закрытой двери нельзя.
    /// </summary>
    public PhoneSectionInfo PhoneInfo()
    {
        var settings = _settings.Settings;
        var gate = _gate();

        return new PhoneSectionInfo(
            Allowed: settings.PhoneEnabled,
            Listening: gate?.Listening == true,
            DeviceCount: gate?.DeviceCount ?? 0,
            Devices: gate?.Devices ?? Array.Empty<PhoneDeviceView>(),
            LiveCode: gate?.HasLiveCode() == true,
            ConsentText: Pricing.PricingDecisions.CheckedText(settings.PhoneConsentAt),
            LastAddress: settings.PhoneLastAddress,
            ChosenAddress: settings.PhoneChosenAddress,
            LastSeenText: Pricing.PricingDecisions.CheckedText(settings.PhoneLastSeen),
            EngineLinked: gate?.EngineLinked ?? false);
    }

    /// <summary>
    /// РУБИЛЬНИК. Порядок шагов — «сначала закрыть дверь, потом забыть ключи»:
    ///
    /// * **выключаем** — сначала <see cref="PhoneGate.Stop"/> (порт освобождается, подписка
    ///   на события гаснет вместе с дверью), потом отвязка всех устройств, потом запись настроек
    ///   без согласия. Обратный порядок оставил бы окно, в котором устройства уже отвязаны,
    ///   а порт ещё слушает: телефон получил бы отказ, но дверь была бы открыта;
    /// * **включаем** — запись согласия, и ТОЛЬКО она. ⚠️ **Калитка здесь НЕ поднимается**
    ///   (уточнение владельца 11.10.2026, живой прогон): сперва нужно узкое правило брандмауэра,
    ///   иначе Windows задаёт свой вопрос и открывает широкие правила. Поднимает её окно —
    ///   <see cref="StartPhoneGate"/>, когда правило есть.
    ///
    /// Возвращает, записалось ли: в прогоне без права не записывается ничего, и «телефон разрешён»
    /// было бы неправдой.
    /// </summary>
    public bool SetPhoneAllowed(bool allowed)
    {
        var gate = _gate();

        if (!allowed)
        {
            gate?.Stop();

            // Отвязка — ДО записи настроек и до ответа человеку: если файл пропуска не записался,
            // устройства останутся сопряжёнными, и сказать «выключено» значило бы соврать.
            var forgotten = gate?.ForgetAllDevices() ?? false;

            if (gate is not null && !forgotten)
            {
                _log(PanelStrings.PhoneForgetAllFailedLog);
                return false;
            }

            return Write(settings =>
            {
                settings.PhoneEnabled = false;
                settings.PhoneConsentAt = string.Empty;
            });
        }

        return Write(settings =>
        {
            settings.PhoneEnabled = true;
            settings.PhoneConsentAt = Pricing.PricingDecisions.Stamp(_clock());
        });
    }

    /// <summary>
    /// ПОДНЯТЬ КАЛИТКУ — по щелчку человека, когда правило брандмауэра уже стоит (или его
    /// некому поставить: прогон проверки брандмауэром не управляет). Калитка к этому мгновению
    /// УЖЕ существует — владеет ею обычный запуск человеком (<c>RunRights.MayOwnPhoneGate</c>),
    /// и включать телефон можно и при выключенном рубильнике.
    ///
    /// Отказ (нет адреса, порт занят, права нет) НЕ отменяет запись согласия: человек разрешил
    /// телефон, а почему дверь не встала — сказано словами в состоянии раздела.
    /// </summary>
    public bool StartPhoneGate()
    {
        var gate = _gate();

        if (gate is null) return false;

        // «Телефон разрешён» спрашивается у НАСТРОЕК, а не у окна: рубильник мог быть выключен
        // в другом окне, и поднимать калитку по памяти значило бы открыть дверь без согласия.
        if (!_settings.Settings.PhoneEnabled) return false;

        var start = gate.Start();

        if (start is { Opened: false }) _log(start.Text);

        return start.Opened;
    }

    /// <summary>
    /// НОВЫЙ КОД. Пусто — выпустить не удалось: калитки нет вовсе (телефон выключен или права
    /// нет). Выдумать код в этом случае значило бы дать человеку цифры, по которым не пустят.
    /// </summary>
    public string NewPhoneCode() => _gate()?.IssueCode() ?? string.Empty;

    /// <summary>
    /// ЖИВОЙ КОД. Спрашивается у калитки: код живёт в ней и нигде больше — в файле пропуска его
    /// нет и быть не должно (он умирает через пять минут, хранить его незачем).
    /// </summary>
    public string PhoneCode() => _gate()?.CurrentCode() ?? string.Empty;

    /// <summary>ОТВЯЗАТЬ ОДНО УСТРОЙСТВО. Остальные остаются: это и есть смысл поимённой отвязки.</summary>
    public bool ForgetPhoneDevice(string deviceId) => _gate()?.ForgetDevice(deviceId) ?? false;

    /// <summary>
    /// ЗАПОМНИТЬ ВЫБОР ЧЕЛОВЕКА среди нескольких подходящих адресов. Калитка при этом НЕ
    /// перезапускается: адрес, на котором она стоит, — решение человека, принятое при включении,
    /// и менять его под работающим слушателем значило бы гасить связь на ровном месте. Новый
    /// адрес подхватится при следующем запуске калитки, и об этом сказано замечанием в разделе.
    /// </summary>
    public bool ChoosePhoneAddress(string address)
    {
        var text = (address ?? string.Empty).Trim();

        return Write(settings => settings.PhoneChosenAddress = text);
    }

    /// <summary>
    /// QR РОВНО С ЭТОЙ СТРОКОЙ — и ни с чем другим.
    ///
    /// Здесь и живёт правило, названное словами в <see cref="Server.PhoneQr.PanelsQrRule"/>:
    /// строка приходит от окна ТОЙ ЖЕ переменной, какой оно показывает адрес. Дверь её
    /// не досочиняет: ни порта, ни схемы, ни цифр кода сопряжения. Иначе правило перестало бы
    /// быть проверяемым, а в кадр `settings-phone` (он уезжает в README) мог бы попасть
    /// настоящий номер адреса машины — решение владельца 11.10.2026.
    /// </summary>
    public byte[] QrPng(string address) => _qr(address ?? string.Empty) ?? Array.Empty<byte>();

    /// <summary>
    /// ЗАПИСАТЬ ПРАВКУ НАСТРОЕК ЦЕЛИКОМ. Копия берётся у действующих настроек, а не собирается
    /// заново: так решение, принятое в другом окне, не теряется (тот же приём, что у галочек копий).
    /// </summary>
    private bool Write(Action<PanelSettings> change)
    {
        var next = SettingsStore.Clean(_settings.Settings);
        change(next);

        return _settings.Save(next);
    }
}
