using Avalonia.Controls;

namespace DshPanel.Shell;

/// <summary>
/// Окно, которое умеет закрыться МОЛЧА — не спрашивая человека ни о чём.
///
/// Зачем отдельный уговор, а не просто <c>Close()</c>: окно настроек спрашивает про
/// несохранённую правку, когда его закрывают (жалоба владельца, п. 16 `docs\DESIGN.md`).
/// Но панель закрывает ЭТО ЖЕ окно сама при выходе, и вопрос там был бы издевательством:
/// человек уже сказал «Выход». Отличить «человек закрыл окно» от «панель убирает окно»
/// нечем — ни одно свойство окна об этом не говорит, — поэтому разница названа явным уговором.
/// </summary>
public interface IQuietClose
{
    /// <summary>Закрыть окно, не спрашивая ни о чём. Зовётся только самой панелью.</summary>
    void CloseQuietly();
}

/// <summary>
/// Окно панели, у которого есть РАЗДЕЛЫ и которое умеет показать раздел «Обновление».
///
/// Зачем уговор, а не прямое обращение к окну настроек: связка (<see cref="PanelShell"/>) НЕ знает,
/// какое именно окно ей вернёт построитель, — это записано в её же правилах («знает только, что
/// это окно»). Уговор держит это обещание и заодно даёт двери <c>OpenUpdateSection</c> разговор
/// с окном, не называя его класса.
///
/// ⚠️ Номер раздела называет САМО окно: у панели одно место правды о том, какой раздел у него
/// «Обновление» (<c>Views\SettingsWindow.UpdateSection</c>), и второй копии этого числа в связке
/// быть не должно — разойдясь, дверь открывала бы соседний раздел.
/// </summary>
public interface IUpdateSectionWindow
{
    /// <summary>Показать раздел «Обновление». Возвращает номер показанного раздела — для проверок.</summary>
    int ShowUpdateSection();
}

/// <summary>
/// Окно панели, у которого есть РАЗДЕЛЫ и которое умеет показать раздел «О программе» (u14, 2.4.0).
///
/// Зачем отдельный уговор, а не прямое обращение к окну настроек: связка (<see cref="PanelShell"/>)
/// НЕ знает, какое именно окно ей вернёт построитель. До 2.4.0 «О программе» было отдельным окном
/// и открывалось своим слотом; теперь ответ живёт разделом, и дверь меню значка ведёт в настройки
/// — на СЕДЬМОЙ раздел. Номер раздела называет само окно, чтобы в связке не завелась вторая
/// копия этого числа.
/// </summary>
public interface IAboutSectionWindow
{
    /// <summary>Показать раздел «О программе». Возвращает номер показанного раздела — для проверок.</summary>
    int ShowAboutSection();
}

/// <summary>
/// Одно окно на панель: второе не строится, повторная просьба выводит уже открытое на передний план.
///
/// Зачем отдельным классом, а не полем в <see cref="PanelShell"/>: у этого правила есть
/// собственная проверка, а связку со значком в тестах не поднять (значок ставится на рабочий стол
/// владельца). Так правило проверяется без значка, окна и рабочего стола — и проверка может упасть,
/// если предохранитель снять.
/// </summary>
public sealed class SingleWindowSlot
{
    private Window? _window;

    public bool IsOpen => _window is not null;

    /// <summary>
    /// ЧЕМ ПОДНИМАТЬ ОКНО. В жизни — <c>Window.Activate()</c>; шов нужен ровно одному прогону:
    /// z-order в безоконном прогоне не существует (`IsActive` остаётся ложным), и «спутник поднят
    /// над панелью» иначе держалось бы на слове. Проверка О-12 (`Topmost` не ставится) швом
    /// не подменяется: она смотрит свойства окна.
    /// </summary>
    internal Action<Window> Raise { get; set; } = window => window.Activate();

    /// <summary>
    /// ВИДНО ЛИ ОКНО ЧЕЛОВЕКУ. Отличается от <see cref="IsOpen"/>: панель, ушедшая в трей,
    /// ПРЯЧЕТ спутники, не закрывая их (вариант 2 нормы `95-windows.md` §3.2), и слот при этом
    /// продолжает помнить своё окно.
    /// </summary>
    public bool IsVisible => _window?.IsVisible == true;

    /// <summary>
    /// СПРЯТАТЬ ОКНО, НЕ ЗАКРЫВАЯ. Зовётся только связкой при уходе панели в трей; место окна
    /// и введённое в нём не теряются — показ панели вернёт окно (как owned-окна в `О-6`).
    /// </summary>
    public void Hide()
    {
        if (_window is not { IsVisible: true } window) return;

        window.Hide();
    }

    /// <summary>
    /// ПОКАЗАТЬ СПРЯТАННОЕ ОКНО И ПОДНЯТЬ ЕГО. Отдельная дверь нужна обоим случаям: возврату
    /// после показа панели (`О-6`) и повторной просьбе двери, когда окно уже построено,
    /// но спрятано (норма `О-10`: `Activate()` на скрытом окне не показывает ничего).
    /// </summary>
    public void Show()
    {
        if (_window is not { } window) return;

        window.Show();
        Raise(window);
    }

    /// <summary>
    /// Показать окно. Возвращает <c>true</c>, если оно построено этим вызовом, и <c>false</c>,
    /// если на передний план выведено уже открытое: так вызывающий может написать в журнал
    /// правду, а не «открыл» в обоих случаях.
    ///
    /// <paramref name="place"/> — куда поставить только что построенное окно. Отдельным
    /// уговором, а не внутри этого класса, намеренно: место окна считается ОДНИМ решением
    /// (<c>Shell\PanelShell.Place</c> → <c>WindowPlacement.NearPanel</c>) и для всех четырёх
    /// вспомогательных окон сразу, а слот про панель, курсор и экраны не знает ничего и знать
    /// не должен — он про «одно окно на панель».
    ///
    /// ⚠️ Место ставится ТОЛЬКО построенному окну. Уже открытое окно на передний план выводится
    /// там, где человек его оставил: переставлять его на каждый щелчок по двери значило бы
    /// выдёргивать окно из-под руки.
    ///
    /// <paramref name="reveal"/> — что сказать окну ПЕРЕД показом и подъёмом, если дверь ведёт
    /// не просто в окно, а в его раздел (пункт меню значка «Обновление панели…» открывает настройки
    /// на разделе «Обновление», решение владельца 09.10.2026). Уговор отдельный от
    /// <paramref name="place"/> ровно потому, что зовётся в ОБОИХ случаях: окно, которое уже открыто
    /// на другом разделе, обязано переключиться, иначе дверь привела бы человека не туда, куда
    /// обещала.
    /// </summary>
    public bool Open(Func<Window> create, Action<Window>? place = null, Action<Window>? reveal = null)
    {
        ArgumentNullException.ThrowIfNull(create);

        if (_window is not null)
        {
            // Раздел выбирается ДО подъёма: человек должен увидеть окно уже на том разделе,
            // за которым шёл, а не мигнуть чужим и переключиться.
            reveal?.Invoke(_window);

            // ⚠️ СПРЯТАННОЕ ОКНО СНАЧАЛА ПОКАЗЫВАЕТСЯ, И ТОЛЬКО ПОТОМ ПОДНИМАЕТСЯ. Панель,
            // ушедшая в трей, прячет спутники (вариант 2), и `Activate()` на скрытом окне
            // не показал бы НИЧЕГО: «нажимаю „Настройки…“ — ничего не происходит» (норма О-10).
            if (!_window.IsVisible) _window.Show();

            Raise(_window);
            return false;
        }

        var window = create() ?? throw new InvalidOperationException("построитель окон вернул null");

        // Место — ДО показа: окно обязано появиться сразу там, где ему сказано, а не мигнуть
        // в углу по умолчанию Windows и переехать.
        place?.Invoke(window);

        // Раздел — тоже до показа, и по той же причине: окно, показанное на «Общем» и переключённое
        // следом, успело бы мигнуть не тем, за чем его открыли.
        reveal?.Invoke(window);

        // Забываем окно, когда человек его закрыл. Иначе повторное открытие выводило бы
        // на передний план окно, которого уже нет, и настройки перестали бы открываться вовсе.
        window.Closed += (_, _) => _window = null;

        _window = window;
        window.Show();
        Raise(window);
        return true;
    }

    /// <summary>
    /// Закрыть открытое окно. Его отсутствие — не ошибка: закрывать могут и на выходе.
    ///
    /// ⚠️ Окно, которое умеет закрываться молча (<see cref="IQuietClose"/>), закрывается ИМЕННО
    /// молча. Единственный, кто зовёт эту дверь, — выход из панели: там вопрос «сохранить
    /// изменения?» был бы задан человеку, который уже вышел, и держал бы панель незакрытой.
    /// </summary>
    public void Close()
    {
        var window = _window;
        _window = null;

        try
        {
            if (window is IQuietClose quiet) quiet.CloseQuietly();
            else window?.Close();
        }
        catch { /* окно уже закрыто само */ }
    }
}
