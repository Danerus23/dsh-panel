namespace DshPanel.Shell;

/// <summary>
/// УГО́ВОР «РАЗДЕЛ НАСТРОЕК СПРАШИВАЕТ БЛОК ДВИЖКА» (этап E3.2) — как <c>IUpdateSectionWindow</c>
/// у панели: окно только показывает и просит, а работу делает тот, кто эту дверь дал.
///
/// **Зачем отдельно.** Решения блока («что за версии», «что делает главная кнопка», «можно ли
/// ставить непроверенную») уже живут в `Server\EngineUpdateDecisions` и `Server\EngineUpdateFlow`,
/// а путь обновления трогает машину (`Server\EngineUpdateRun` с дверями). Окну нечего об этом
/// знать: ему нужны строки, кнопки и запрет, и всё это здесь — одним уговором.
///
/// ⚠️ **Дверь может молчать** (изолированный прогон, нет подсказок, нет своей папки движка):
/// тогда окно обязано показать это СЛОВАМИ, а не пустые строки, и кнопки не должны делать вид,
/// что работают. Поэтому у двери есть <see cref="Available"/> и <see cref="RefusalKey"/>.
/// </summary>
public interface IEngineUpdateSection
{
    /// <summary>Есть чем обновлять: подсказки прочитаны, рекомендованная версия известна.</summary>
    bool Available { get; }

    /// <summary>Почему нельзя — ключ словаря (пусто, когда можно).</summary>
    string RefusalKey { get; }

    /// <summary>Рекомендуемая (проверенная) версия; пусто — нет.</summary>
    string Recommended { get; }

    /// <summary>
    /// ЧТО СТОИТ СЕЙЧАС — своя версия сервера DSH. Пусто — прочитать не удалось, и окно скажет
    /// это словами: без неё карточка предлагала «обновить» на то же самое (находка владельца
    /// 14.10.2026), а сравнить показанное было не с чем.
    /// </summary>
    string Installed { get; }

    /// <summary>
    /// СЕРВЕР DSH НА МАШИНЕ ЕСТЬ ВООБЩЕ — ОТДЕЛЬНЫЙ ФАКТ, а не <c>Installed.Length &gt; 0</c> (A5 §7).
    ///
    /// **Зачем.** Пустая <see cref="Installed"/> значит и «сервера нет», и «версию не прочитали»,
    /// а это разные состояния: в первом карточка обязана предложить УСТАНОВКУ (иначе дорога
    /// к установке — тупик), во втором — сказать «не прочиталось» и оставить кнопку обновления.
    /// Признак даёт поиск сервера DSH (`OwnEngine.Locate`), а не строка версии.
    /// </summary>
    bool EnginePresent { get; }

    /// <summary>Свежая версия из реестра; пусто — не спрашивали или нет новее.</summary>
    string Fresh { get; }

    /// <summary>Свежая НОВЕЕ рекомендованной — только тогда её и предлагаем отдельной кнопкой.</summary>
    bool FreshIsNewer { get; }

    /// <summary>
    /// МОЖНО ЛИ ПОСТАВИТЬ СВЕЖУЮ: панель ставит движок только **по замку**, а замок снимается
    /// замером с проверенной версии. Нет замка для свежей — отдельная кнопка не работает, и окно
    /// обязано сказать это СЛОВАМИ (иначе панель поставила бы другую версию, а объявила эту).
    /// </summary>
    bool FreshInstallable { get; }

    /// <summary>
    /// СТАВИТЬ: <paramref name="freshWanted"/> = «человек нажал ОТДЕЛЬНУЮ кнопку непроверенной
    /// версии» (главная кнопка всегда идёт с `false`). Отвечает строкой о том, что сделано.
    /// </summary>
    string Run(bool freshWanted);

    /// <summary>Заново спросить версии (после проверки выпусков или после обновления).</summary>
    void Refresh();

    // ---------------------------------------------------------------- ОТКАТ ПО КНОПКЕ (E3.3)

    /// <summary>Вопрос перед обновлением: версия, что прервётся, и что панель сделает.</summary>
    PanelQuestion UpdateQuestion { get; }

    /// <summary>
    /// ВЫЖИМКА ПРО ВЕРСИИ ДВИЖКА — строки для своего прокручиваемого поля (решение владельца
    /// 11.10.2026): заметки из файла подсказок и известные беды. Пусто — окно скажет словами,
    /// что заметок нет, а не покажет пустое поле как «всё хорошо».
    /// </summary>
    IReadOnlyList<string> Notes { get; }

    /// <summary>
    /// АДРЕС ВЫПУСКОВ ДВИЖКА для ссылки в той же строке. Пусто — ссылки нет вовсе.
    /// Открывается **только по щелчку человека**: окно зовёт дверь браузера, панель сама не ходит.
    /// </summary>
    string ReleasesAddress { get; }

    /// <summary>Есть куда возвращаться: прежняя версия, которую ставила панель, лежит на диске.</summary>
    bool RollbackAvailable { get; }

    /// <summary>Куда вернёмся — версия; пусто, когда возвращаться некуда (ею подписана кнопка).</summary>
    string RollbackTarget { get; }

    /// <summary>Вопрос перед откатом: **последствие для сессий названо словами** (требование владельца).</summary>
    PanelQuestion RollbackQuestion { get; }

    /// <summary>
    /// ВЕРНУТЬСЯ К ПРЕЖНЕЙ ВЕРСИИ. Отвечает последней строкой пути — тем, чем кончилось; отказ
    /// «возвращаться некуда» машину не трогает вовсе.
    /// </summary>
    string Rollback();
}
