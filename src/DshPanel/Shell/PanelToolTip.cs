using Avalonia.Controls;

namespace DshPanel.Shell;

/// <summary>
/// Подсказка кнопки — ОДНИМ движением и по одной мерке на всю панель.
///
/// Решение владельца 27.09.2026 (шаг 1 «живости вида»): подсказка обязана быть у каждой кнопки
/// каждого окна панели — что произойдёт по нажатию и, где кнопка бывает недоступна, почему она
/// недоступна. Сами слова живут в словарях (<see cref="PanelStrings"/>); здесь — только способ
/// их показать, один на все окна: задержка, поведение у недоступной кнопки и требование
/// не ставить пустую подсказку.
///
/// ⚠️ **Недоступная кнопка без этого показывала бы подсказку НИКОГДА.** У каркаса подсказка
/// у недоступного органа выключена по умолчанию (<c>ShowOnDisabled = false</c>), а именно там
/// она и нужнее всего: человек видит серую кнопку и не понимает, чего ждёт панель. Поэтому
/// <see cref="Set"/> включает её всегда, а не «где понадобится».
///
/// ⚠️ **Пустая подсказка — не «подсказки нет», а дефект**: кнопка без объяснения. Такую строку
/// <see cref="Set"/> не ставит вовсе, чтобы её было видно проверке (`ButtonTooltipTests`),
/// а не человеку — вместо имени ключа в окне.
/// </summary>
public static class PanelToolTip
{
    /// <summary>
    /// Через сколько миллисекунд после наведения показывать подсказку. Одно число на всю панель:
    /// подсказки, появляющиеся с разной задержкой в разных окнах, читаются как разные механизмы.
    /// </summary>
    public const int ShowDelay = 400;

    /// <summary>
    /// Поставить подсказку. Пустой текст — не подсказка, а её отсутствие: такой вызов ничего
    /// не ставит (и это видно проверке «у каждой кнопки есть подсказка»).
    /// </summary>
    public static void Set(Control control, string? text)
    {
        if (control is null) return;
        if (string.IsNullOrWhiteSpace(text)) return;

        ToolTip.SetTip(control, text);
        ToolTip.SetShowDelay(control, ShowDelay);

        // Подсказка у НЕДОСТУПНОЙ кнопки — то, ради чего это место и заведено.
        ToolTip.SetShowOnDisabled(control, true);
    }
}
