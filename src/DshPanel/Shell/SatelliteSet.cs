using Avalonia.Controls;

namespace DshPanel.Shell;

/// <summary>
/// СПУТНИКИ ПАНЕЛИ, КОТОРЫЕ ПРЯЧУТСЯ И ВОЗВРАЩАЮТСЯ ВМЕСТЕ С НЕЙ (вариант 2 нормы
/// `95-windows.md` §3.2, решение владельца 22.10.2026).
///
/// **Почему отдельным классом.** Система этого не сделает: владельца (`Window.Owner`) у спутников
/// нет — панель живёт в трее, а владелец обязан быть видимым (`О-1`, `О-15`). Значит «спрятать
/// вместе» и «вернуть вместе» — наша работа, и она обязана проверяться прогоном, а не держаться
/// на двух вызовах внутри связки, которые однажды снимут.
///
/// **Правила, и каждое из случая.**
///
/// 1. **Прячем, а не закрываем.** «Закрыть» у панели значит «спрятать»: человек не выходил.
///    Закрыть настройки с несохранённой правкой значило бы задать вопрос или потерять правку
///    без действия человека.
/// 2. **Возвращаем ТОЛЬКО то, что спрятали сами.** Пока панель была в трее, человек мог закрыть
///    окно — закрытое возвращать нельзя, это было его действие.
/// 3. **Спрятанное окно при повторной просьбе ПОКАЗЫВАЕТСЯ.** `Activate()` на скрытом окне
///    не показывает ничего («нажимаю „Настройки…“ — ничего не происходит», `О-10`); это правило
///    живёт в <see cref="SingleWindowSlot.Open"/> и проверяется отдельно.
/// </summary>
public sealed class SatelliteSet
{
    private readonly SingleWindowSlot[] _slots;
    private readonly List<SingleWindowSlot> _hidden = new();

    public SatelliteSet(params SingleWindowSlot[] slots) =>
        _slots = slots ?? throw new ArgumentNullException(nameof(slots));

    /// <summary>Сколько спутников спрятала панель и ещё не вернула (для журнала и проверок).</summary>
    public int HiddenCount => _hidden.Count;

    /// <summary>
    /// ПАНЕЛЬ УШЛА В ТРЕЙ — спрятать все видимые спутники и запомнить их. Возвращает число
    /// спрятанных: по нему связка пишет строку в журнал, а прогон отличает «спрятали» от «нечего».
    /// </summary>
    public int HideAll()
    {
        _hidden.Clear();

        foreach (var slot in _slots)
        {
            if (!slot.IsVisible) continue;

            slot.Hide();
            _hidden.Add(slot);
        }

        return _hidden.Count;
    }

    /// <summary>
    /// ПАНЕЛЬ ПОКАЗАЛАСЬ — вернуть спрятанное ею. Возвращает число возвращённых.
    ///
    /// ⚠️ Окно, закрытое человеком, пока панель была в трее, в списке не окажется: слот помнит
    /// закрытие сам, и второго учёта «какие окна открыты» здесь не заводится.
    /// </summary>
    public int Restore()
    {
        if (_hidden.Count == 0) return 0;

        var restored = 0;

        foreach (var slot in _hidden)
        {
            if (!slot.IsOpen) continue;

            slot.Show();
            restored++;
        }

        _hidden.Clear();
        return restored;
    }
}
