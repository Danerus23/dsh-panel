namespace DshPanel.Shell;

/// <summary>
/// ВОПРОС ЧЕЛОВЕКУ, который окно показывает перед важной магией (этап E3.2/E3.3): заголовок,
/// текст вопроса, подписи обеих кнопок и их подсказки.
///
/// **Зачем отдельной записью, а не строкой.** Вопрос — это разговор, и у него есть не только текст:
/// «да» при обновлении значит «останови наш движок и поставь версию», а «да» при откате — «верни
/// прежнюю, и сессии новой версии старый движок не откроет». Собрать это одним текстом значило бы
/// где-то потерять подписи или подсказки — ровно на том месте, где ошибаться дороже всего.
///
/// ⚠️ Слова живут в трёх словарях, а не здесь: тут только то, что показывает окно.
/// </summary>
public sealed record PanelQuestion(
    string Title,
    string Text,
    string Yes,
    string No,
    string TipYes,
    string TipNo);
