namespace DshPanel.Server;

/// <summary>
/// ЧЕМ СТОЯЩАЯ ВЕРСИЯ СЕРВЕРА DSH ОТНОСИТСЯ К РЕКОМЕНДУЕМОЙ (решение владельца 14.10.2026).
///
/// ⚠️ <see cref="Unknown"/> — не «то же самое» и не «новее»: версию не прочитали, и панель обязана
/// сказать это словами, а не показать пустую строку или предложить обновление наугад.
/// </summary>
public enum EngineVersionStanding
{
    /// <summary>
    /// СЕРВЕРА DSH НЕТ ВОВСЕ — отдельный факт присутствия, а НЕ пустая строка версии (A5 §7).
    ///
    /// **Зачем отдельное значение.** Прежде «движка нет» и «версию не прочитали» были одним
    /// <see cref="Unknown"/>, и на чистой машине карточка говорила «версию прочитать не удалось»
    /// и не показывала НИ ОДНОЙ кнопки — то есть дорога к установке была тупиком ровно у того,
    /// кому она нужнее всего. Признак берётся у поиска сервера DSH (пусто — не нашли), а не у
    /// строки версии: `EngineUpdateNotice.Installed` пуста и когда сервера нет, и когда версию
    /// не прочитали.
    /// </summary>
    Absent,

    /// <summary>Сравнивать не с чем: своя или рекомендуемая версия неизвестна.</summary>
    Unknown,

    /// <summary>Стоит ровно рекомендуемая — обновлять нечего, и кнопки нет.</summary>
    Same,

    /// <summary>Стоит старше рекомендуемой — предлагаем обновление кнопкой.</summary>
    Older,

    /// <summary>Стоит новее рекомендуемой — панель свою версию не понижает (решение владельца).</summary>
    Newer,
}

/// <summary>
/// ЧТО ДЕЛАЕТ КНОПКА В БЛОКЕ ДВИЖКА И ЧТО ДЕЛАЕТ ОТДЕЛЬНАЯ ДВЕРЬ — ЧИСТОЕ РЕШЕНИЕ
/// (решение владельца 10.10.2026, коммиты `6565ac9` и `f09da5d`).
///
/// **Две строки, и они РАЗНЫЕ — это замер, а не вкус.** Реестр npm зовёт свежей `0.2.0-rc.2`
/// (`latest` = `next`), а панель рекомендует проверенную `0.1.5-rc.2`. Замер 18.10.2026 (блок A
/// плана 2.2.0): `latest` = `0.2.0-rc.2`, `next` = `0.2.1-rc.2`, всего 36 версий; поверхность
/// 0.2.x панель теперь знает (77 нужных имён, 7 известных потерь), но версия остаётся
/// **непроверенной** и набора версий для неё нет — поэтому и ставится только отдельным действием.
///
/// **Правило, которое здесь закреплено:** главная кнопка **«Обновить» ставит РЕКОМЕНДУЕМУЮ**
/// (проверенную) версию — и **никогда** непроверенную, даже когда та новее. Непроверенная ставится
/// **только отдельным осознанным действием** (своя кнопка и подтверждение) и **разово**: галочек
/// и «запомнить выбор» здесь нет.
///
/// ⚠️ **Чего здесь нет и почему.** Самого пути обновления (гашение своего движка, скачивание,
/// предохранительная копия профиля) и окна — они пишутся следующими кусками E3.2; здесь только
/// решение «что можно ставить какой кнопкой», поэтому его и проверяют без окна и без сети.
/// </summary>
public static class EngineUpdateDecisions
{
    /// <summary>
    /// РЕКОМЕНДУЕМАЯ ВЕРСИЯ — проверенная запись из файла подсказок (первая по порядку файла).
    /// Пусто — подсказок нет или ни одна версия не проверена: тогда панель **не предлагает
    /// обновление вовсе**, а не берёт «что посвежее».
    /// </summary>
    public static string Recommended(EngineHints? hints)
    {
        if (hints is null) return string.Empty;

        return hints.Versions
            .Where(hint => hint.Verified)
            .Select(hint => hint.Version.Trim())
            .FirstOrDefault(version => version.Length > 0) ?? string.Empty;
    }

    /// <summary>
    /// СВЕЖАЯ ЛИ ВЕРСИЯ НОВЕЕ РЕКОМЕНДУЕМОЙ — С ПРЕДРЕЛИЗНОЙ ЧАСТЬЮ (задача F-1b, слово владельца
    /// 20.10.2026). Сравнение — <see cref="EngineVersionOrder"/>: числа, при равенстве хвост по
    /// SemVer (`0.2.1-rc.3` новее `0.2.1-rc.2`, `0.2.1-alpha.5` младше `0.2.1-rc.2`, `0.2.1` новее
    /// любого своего предрелиза). Прежде здесь стоял `EngineNode.Compare` (он про версии Node и
    /// режет номер до `X.Y.Z`), и `rc.3` против `rc.2` считалось «то же самое» — ложное отрицание
    /// ровно в том сценарии, ради которого правило делалось.
    ///
    /// ⚠️ **Объявление о новой версии так НЕ сравнивает и не должно:** там решение владельца —
    /// «решает проба, а не хвост номера», и для него есть отдельный ответ
    /// <see cref="FreshIsNewerByNumber"/>. Менять его вместе с этим значило бы менять ДРУГОЕ решение.
    /// ⚠️ **Не версия — не «новее»:** обе стороны обязаны разбираться как номер
    /// (<see cref="EngineVersionOrder.IsVersion"/>). Иначе мусорная строка без дефиса выглядела бы
    /// «финальным выпуском» и оказалась бы новее любого rc — успех, выдуманный из опечатки.
    /// </summary>
    public static bool FreshIsNewer(string? fresh, string? recommended) =>
        EngineVersionOrder.IsVersion(fresh)
        && EngineVersionOrder.IsVersion(recommended)
        && EngineVersionOrder.IsNewer(fresh, recommended);

    /// <summary>
    /// НОВЕЕ ЛИ ПО ЧИСЛАМ, БЕЗ ХВОСТА — правило объявления о новой версии движка
    /// (<see cref="EngineUpdateNotice"/>). Отдельное имя, а не «то же сравнение»: у объявления своё
    /// решение владельца («новее здесь значит старшая часть версии больше, а решает всё равно проба,
    /// а не хвост номера»), и оно не меняется вместе с кнопкой непроверенной версии.
    /// </summary>
    public static bool FreshIsNewerByNumber(string? fresh, string? recommended) =>
        EngineVersionOrder.IsNewerByNumber(fresh, recommended);

    /// <summary>
    /// ПОКАЗЫВАТЬ ЛИ КНОПКУ «Поставить непроверенную…» (находка F-1, слово владельца 20.10.2026).
    ///
    /// **От какого случая — скрин владельца.** Стояла `0.2.1-rc.2`, свежая в реестре была ТА ЖЕ
    /// `0.2.1-rc.2`, рекомендованная — `0.1.5-rc.2`. Кнопка была видна и «что-то делала», хотя
    /// ставить было нечего: прежнее правило сравнивало свежую ТОЛЬКО с рекомендуемой и на СТОЯЩУЮ
    /// не смотрело вовсе.
    ///
    /// **Правило:** свежая обязана быть новее и рекомендованной (это <paramref name="freshIsNewer"/> —
    /// готовый ответ двери, он же решает строку про свежую версию), и СТОЯЩЕЙ. Оба сравнения —
    /// ПРАВИЛОМ ПАНЕЛИ С ПРЕДРЕЛИЗНОЙ ЧАСТЬЮ (<see cref="EngineVersionOrder"/>, задача F-1b): поэтому
    /// `0.2.1-rc.3` против стоящей `0.2.1-rc.2` кнопку ПОКАЖЕТ, а `0.2.1-rc.3` против стоящей
    /// `0.2.1` — нет (финальный выпуск выше своего предрелиза).
    /// ⚠️ `EngineNode.Compare` здесь не годится: он нормализует версию до `X.Y.Z` (`22.19` →
    /// `22.19.0`) и хвост `-rc` не видит вовсе — он про версии Node, где хвостов не бывает.
    /// ⚠️ Стоящая не прочитана (пусто) или не разбирается как версия — «новее стоящей» НЕ ДОКАЗАНО,
    /// и кнопки нет: в состоянии «версию прочитать не удалось» остаётся главная кнопка. Разбор
    /// версий — на стороне <see cref="FreshIsNewer"/> (обе стороны обязаны быть версиями). О мусорной
    /// версии служба говорит строкой в журнал (`EngineUpdateFreshUnreadableLogFormat` /
    /// `EngineUpdateInstalledUnreadableLogFormat`), а не молчанием.
    /// </summary>
    public static bool FreshWorthShowing(bool freshIsNewer, string? installed, string? fresh) =>
        freshIsNewer && FreshIsNewer(fresh, installed);

    /// <summary>
    /// ГЛАВНАЯ КНОПКА СТАВИТ СВЕЖУЮ ВЕРСИЮ? **Никогда.** Это не «настройка» и не «пока так»:
    /// одним щелчком «Обновить» непроверенная версия не ставится — иначе человек получил бы
    /// непроверенное дерево, ничего об этом не нажимая.
    /// </summary>
    public static bool MainButtonInstallsFresh => false;

    /// <summary>
    /// ЧЕМ СТОЯЩАЯ ВЕРСИЯ ОТНОСИТСЯ К РЕКОМЕНДУЕМОЙ — из этого решается, что показывает карточка
    /// обновления и нужна ли ей кнопка.
    ///
    /// **От какого случая (владелец, 14.10.2026).** На карточке не было СВОЕЙ версии, и панель
    /// предлагала «Обновить» **на то же самое**: сравнить показанное было не с чем. Теперь три
    /// состояния названы по отдельности, и «обновлять нечего» — одно из них, а не молчание.
    ///
    /// ⚠️ **Понижение — НЕ дело панели.** Стоящая версия новее рекомендуемой — это законное
    /// состояние (человек поставил себе свежую), и панель об этом говорит словами, а не «обновляет»
    /// его назад. Единственный путь назад — откат по кнопке, и он про другое.
    /// </summary>
    /// <param name="enginePresent">
    /// ФАКТ ПРИСУТСТВИЯ сервера DSH на машине (A5 §7): <c>false</c> — поиск не нашёл его вовсе.
    /// Приходит ОТДЕЛЬНЫМ доводом, а не выводится из пустой строки версии: «не нашли» и «не прочитали»
    /// — разные факты, и слитые в один они врут в обе стороны. Умолчание <c>true</c> оставлено
    /// вызывающим, которые про присутствие не знают: они и раньше отвечали только про версии.
    /// </param>
    public static EngineVersionStanding Standing(string? installed, string? recommended, bool enginePresent = true)
    {
        if (!enginePresent) return EngineVersionStanding.Absent;

        if (string.IsNullOrWhiteSpace(installed) || string.IsNullOrWhiteSpace(recommended))
            return EngineVersionStanding.Unknown;

        // С 20.10.2026 (F-1b) сравнение — с предрелизной частью: стоящая `0.2.1-rc.3` против
        // рекомендуемой `0.2.1-rc.2` — это «своя новее», а не «обновлять нечего».
        var order = EngineVersionOrder.Compare(installed, recommended);

        return order switch
        {
            < 0 => EngineVersionStanding.Older,
            0 => EngineVersionStanding.Same,
            _ => EngineVersionStanding.Newer,
        };
    }

    /// <summary>
    /// МОЖНО ЛИ СТАВИТЬ СВЕЖУЮ ОТДЕЛЬНОЙ ДВЕРЬЮ: нужны и свежая, и рекомендованная, и свежая
    /// обязана быть **новее** — «поставить то же самое, только страшнее» не бывает.
    /// </summary>
    public static bool MayInstallFresh(string? fresh, string? recommended) =>
        !string.IsNullOrWhiteSpace(fresh)
        && !string.IsNullOrWhiteSpace(recommended)
        && FreshIsNewer(fresh, recommended);

    /// <summary>
    /// СЛОВА ПОДТВЕРЖДЕНИЯ ЗАВИСЯТ ОТ ТОГО, ЧТО СТАВИМ: непроверенная требует предупреждения
    /// **словами** (в том числе про сессии, журнал v4), рекомендованная — обычной строки.
    /// Здесь только выбор того, какой ключ показывать; сами фразы живут в словарях.
    /// </summary>
    public static string Confirmation(bool fresh) =>
        fresh ? EngineInstallRefusals.FreshUnverifiedWarning : EngineInstallRefusals.RecommendedUpdate;
}
