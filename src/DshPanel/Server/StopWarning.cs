using DshPanel.Isolation;
using DshPanel.Localization;

namespace DshPanel.Server;

/// <summary>
/// ПРЕДУПРЕЖДЕНИЕ ПЕРЕД ГАШЕНИЕМ СЕРВЕРА — одна дверь (решение владельца 10.10.2026:
/// *«Важная магия — с предупреждением»*, и уточнение к нему: *«„гасит свободно“ значит без нового
/// вопроса, а не без предупреждения»*).
///
/// **Что говорится и почему именно это.** Перед гашением панель называет словами **какой** сервер
/// останавливает (порт) и **что из-за этого прервётся**: через такой сервер может идти текущая
/// работа агента. Человек, нажавший «Остановить», иначе узнал бы об этом уже после — а журнал
/// читать он не обязан (то же решение: панель не требует от человека ритуалов).
///
/// **Порядок — часть обещания.** Предупреждение говорится ДО гашения: после него это уже не
/// предупреждение, а отчёт. После гашения идёт своя строка — «сервер остановлен, порт свободен»
/// (она была и раньше).
///
/// ⚠️ **Изолированный прогон молчит об этом, как и о любом своём сообщении** — дверь
/// <see cref="IsolationRules.ShouldNotify"/> стоит в одном месте (там, где сообщение показывается),
/// и вторых ворот здесь нет: иначе однажды разошлись бы. В журнал строка уходит всегда — журнал
/// прогона читает агент, а не человек.
/// </summary>
public static class StopWarning
{
    /// <summary>Слова предупреждения: свой сервер или взятый под управление — и порт.</summary>
    public static string Words(bool own, int port) =>
        own
            ? Loc.T("ServerStopWarningOwnFormat", port)
            : Loc.T("ServerStopWarningAdoptedFormat", port);

    /// <summary>
    /// СКАЗАТЬ ПЕРЕД ГАШЕНИЕМ: строка в журнал — всегда, сообщение человеку — если его дали
    /// (<paramref name="notify"/>); показывать или промолчать решает общая дверь изоляции.
    /// </summary>
    public static void Say(Action<string> log, Action<NoticeKind, string, string>? notify, bool own, int port)
    {
        ArgumentNullException.ThrowIfNull(log);

        var text = Words(own, port);

        log(text);
        notify?.Invoke(NoticeKind.ServerStop, Loc.T("NotifyServerStopTitle"), text);
    }
}
