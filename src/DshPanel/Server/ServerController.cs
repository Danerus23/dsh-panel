using System.Diagnostics;
using System.Globalization;
using System.Text;
using DshPanel.Shell;

namespace DshPanel.Server;

/// <summary>
/// То, что нужно окну панели от сервера. Отдельный интерфейс — не украшение: окно проверяется
/// без экрана и без запуска настоящего движка, а для этого ему нужна подмена.
/// </summary>
public interface IServerControl
{
    ServerState State { get; }

    /// <summary>
    /// СОСТОЯНИЕ СЕРВЕРА ПРОЧИТАНО ХОТЬ РАЗ (задание владельца 14.10.2026, §1).
    ///
    /// **От какого случая.** В первые мгновения после запуска панели состояние сервера ещё
    /// не прочитано, и «сервера нет» — это ЕЩЁ НЕ ОТВЕТ, а «не смотрели». Калитка телефона
    /// спрашивала подписку в этот самый миг и писала в журнал «связи с сервером DSH нет — вопрос
    /// агенту телефону показать нечем» про работающий СВОЙ сервер (живой случай владельца
    /// 14.10.2026, 23:53:43). Различать «нет» и «не смотрели» можно только здесь: прочитанность
    /// знает тот, кто читает.
    ///
    /// ⚠️ **Реализация по умолчанию — «прочитано»**: подстановкам сервера в проверках читать
    /// нечего, они отвечают готовым состоянием, и молчаливо-«неизвестное» сделало бы их слепыми.
    /// </summary>
    bool Known => true;

    /// <summary>
    /// СМЕНА СОСТОЯНИЯ СЕРВЕРА — СООБЩЕНИЕ О ДАННЫХ, А НЕ ЧАСЫ (задание владельца 14.10.2026, §3).
    ///
    /// Нужно разделу «Сервер» в настройках: он обязан перерисоваться, когда сервер поднялся или
    /// погас, — иначе строки порта и состояния остаются прежними до нажатия кнопки. Опрос раз
    /// в секунду у главного окна — его дело, здесь сообщение.
    ///
    /// ⚠️ **Реализация по умолчанию МОЛЧИТ**, и это не заглушка «пока»: подстановок сервера
    /// в проверках много, и каждой из них заводить событие незачем — молчащая дверь честно
    /// говорит, что сообщать ей нечего. Тем же способом молчит образцовая дверь обновления
    /// в `Program` (`IUpdateControl`: «подписка принимается и молчит»).
    /// </summary>
    event Action? Changed { add { } remove { } }

    /// <summary>
    /// ПРОЦЕСС СВОЕГО СЕРВЕРА — PID И ВРЕМЯ СТАРТА ОДНОЙ ПАРОЙ (задача F-2, слово владельца
    /// 20.10.2026). Живая проба умений решает по нему «тот же это сервер или новый»: у
    /// перезапущенного сервера те же порт и те же длины ссылок, а процесс другой.
    ///
    /// ⚠️ **Реализация по умолчанию — «процесс не назван»** (<c>null</c>): подстановки сервера
    /// в проверках процесса не имеют, и выдумывать им номер значило бы дать пробе ложный ключ.
    /// Честный <c>null</c> заставляет пробу сказать «процесс неизвестен» словами и взять ключом
    /// ссылку входа — это и есть поведение при неизвестном процессе.
    /// </summary>
    (int Pid, long StartTicks)? OwnProcess() => null;

    /// <summary>Кто поднял сервер, которым управляет панель. Влияет на право гашения.</summary>
    ServerOwner Owner { get; }

    /// <summary>
    /// Согласие человека на ЭТОТ встроенный сервер ЗАПОМНЕНО (порт лежит в настройках панели).
    ///
    /// Решение владельца 26.09.2026: ответ «беру под управление» спрашивается один раз и
    /// запоминается. Запомнено — панель считает окружение своим и гасит сервер свободно;
    /// не запомнено (не спрашивали, или записать не удалось) — спрашивает подтверждение
    /// каждый раз, как раньше.
    /// </summary>
    bool ConsentRemembered { get; }

    /// <summary>Перечитать состояние (кто на порту, отвечает ли сервер).</summary>
    ServerState Refresh();

    /// <summary>Поднять СВОЙ сервер и дождаться, пока он ответит. Возвращает состояние на момент выхода.</summary>
    ServerState Start(TimeSpan timeout);

    /// <summary>
    /// Погасить сервер.
    ///
    /// <paramref name="confirmed"/> обязателен только для встроенного сервера
    /// (<see cref="ServerOwner.Adopted"/>), и только пока согласие не запомнено
    /// (<see cref="ConsentRemembered"/>): его панель не поднимала, через него может идти
    /// текущая работа человека, и подтверждение спрашивается КАЖДЫЙ раз (решение владельца
    /// 24.09.2026). Запомненное согласие — это уже данный один раз ответ «беру под управление»
    /// (решение владельца 26.09.2026), и тогда подтверждения не нужно. Свой сервер панель гасит
    /// и без подтверждения — это её процесс.
    /// </summary>
    ServerState Stop(bool confirmed);

    /// <summary>
    /// Перезапуск: погасить и поднять заново.
    ///
    /// <paramref name="confirmed"/> ОБЯЗАТЕЛЕН и значит ровно то же, что у <see cref="Stop"/>:
    /// у ВСТРОЕННОГО сервера (<see cref="ServerOwner.Adopted"/>) без подтверждения человека и без
    /// запомненного согласия (<see cref="ConsentRemembered"/>) контроллер не гасит чужой процесс —
    /// а значит и перезапускать нечего, и ответ будет тот же, что у неподтверждённой остановки.
    /// Предохранитель стоит ЗДЕСЬ, а не в окне: окно лишь спрашивает по предикату, а решает
    /// контроллер — и решает так же, как при гашении (красная линия 6).
    /// </summary>
    ServerState Restart(TimeSpan timeout, bool confirmed);

    /// <summary>
    /// ПОДНЯТЬ СВОЙ СЕРВЕР ЗАНОВО: погасить работающий DSH, который панель НЕ поднимала,
    /// и поднять на его месте свой (своей ссылкой входа). Решение владельца 13.10.2026.
    ///
    /// <paramref name="confirmed"/> ОБЯЗАТЕЛЕН и спрашивается КАЖДЫЙ раз: гасится чужой процесс,
    /// через который может идти текущая работа человека. Без подтверждения не происходит ничего.
    /// Встроенный сервер (<see cref="ServerOwner.Adopted"/>) этой дорогой не гасится — у него своя
    /// («Отвязаться» и «Остановить»).
    /// </summary>
    ServerState RecoverOwnServer(TimeSpan timeout, bool confirmed);

    /// <summary>
    /// Найти работающие серверы DSH, которые панель НЕ поднимала. Свой сервер и тот, в который
    /// панель уже встроена, в находку не попадают: предлагать встроиться в то, чем уже
    /// управляешь, — это шум. На этой же находке стоит ЗАМОК от второго движка: пока она
    /// не пуста, свой сервер панель не поднимает (см. <c>allowParallelStart</c>).
    /// </summary>
    DiscoveryResult Scan();

    /// <summary>
    /// Взять найденный сервер под управление. Своего сервера при этом НЕ поднимает.
    /// Приметы проверяются заново: между находкой и согласием человека мир мог измениться.
    /// </summary>
    ServerState Adopt(FoundServer found);

    /// <summary>Перестать управлять найденным сервером, НЕ гася его. Отвязались — он живёт дальше.</summary>
    ServerState Detach();

    /// <summary>
    /// ССЫЛКА ВХОДА в панель (в ней ТОКЕН) или пустая строка, если панель её не знает.
    ///
    /// ⚠️ Это СЕКРЕТ: она не показывается человеку ни текстом, ни подсказкой, ни в подписях,
    /// ни в журнале — только уходит в браузер по его щелчку (красная линия 7). Из контроллера
    /// она выходит одним свойством, чтобы второго способа её достать не завелось.
    /// </summary>
    string EntryLink { get; }

    /// <summary>
    /// Похоже ли, что профиль движка достраивается ВПЕРВЫЕ (t15, 18.10.2026). От этого зависит
    /// ОДНА надпись — <c>EngineFirstRun.StartingLabel</c>: обещать «первый запуск достраивает
    /// профиль» на каждом подъёме панель больше не имеет права.
    ///
    /// ⚠️ **Реализация по умолчанию — «не первый»**: подстановки сервера в проверках каталога
    /// движка не знают, и «нечем мерить» обязано давать ЧЕСТНУЮ надпись без обещания, а не
    /// наоборот. Тем же способом молчат <see cref="Known"/> и <see cref="Changed"/>.
    /// </summary>
    bool FirstRunLooks => false;
}

/// <summary>
/// Сервер DSH: поднять, погасить, показать состояние, найти чужой и встроиться в него.
///
/// Устройство простое и намеренно скучное: панель ЗАПОМИНАЕТ дескриптор процесса, который
/// запустила сама, и только его имеет право гасить свободно. Встроенный сервер гасится
/// по подтверждению — но тоже не «по примете из командной строки», а по тому же процессу,
/// который панель увидела в момент встраивания (номер процесса плюс время его создания).
/// И у этого правила есть одно исключение, названное владельцем 26.09.2026: если человек
/// ОДИН РАЗ сказал «беру под управление», ответ запоминается в настройках, и дальше панель
/// считает это окружение своим — берёт сервер сама и гасит свободно.
///
/// Что панель НЕ делает: **не занимает порт владельца без права** (3080 — решение владельца
/// 26.09.2026: обычный запуск человеком его занимает, прогон проверки приводится к 3081),
/// не пишет в его
/// `~/.dsh` (домашний каталог движка приходит снаружи и в изолированном прогоне лежит под корнем),
/// не ставит и не обновляет движок, **не поднимает свой сервер рядом с найденным чужим**
/// (замок от второго движка: данные у них одни и те же, находка 25.09.2026 — право «поднимать
/// рядом» приходит явным параметром и по умолчанию выключено) и не гасит без подтверждения то,
/// что подняла не она, пока согласие не запомнено.
///
/// Встроившись, панель берёт у окружения АДРЕС сервера. Домашний каталог движка (`DSH_HOME`)
/// она по-прежнему берёт из своего окружения: у работающего сервера его нигде не спросить
/// (`docs\ENGINE.md` §11, п. 4). Для обычного запуска человеком это тот же `~/.dsh` — то есть
/// на практике совпадает, но обещать «панель узнала DSH_HOME чужого сервера» нельзя.
/// </summary>
public sealed class ServerController : IServerControl, IDisposable
{
    /// <summary>
    /// Сколько строк вывода движка панель помнит для объяснения неудачи. Держать больше
    /// незачем: человеку нужна последняя причина, а не весь журнал запуска. Число — ОДНО на
    /// кольцевой буфер и на запись о завершении (<see cref="EngineExitReport.TailLines"/>),
    /// иначе запись обещала бы больше строк, чем панель помнит.
    /// </summary>
    private const int RememberedEngineLines = EngineExitReport.TailLines;

    /// <summary>
    /// Как часто панель по-настоящему осматривает порты машины. Опрос состояния идёт раз в секунду,
    /// и полный осмотр на каждом тике был бы тратой: находка не появляется и не исчезает мгновенно.
    /// Отдельная ручка — потому что проверке нужен свежий ответ сейчас же.
    /// </summary>
    public static readonly TimeSpan DefaultScanInterval = TimeSpan.FromSeconds(2);

    /// <summary>Сколько ждать, пока порт действительно освободится после гашения.</summary>
    public static readonly TimeSpan DefaultStopWait = TimeSpan.FromSeconds(20);

    /// <summary>
    /// Сколько раз панель пробует снять УСТАРЕВШУЮ запись о своём сервере, прежде чем сказать
    /// человеку словами. Три — потому что осмотр идёт раз в секунду, а снятие файла может
    /// не удаться из-за мгновенной занятости; бесконечно пробовать нельзя: это и есть тот
    /// «тихий цикл», ради которого предел заведён.
    /// </summary>
    public const int ForgetAttempts = 3;

    /// <summary>Пауза между попытками снять устаревшую запись (осмотр состояния идёт раз в секунду).</summary>
    public static readonly TimeSpan ForgetPause = TimeSpan.FromSeconds(15);

    /// <summary>
    /// Редкий повтор ПОСЛЕ лимита: файл мог освободиться сам. Молча и не чаще раза в пять минут —
    /// слова человеку уже сказаны, а повторять их каждую секунду значит шуметь вместо работы.
    /// </summary>
    public static readonly TimeSpan ForgetSlowRetry = TimeSpan.FromMinutes(5);

    private readonly string _dshHome;
    private readonly Func<string> _workingDirectory;
    private readonly Func<int> _requestedPort;
    private readonly Action<string> _log;
    private readonly Func<DshEngine?> _locateEngine;
    private readonly IProcessKiller _killer;

    /// <summary>Сообщение человеку: предупреждение перед гашением (решение владельца 10.10.2026).</summary>
    private readonly Action<Isolation.NoticeKind, string, string>? _notify;
    private readonly ServerProbe _probe;
    private readonly TimeSpan _stopWait;
    private readonly TimeSpan _scanInterval;
    private readonly Func<int>? _readAdoptedPort;
    private readonly Action<int>? _rememberAdoptedPort;
    private readonly bool _allowParallelStart;
    private readonly bool _mayOccupyOwnerPort;

    /// <summary>
    /// Право убрать МЁРТВЫЙ замок движка (<see cref="RunRights.MayClearEngineLocks"/>): это
    /// удаление чужого файла в доме движка.
    ///
    /// Умолчание — <c>false</c>, и это БЕЗОПАСНАЯ сторона, ровно как у <c>allowParallelStart</c>
    /// (тоже право, тоже с умолчанием «замок включён»): забыть выдать право значит «не убирать
    /// ничего» — человек увидит названный замок и уберёт его сам, — а вот забыть запретить было бы
    /// удалением чужого файла. Выдаёт право <c>App.StartPanel</c>, и только обычному запуску
    /// человеком или изолированному прогону (<see cref="RunRights.MayClearEngineLocks"/>).
    /// </summary>
    private readonly bool _mayClearEngineLocks;
    private readonly ServerStateFiles _files;

    /// <summary>
    /// ГДЕ ЛЕЖИТ СВОЙ ДВИЖОК ПАНЕЛИ (<c>&lt;корень панели&gt;\engine</c>) — третья примета владения
    /// (этап E3): по ней панель узнаёт свой сервер **по пути запуска**, а разведка помечает находку
    /// «наш движок (версия)».
    ///
    /// ⚠️ **Почему отдельным доводом, а не через файлы состояния.** Прежде путь шёл в
    /// <see cref="ServerStateFiles.OwnEngineDir"/> — и это было неверно: файлы состояния дают
    /// **право читать и писать** данные панели, а путь к своей папке движка правом не является
    /// (это не секрет и не чужие данные). Из-за смешения съёмка, которой файлы состояния не выдаются
    /// вовсе, не могла показать пометку «наш движок» — и кадр врал: два сервера выглядели
    /// одинаково чужими. Пусто — приметы нет, и находки остаются «чужими».
    /// </summary>
    private readonly Func<string> _ownEngineDir;

    /// <summary>
    /// Каким движком панель подняла СВОЙ сервер (путь к <c>bin.js</c>).
    ///
    /// Живёт в памяти ровно для одной записи: <c>state\own-server.txt</c> обязана называть движок
    /// и его версию (этап E3). Из памяти, а не из повторного поиска: поиск находит движок **человека**
    /// (глобальную установку), а свой — тот, которым панель только что запустила процесс.
    /// </summary>
    private string _ownEnginePath = string.Empty;
    private readonly Func<string>? _readFoundServerLink;
    private readonly Func<string, LinkProbe> _linkProbe;

    /// <summary>
    /// Часы панели. Нужны ровно для одного: пауза между попытками снять устаревшую запись
    /// о своём сервере. Шов для проверок — иначе предел и паузу пришлось бы ждать в реальном
    /// времени (пятнадцать секунд на каждую проверку).
    /// </summary>
    private readonly Func<DateTimeOffset> _clock;

    private readonly object _gate = new();
    private readonly object _scanGate = new();
    private readonly Queue<string> _engineTail = new();

    private Process? _process;
    private string _lastEngineLine = string.Empty;
    private bool _exitReported;

    /// <summary>
    /// ДЕСКРИПТОР СЕРВЕРА, ПРИНЯТОГО ПО ЗАПИСИ (DEF-057).
    ///
    /// **От какого случая.** После перезапуска панели свой сервер узнаётся по записи
    /// <c>state\own-server.txt</c>, и процесса, который панель запускала САМА, у неё уже нет.
    /// Сторож падения был подписан только на <see cref="_process"/>, поэтому внешнее убийство
    /// давало один ответ опроса «сервер не запущен»: ни шарика, ни строки журнала, ни кода выхода
    /// (журнал владельца 24.10.2026, 12:20:16 и 12:30:50).
    ///
    /// **Что это за объект.** Обычный <see cref="Process"/>, открытый по номеру принятого сервера
    /// (<see cref="Process.GetProcessById"/>) с включёнными сообщениями о выходе
    /// (<see cref="Process.EnableRaisingEvents"/>). Он живёт отдельно от <see cref="_process"/>
    /// намеренно: <see cref="_process"/> — процесс, который панель ПОДНЯЛА, и его гасят иначе
    /// (своим <c>Kill</c>), а принятый гасится по записи через <see cref="IProcessKiller"/> со сверкой
    /// времени создания. Один флаг на два разных способа гашения — это два разных поведения
    /// в одном поле.
    ///
    /// **Права могут не дать.** Тогда дескриптора нет, и выход замечается опросом порта
    /// (<see cref="ForgetRecordedOwnWithoutHandle"/>): честно «код неизвестен», а не выдуманный ноль.
    /// Это не падение панели.
    /// </summary>
    private Process? _watched;

    /// <summary>Номер и время создания процесса под наблюдением: нужны отчёту о выходе (DEF-057).</summary>
    private int _watchedPid;
    private long _watchedStartTicks;

    /// <summary>
    /// О ВЫХОДЕ ПРИНЯТОГО СЕРВЕРА УЖЕ СКАЗАНО — РОВНО ОДИН РАЗ (DEF-057).
    ///
    /// **Зачем отдельный флаг.** Детекторов ДВА: сообщение <see cref="Process.Exited"/> (приходит
    /// своей ниткой, когда система его доставит) и опрос в <see cref="Refresh"/> (смотрит факт
    /// `HasExited`). Оба ведут в одно место (<see cref="ReportRecordedOwnExit"/>), и оба идут под
    /// <see cref="_gate"/>: флаг здесь и есть та единственная правда, по которой второй детектор
    /// молчит. Без него одно падение дало бы две строки «завершился САМ» и два шарика.
    ///
    /// Ставится и тогда, когда панель гасит сервер САМА (<see cref="StopWatching"/>): её слово уже
    /// сказано ею («остановлен панелью»), и сторожу здесь говорить нечего.
    /// </summary>
    private bool _watchReported;

    /// <summary>
    /// ИДЁТ ПОПЫТКА СТАРТА — <c>Start</c> выполняется прямо сейчас (DEF-054, 2.4.0).
    ///
    /// **Зачем отдельный флаг, а не «спросить состояние».** <c>Start</c> держит замок контроллера
