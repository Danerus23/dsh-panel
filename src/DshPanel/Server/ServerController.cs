    /// <summary>
    /// ПРОЦЕСС СВОЕГО СЕРВЕРА — PID И ВРЕМЯ СТАРТА ОДНОЙ ПАРОЙ (задача F-2, слово владельца
    /// 20.10.2026). Нужен живой пробе умений: «тот же это сервер или новый» решается ПРОЦЕССОМ,
    /// а не длинами ссылок — у перезапущенного сервера те же порт и те же длины.
    ///
    /// **Откуда.** Из той же записи, которой панель доказывает владение (`state\own-server.txt`):
    /// другого места, где время старта своего сервера записано, у панели нет — состояние сервера
    /// (`ServerState`) знает только номер процесса, а номер переиспользуется.
    ///
    /// **Три условия, все обязательны:** запись есть и разбирается; панель управляет именно СВОИМ
    /// сервером (<see cref="ServerOwner.Panel"/>); записанный номер процесса — тот же, что у нашего
    /// живого (<c>_ownPid</c>). Иначе <c>null</c> — «процесс не назван», и проба обязана сказать это
    /// словами, а не выдать чужую запись за свой процесс.
    /// </summary>
    public (int Pid, long StartTicks)? OwnProcess()
    {
        var saved = OwnServerRecord.Parse(ReadOwnServerFile());
        if (saved is not { } record) return null;

        lock (_gate)
        {
            if (Owner != ServerOwner.Panel || _ownPid <= 0 || record.Pid != _ownPid) return null;
        }

        return (record.Pid, record.StartTicks);
    }

    private ServerState Fail(string detail)
    {
        var suffix = _lastEngineLine.Length == 0
            ? string.Empty
            : string.Format(CultureInfo.CurrentCulture, PanelStrings.SrvEngineLineSuffixFormat, _lastEngineLine);
        _log(detail + suffix);
        _port = 0;
        Owner = ServerOwner.None;

        // ПОПЫТКА КОНЧИЛАСЬ НЕУДАЧЕЙ — «ещё стартует» больше неправда (DEF-054).
        _engineStillStarting = false;

        return State = ServerState.Stopped(0, detail);
    }

    /// <summary>
    /// Отказ поднять СВОЙ сервер. Отдельно от <see cref="Fail"/>: тот объясняет неудачу ЗАПУСКА
    /// и приписывает к причине последнюю строку движка, а здесь движок и не запускался —
    /// чужая строка из прошлого запуска только запутала бы человека.
    /// </summary>
    private ServerState Refuse(string detail)
    {
        _log(detail);
        _startRefusal = detail;
        _port = 0;
        Owner = ServerOwner.None;

        // ОТКАЗ — это не «ещё стартует»: попытки не было вовсе (DEF-054).
        _engineStillStarting = false;

        return State = ServerState.Stopped(0, detail);
    }

    /// <summary>
    /// Найденный работающий DSH, из-за которого панель НЕ поднимает свой, или <c>null</c>, если
    /// поднимать можно. Свой процесс и сервер под управлением в находку не попадают — их исключает
    /// разведка, и это правильно: они не «чужие». Право «поднимать рядом» приходит ЯВНО
    /// (<c>allowParallelStart</c>), а не выводится из окружения: выведенное право однажды
    /// теряется незаметно.
    /// </summary>
    private FoundServer? ForeignServerBlocker()
    {
        var found = Scan();
        if (!ServerDecisions.BlockedByForeignServer(_allowParallelStart, found.Any)) return null;

        return found.First;
    }

