using System.Text.Json;
using System.Text.RegularExpressions;

namespace DshPanel.Server;

/// <summary>
/// Что движок САМ ОБЪЯВЛЯЕТ про свою поверхность RPC: версия пакета и полный список имён
/// <c>&lt;namespace/method&gt;</c>, прочитанный из объявлений, которые движок генерирует у себя.
/// </summary>
public sealed record EngineRpcDeclaration(
    string Version,
    IReadOnlyList<string> Endpoints,
    IReadOnlyList<string> Files,
    string Detail)
{
    public static EngineRpcDeclaration Unknown(string detail) =>
        new(string.Empty, Array.Empty<string>(), Array.Empty<string>(), detail);
}

/// <summary>
/// ОПИСЬ ДВИЖКА, ПРОЧИТАННАЯ У НЕГО САМОГО, — источник, с которым сверяется закреплённый список
/// панели (<see cref="EngineRpcSurface"/>).
///
/// **Зачем, если есть живая проба.** Проба по HTTP отвечает на вопрос «движок признал имя».
/// Она НЕ отвечает на вопрос «а не забыли ли мы чего»: имя, которого нет в списке панели, живой
/// пробой не проверяется вовсе — её просто не зовут. Здесь берётся полный перечень движка, и
/// сверка идёт **в обе стороны**: и «наше имя пропало у движка», и «у движка появилось имя,
/// которого мы не знаем».
///
/// **Почему это замер, а не документация.** Движок генерирует эти объявления из своей настоящей
/// поверхности (`Generated by @deepseek-ai/dsh-typert-generator from the Host FaceModel`), и они
/// лежат на диске рядом с тем самым <c>bin.js</c>, который запускает панель. Ничего не скачивается
/// и ни в какую сеть не ходит.
/// </summary>
public static class EngineRpcDeclarations
{
    /// <summary>Имя файла объявлений удалённого клиента (одно на пакет).</summary>
    public const string DeclarationFileName = "typert.remote-client.d.ts";

    /// <summary>Строка описи: <c>'namespace/method':</c> — так их пишет генератор движка.</summary>
    private static readonly Regex Entry = new(
        @"^\s*'([A-Za-z][A-Za-z0-9]*/[A-Za-z][A-Za-z0-9]*)':",
        RegexOptions.Multiline | RegexOptions.Compiled);

    /// <summary>
    /// Прочитать опись по пути к <c>bin.js</c> движка: версия из <c>package.json</c> пакета,
    /// имена — из объявлений всех пакетов движка. Ошибки чтения не бросаются наружу: опись
    /// «не прочиталась» — это ответ, а не падение пробы.
    /// </summary>
    public static EngineRpcDeclaration Read(string? engineBinPath)
    {
        if (string.IsNullOrWhiteSpace(engineBinPath))
            return EngineRpcDeclaration.Unknown("путь к движку не задан");

        try
        {
            // <пакет>\lib\bin.js → <пакет>
            var packageRoot = Path.GetDirectoryName(Path.GetDirectoryName(engineBinPath.Trim()));
            if (string.IsNullOrEmpty(packageRoot) || !Directory.Exists(packageRoot))
                return EngineRpcDeclaration.Unknown("пакет движка не найден рядом с bin.js");

            var version = PackageVersion(Path.Combine(packageRoot, "package.json"));

            var roots = ModuleRoots(packageRoot);
            if (roots.Count == 0)
            {
                // ⚠️ ВЕРСИЯ ОСТАЁТСЯ, даже когда сверять нечего: «объявлений нет» — это про имена,
                // а не про версию. Прежний код возвращал здесь `Unknown(…)` с ПУСТОЙ версией, и
                // строка отчёта говорила «версия «»», а умение «Версия движка» читалось как беда
                // (дефект, найденный замером 10.10.2026 на `0.2.0-rc.2`).
                return new EngineRpcDeclaration(
                    version,
                    Array.Empty<string>(),
                    Array.Empty<string>(),
                    "рядом с движком нет node_modules/@deepseek-ai — сверять нечего");
            }

            var endpoints = new SortedSet<string>(StringComparer.Ordinal);
            var files = new List<string>();

            // Идём ПРЯМО по пакетам движка, а не обходом всего дерева: обход `AllDirectories`
            // спотыкается на первом же недоступном каталоге в `node_modules` и уносит с собой
            // ВСЮ опись (проверено живым прогоном 10.10.2026: «объявлений у движка: 0»).
            // Объявления лежат ровно здесь: <пакет>\lib\ (где бы ни лежал сам <пакет>).
            var candidates = new List<string>();

            foreach (var modules in roots)
            {
                foreach (var package in Directory.EnumerateDirectories(modules))
                {
                    candidates.Add(Path.Combine(package, "lib", DeclarationFileName));

                    // У пакета бывает и своё `node_modules` (например у самого движка) — берём
                    // на шаг глубже, но по-прежнему перебором каталогов, а не обходом дерева.
                    var nested = Path.Combine(package, "node_modules", "@deepseek-ai");
                    if (!Directory.Exists(nested)) continue;

                    foreach (var inner in Directory.EnumerateDirectories(nested))
                        candidates.Add(Path.Combine(inner, "lib", DeclarationFileName));
                }
            }

            foreach (var file in candidates.Distinct(StringComparer.OrdinalIgnoreCase))
            {
                if (!File.Exists(file)) continue;

                var text = File.ReadAllText(file);
                var found = false;

                foreach (Match match in Entry.Matches(text))
                {
                    endpoints.Add(match.Groups[1].Value);
                    found = true;
                }

                if (found) files.Add(file);
            }

            return new EngineRpcDeclaration(
                version,
                endpoints.ToList(),
                files,
                files.Count > 0 ? "опись прочитана" : "объявлений поверхности не нашлось");
        }
        catch (Exception error)
        {
            return EngineRpcDeclaration.Unknown($"{error.GetType().Name}: {error.Message}");
        }
    }

    /// <summary>
    /// ГДЕ ЛЕЖАТ ПАКЕТЫ ДВИЖКА. Раскладок две, и обе настоящие:
    ///
    /// * **вложенная** (так ставит `npm install -g`): пакеты лежат **внутри** пакета движка —
    ///   `&lt;пакет&gt;\node_modules\@deepseek-ai\*`;
    /// * **плоская** (так ставит `npm install --prefix &lt;папка&gt;` — **и так панель будет ставить
    ///   движок сама**, этап E3): пакеты лежат **рядом** с движком, в том же `@deepseek-ai`, что
    ///   и сам движок, — `&lt;папка&gt;\node_modules\@deepseek-ai\*`.
    ///
    /// ⚠️ **Вложенная главнее, и это не вкус:** рядом с движком бывают и **чужие** пакеты
    /// `@deepseek-ai` (у человека их может быть сколько угодно). Если читать обе раскладки сразу,
    /// в опись попадут имена, которых у движка нет, и проверка «у движка появилось незнакомое имя»
    /// закричит ложную тревогу. Поэтому плоская берётся **только когда вложенной нет** — ровно так
    /// вышло в замере 10.10.2026: у `0.2.0-rc.2` своего `node_modules` нет вовсе, и объявления
    /// (26 файлов на диске) оставались невидимыми, а панель говорила «сверять нечего».
    /// </summary>
    private static IReadOnlyList<string> ModuleRoots(string packageRoot)
    {
        var nested = Path.Combine(packageRoot, "node_modules", "@deepseek-ai");
        if (Directory.Exists(nested)) return new[] { nested };

        // <...>\node_modules\@deepseek-ai\dsh → <...>\node_modules\@deepseek-ai
        var sibling = Path.GetDirectoryName(packageRoot);

        if (!string.IsNullOrEmpty(sibling)
            && Directory.Exists(sibling)
            && string.Equals(Path.GetFileName(sibling), "@deepseek-ai", StringComparison.OrdinalIgnoreCase))
            return new[] { sibling };

        return Array.Empty<string>();
    }

    /// <summary>Версия пакета движка. Пусто — прочитать не удалось, и это не «совпало».</summary>
    public static string PackageVersion(string? packageJson)
    {
        if (string.IsNullOrWhiteSpace(packageJson) || !File.Exists(packageJson)) return string.Empty;

        try
        {
            using var document = JsonDocument.Parse(File.ReadAllText(packageJson));

            return document.RootElement.TryGetProperty("version", out var version)
                ? version.GetString()?.Trim() ?? string.Empty
                : string.Empty;
        }
        catch
        {
            return string.Empty;
        }
    }

    /// <summary>Чего в списке панели нет, а у движка есть. Пусто — список полон.</summary>
    public static IReadOnlyList<string> Missing(EngineRpcDeclaration declaration, IReadOnlyList<EngineRpcMethod> pinned)
    {
        ArgumentNullException.ThrowIfNull(declaration);
        ArgumentNullException.ThrowIfNull(pinned);

        var known = pinned.Select(m => m.Endpoint).ToHashSet(StringComparer.Ordinal);
        return declaration.Endpoints.Where(name => !known.Contains(name)).ToList();
    }

    /// <summary>Что панель ждёт, а движок больше не объявляет. Пусто — ничего не пропало.</summary>
    public static IReadOnlyList<string> Gone(EngineRpcDeclaration declaration, IReadOnlyList<EngineRpcMethod> pinned)
    {
        ArgumentNullException.ThrowIfNull(declaration);
        ArgumentNullException.ThrowIfNull(pinned);

        var declared = declaration.Endpoints.ToHashSet(StringComparer.Ordinal);
        return pinned.Select(m => m.Endpoint).Where(name => !declared.Contains(name)).ToList();
    }
}
