namespace DshPanel.Server;

/// <summary>
/// ДВА ВЫВОДА ЗАМЕРОВ РАЗВЕДКИ E3.2, КОТОРЫЕ ОБЯЗАНЫ БЫТЬ В КОДЕ, А НЕ В РАЗГОВОРЕ (10.10.2026).
///
/// Здесь они объявлены **до** самой работы E3.2 намеренно — как `PanelFunction` для телефона и
/// обновления движка: правило, объявленное заранее, не забудется при написании путей, а его
/// значение стерегут проверки (перевернуть флаг — уронить названную).
/// </summary>
public static class EngineUpdatePolicy
{
    /// <summary>
    /// ⚠️ **«СПРАШИВАТЬ ВСЕГДА ПЕРЕД ОБНОВЛЕНИЕМ ДВИЖКА».**
    ///
    /// Замер разведки E3.2 (10.10.2026): признака «идёт работа» у панели **нет**. В закреплённой
    /// поверхности нет ни `session/status`, ни `job/*` (у линии 0.2.x они появились — 3 имени среди
    /// 67 новых, — но панель их не зовёт и признак «идёт работа» ими НЕ измерен), ответ
    /// `session/list` панель не разбирает, а **«сервер отвечает» признаком НЕ
    /// является**: замер показал отвечающий сервер владельца на 3080 при простое.
    ///
    /// Поэтому **никакого «умного определения» в коде быть не должно**, пока признак не измерен
    /// отдельно — на живом движке с ключом модели, дважды (простой против работы). До тех пор
    /// панель **спрашивает всегда**.
    /// </summary>
    public const bool AskAlwaysBeforeUpdate = true;

    /// <summary>
    /// ⚠️ **«ПОЛУАРХИВА НЕ БЫВАЕТ».**
    ///
    /// Замер разведки E3.2 (10.10.2026): копия профиля с работой — **42,2 МБ за 1,6 с** (профиль
    /// 40,0 МБ, сжатия почти нет: журналы уже `zstd`); при подложенной беде панель **отказывает
    /// словами** («по пути лежит ФАЙЛ, а нужна папка для архива») или честно говорит «файл НЕ
    /// ПРОЧИТАН: IOException» и объявляет **ПРОВАЛ**.
    ///
    /// Отсюда правило для обновления движка: предохранительная копия профиля — **либо целая, либо
    /// её нет**, и тогда **обновление не начинается**. «Полуархив», выглядящий как право
    /// откатиться, — обман человека в самом опасном месте.
    /// </summary>
    public const bool SafetyCopyMustBeWhole = true;
}
