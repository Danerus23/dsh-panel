    /// <summary>
    /// ДОЧИТАТЬ ОСТАТОК ЗАПРОСА И ЗАКРЫТЬ СОКЕТ ВЕЖЛИВО.
    ///
    /// Windows отвечает `RST` всякому, кто закрывает сокет с непрочитанными данными, — и тогда
    /// уже отправленный ответ до клиента не доходит. Проверка «слишком большое тело» на этом
    /// и попала бы: отказ был бы, а слов человек не увидел.
    ///
    /// Предел дочитывания назван: клиент, который шлёт бесконечно, держит соединение не дольше
    /// общего срока запроса (<see cref="RequestTimeout"/>) и не больше полумегабайта.
    /// </summary>
    private static async Task LingerAsync(NetworkStream stream, CancellationToken token)
    {
        try
        {
            stream.Socket.Shutdown(SocketShutdown.Send);

            var scrap = new byte[4096];
            var left = 512 * 1024;

            while (left > 0)
            {
                var read = await stream.ReadAsync(scrap.AsMemory(), token).ConfigureAwait(false);
                if (read <= 0) return;

                left -= read;
            }
        }
        catch
        {
            // Клиент уже ушёл — ровно этого и добивались.
        }
    }

    private static async Task WriteAsync(NetworkStream stream, PhoneHttpResponse response, CancellationToken token)    {
        var body = Encoding.UTF8.GetBytes(response.Body);

        var head = new StringBuilder()
            .Append("HTTP/1.1 ").Append(response.Status).Append(' ').Append(Reason(response.Status)).Append("\r\n")
            .Append("Content-Type: ").Append(response.ContentType).Append("\r\n")
            .Append("Content-Length: ").Append(body.Length).Append("\r\n")
            .Append("Connection: close\r\n");

        if (response.Cookie is not null) head.Append("Set-Cookie: ").Append(response.Cookie).Append("\r\n");

        // ПЕРЕНАПРАВЛЕНИЕ — ЗАГОЛОВКОМ: браузер уходит на `Location` сам, поэтому F5 повторяет
        // уже GET, а не отправку формы.
        if (response.Location is not null) head.Append("Location: ").Append(response.Location).Append("\r\n");

        // ⚠️ ЗАГОЛОВКИ БЕЗОПАСНОСТИ — НА КАЖДОМ ОТВЕТЕ (B-10). Место ОДНО: голова ответа собирается
        // здесь, и через эту строку проходит КАЖДЫЙ ответ калитки — 200, 303, 400, 401, 403, 404,
        // 405, 413, 429, 500, 502, 503. Поэтому «заголовки на всех ответах, включая ошибки»
        // держится УСТРОЙСТВОМ (одна дверь ответа), а не списком мест, где их не забыли.
        //
        // * `Cache-Control: no-store` — ответы калитки несут ЛИЧНОЕ: вопрос агента (в нём бывает
        //   текст чужой переписки), список сессий, имя устройства. Кэш телефона или прокси,
        //   сохранивший такую страницу, показал бы её следующему человеку, взявшему тот же телефон,
        //   а после «Отключить телефон» страница осталась бы в кэше. `no-store` — не «не кэшируй
        //   надолго», а «не сохраняй вовсе»: у калитки нет ни одного ответа, который повторное
        //   открытие должно взять из кэша.
        // * `X-Content-Type-Options: nosniff` — запрет угадывать тип: без него браузер может
        //   отрисовать ответ как HTML там, где мы сказали `application/json` (ASVS 5.0 3.4.4, L2).
        // * `Content-Security-Policy: frame-ancestors 'none'` — запрет вставлять наши страницы
        //   в рамку (кликджекинг). Выбран ИМЕННО CSP, а не `X-Frame-Options`: ASVS 5.0 3.4.6
        //   требует `frame-ancestors` для каждого ответа и называет `X-Frame-Options` устаревшим.
        //   Второго заголовка не ставим — «оба на всякий случай» читается как «мы не выбрали».
        //   Директива говорит ТОЛЬКО о рамках и не запрещает наши же `<style>`/`<script>`, поэтому
        //   страница телефона (у неё свой скрипт живого обновления) не ломается.
        // ⚠️ СВОИ ЗАГОЛОВКИ — НЕ «ОТМЕНА БЕЗОПАСНОСТИ», а точечная замена: у ассетов пульта
        // СВОЙ срок кэша (`immutable`: имя файла содержит хеш), а политика поверх них — та же,
        // только вместо `frame-ancestors` — ПОЛНАЯ `PhoneWeb.Csp` (это же и есть новая поверхность).
        // Дубля заголовков при этом нет: значение, названное в `Headers`, заменяет умолчание.
        var extra = response.Headers ?? Array.Empty<(string Name, string Value)>();

        bool Given(string name) => extra.Any(item =>
            string.Equals(item.Name, name, StringComparison.OrdinalIgnoreCase));

        if (!Given("Cache-Control")) head.Append("Cache-Control: no-store\r\n");

        head.Append("X-Content-Type-Options: nosniff\r\n");

        if (!Given("Content-Security-Policy"))
            head.Append("Content-Security-Policy: frame-ancestors 'none'\r\n");

        foreach (var (name, value) in extra) head.Append(name).Append(": ").Append(value).Append("\r\n");

        head.Append("\r\n");

        await stream.WriteAsync(Encoding.ASCII.GetBytes(head.ToString()), token).ConfigureAwait(false);
        await stream.WriteAsync(body, token).ConfigureAwait(false);
        await stream.FlushAsync(token).ConfigureAwait(false);
    }

    private static string Reason(int status) => status switch
    {
        200 => "OK",
        303 => "See Other",
        400 => "Bad Request",
        401 => "Unauthorized",
        403 => "Forbidden",
        404 => "Not Found",
        405 => "Method Not Allowed",
        413 => "Payload Too Large",
        429 => "Too Many Requests",
        500 => "Internal Server Error",
        502 => "Bad Gateway",
        503 => "Service Unavailable",
        _ => "OK",
    };

    /// <summary>
    /// Ответ калитки телефону. <see cref="Cookie"/> — только у удачного сопряжения,
    /// <see cref="Location"/> — только у перенаправления (303) после формы.
    ///
    /// <see cref="Sse"/> — ЖИВОЙ ПОТОК, А НЕ ГОТОВЫЙ ОТВЕТ: у такого ответа НЕТ <c>Content-Length</c>,
    /// голову пишет <see cref="WriteSseHeadAsync"/>, а события — та же дверь (одна на поток).
    /// <see cref="Lease"/> — место живого экрана: возвращается, когда ответ (включая поток) кончился.
    /// </summary>
    private sealed record PhoneHttpResponse(
        int Status,
        string ContentType,
        string Body,
        string? Cookie,
        string? Location = null,
        Func<NetworkStream, CancellationToken, Task>? Sse = null,
        IDisposable? Lease = null,
        IReadOnlyList<(string Name, string Value)>? Headers = null,
        TimeSpan? OwnTimeout = null,
        Func<CancellationToken, Task<PhoneHttpResponse>>? Late = null)
    {
        public static PhoneHttpResponse Json(int status, string body) =>
            new(status, "application/json; charset=utf-8", body, null);

        public static PhoneHttpResponse Html(string body) =>
            new(200, "text/html; charset=utf-8", body, null);

        /// <summary>
        /// ОТПРАВИТЬ БРАУЗЕР НА ДРУГУЮ СТРАНИЦУ — 303 и <c>Location</c>, тело пустое.
        ///
        /// ⚠️ Именно 303, а не 302: <c>See Other</c> обязывает браузер сделать следующий запрос
        /// методом <c>GET</c>. С 302 браузер повторил бы POST на <c>/</c> по F5 — то есть отправлял
        /// бы ответ на вопрос повторно, чего решением владельца быть не должно.
        /// </summary>
        public static PhoneHttpResponse Redirect(string location) =>
            new(303, "text/html; charset=utf-8", string.Empty, null, location);

        /// <summary>Слова человеку в одном виде: <c>{"ok":…,"message":"…"}</c>.</summary>
        public static PhoneHttpResponse Words(int status, bool ok, string words) =>
            Json(status, "{\"ok\":" + (ok ? "true" : "false") + ",\"message\":" + Quote(words) + "}");
    }

    /// <summary>Как писать строки в JSON: кириллица и китайский — СЛОВАМИ, а не <c>\uXXXX</c>.</summary>
    private static readonly JsonSerializerOptions Readable = new()
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    /// <summary>Доводы в JSON одной строкой — тем же кодировщиком, что и слова человеку.</summary>
    private static string Quote(string text) => JsonSerializer.Serialize(text ?? string.Empty, Readable);
}









