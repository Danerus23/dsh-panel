    private async Task AcceptLoopAsync(TcpListener listener, CancellationToken token)
    {
        while (!token.IsCancellationRequested)
        {
            TcpClient client;

            try
            {
                client = await listener.AcceptTcpClientAsync(token).ConfigureAwait(false);
            }
            catch (Exception)
            {
                // Слушатель закрыт (остановка калитки) или сокет отказал — цикл кончается.
                // Слов здесь не порождается: об остановке калитка уже сказала.
                return;
            }

            _ = Task.Run(() => ServeAsync(client, token), CancellationToken.None);
        }
    }

    private async Task ServeAsync(TcpClient client, CancellationToken token)
    {
        using (client)
        {
            PhoneHttpResponse? response = null;

            try
            {
                client.NoDelay = true;

                using var timed = CancellationTokenSource.CreateLinkedTokenSource(token);
                timed.CancelAfter(RequestTimeout);

                var stream = client.GetStream();
                var (request, notHttp) = await ReadAsync(stream, client, timed.Token).ConfigureAwait(false);

                // ⚠️ НЕ HTTP — ЗАКРЫВАЕМ СРАЗУ И МОЛЧА, НИ ОДНОГО БАЙТА В ОТВЕТ (DEF-062). Чужая
                // проба — это TLS ClientHello от браузера телефона (`0x16 0x03…`), сканер или
                // просто мусор; «запроса» здесь нет, и дочитывать нечего. Держать такое соединение
                // до RequestTimeout и было дефектом: первый вход на страницу телефона занимал
                // 15 068 мс — ровно срок запроса.
                if (notHttp) return;

                response = request is null
                    ? PhoneHttpResponse.Words(400, false, Loc.T(PanelStrings.PhoneGateBadRequest))
                    : Route(request);

                // ЖИВОЙ ПОТОК ОТВЕЧАЕТ СВОИМ СРОКОМ. Пятнадцатисекундный `timed` — срок ЧТЕНИЯ
                // запроса; для SSE он остаётся только на запись головы, а сама лента живёт
                // своим сроком (<see cref="LiveLifetime"/>) и гаснет вместе с калиткой (token).
                if (response.Sse is not null)
                {
                    await WriteSseHeadAsync(stream, timed.Token).ConfigureAwait(false);
                    await response.Sse(stream, token).ConfigureAwait(false);
                    return;
                }

                // СВОЙ СРОК У ОТВЕТА (двери S3, контракт §1.5). Пятнадцать секунд — срок ЧТЕНИЯ
                // запроса; у D2 два вызова движка (10 + 10), у D4 ожидание baseline — оба в 15 с
                // НЕ ВЛЕЗАЮТ. Прежний порядок срезал бы готовый ответ молчанием (срок истёк —
                // писать нечем), и человек прочитал бы «ничего не пришло» вместо «не принято».
                using var writing = CancellationTokenSource.CreateLinkedTokenSource(token);

                writing.CancelAfter(response.OwnTimeout ?? RequestTimeout);

                // ОТЛОЖЕННЫЙ ОТВЕТ: тело собирается АСИНХРОННО (D4 ждёт baseline). Голова при
                // этом пишется по-прежнему одна и та же — `WriteAsync`, с Content-Length.
                if (response.Late is not null)
                    response = await response.Late(writing.Token).ConfigureAwait(false);

                await WriteAsync(stream, response, writing.Token).ConfigureAwait(false);

                // ВЕЖЛИВОЕ ЗАКРЫТИЕ — и это не украшение. Если закрыть сокет, не дочитав то, что
                // клиент ещё шлёт, Windows отвечает ему `RST`, и ответ до него НЕ ДОХОДИТ: отказ
                // «слишком большое тело» превратился бы в «соединение сброшено», то есть в молчание.
                // Поэтому сначала «я больше не пишу», потом дочитывание остатка с пределом.
                await LingerAsync(stream, writing.Token).ConfigureAwait(false);
            }
            catch (Exception)
            {
                // Клиент ушёл посреди запроса — это его дело, а не беда калитки. Молчать здесь
                // можно: ответа всё равно некому отдать.
            }
            finally
            {
                // МЕСТО ЖИВОГО ПОТОКА ВОЗВРАЩАЕТСЯ ВСЕГДА — и когда поток открылся, и когда
                // голова не записалась: иначе «слишком много экранов» осталось бы навсегда.
                response?.Lease?.Dispose();
            }
        }
    }

    /// <summary>
    /// ОДИН РАЗОБРАННЫЙ ЗАПРОС. Из заголовков читаются ШЕСТЬ, и у каждого названо, зачем он:
    /// `Cookie` (кто пришёл), `Content-Length` (сколько читать — в записи остаётся только тело),
    /// `Accept-Language` (на каком языке говорить), `User-Agent` (как назвать телефон человеку)
    /// и пара `Host`/`Origin` — **только затем, чтобы сверить дверь** (`JudgeDoor`): дальше они
    /// не идут ни в ответ, ни в журнал, ни в движок.
    /// Чужие заголовки не сохраняются вовсе — значит их нельзя случайно передать дальше,
    /// и «никаких чужих заголовков» держится устройством, а не внимательностью.
    /// </summary>
    private sealed record PhoneHttpRequest(
        string Method,
        string Path,
        string Query,
        string Cookie,
        string Language,
        string Address,
        string Body,
        bool TooBig,
        string UserAgent,
        string Host,
        string Origin);

    /// <summary>
    /// НАЧАЛА HTTP-МЕТОДОВ, которые калитка разбирает. Список нужен НЕ маршрутизации (метод сверяет
    /// <see cref="Route"/>), а первой развилке чтения: чем кончилось соединение — запросом или
    /// чужим протоколом.
    ///
    /// ⚠️ **От какого случая (DEF-062).** Первый вход на страницу телефона занимал **15 068 мс**:
    /// браузер телефона пробует HTTPS и первым делом шлёт TLS ClientHello (`0x16 0x03…`), а калитка
    /// считала его началом запроса и ждала заголовков до <see cref="RequestTimeout"/> — ровно 15 с.
    /// Теперь такое соединение закрывается сразу и молча: 0 байт в ответ, ноль ожидания.
    /// </summary>
    private static readonly string[] HttpMethodStarts =
        { "GET", "HEAD", "POST", "PUT", "DELETE", "CONNECT", "OPTIONS", "TRACE", "PATCH" };

    /// <summary>
    /// ЭТО НАЧАЛО HTTP-ЗАПРОСА — ответ по первым байтам: <c>false</c> — «закрывай, это не HTTP»,
    /// <c>true</c> — «похоже и, может быть, ещё не всё» (<c>GE</c> — начало <c>GET</c>), либо метод
    /// уже дочитан и за ним стоит пробел.
    ///
    /// ⚠️ **РЕШАТЬ ПО ПЕРВОМУ КУСКУ НЕЛЬЗЯ.** Запрос идёт по TCP кусками: телефон вправе прислать
    /// «GE», помолчать и прислать «T / HTTP/1.1…». Поэтому мусором «GE» становится не сразу, а
    /// только когда следующий байт перестал быть продолжением ни одного метода.
    /// </summary>
    private static bool PlausibleHttpStart(byte[] buffer, int length)
    {
        foreach (var method in HttpMethodStarts)
        {
            if (length <= method.Length)
            {
                if (Prefix(buffer, length, method)) return true;

                continue;
            }

            // Метод дочитан целиком: за ним обязан стоять пробел — «GETX» запросом не является.
            if (Prefix(buffer, method.Length, method) && buffer[method.Length] == (byte)' ') return true;
        }

        return false;
    }

    /// <summary>Первые <paramref name="length"/> байт — начало <paramref name="method"/>.</summary>
    private static bool Prefix(byte[] buffer, int length, string method)
    {
        for (var index = 0; index < length; index++)
            if (buffer[index] != (byte)method[index]) return false;

        return true;
    }

    /// <summary>
    /// ОДИН ЗАПРОС ИЗ СОКЕТА. Пара на выходе различает три исхода, и это НЕ украшение: мусору
    /// ответа не пишут вовсе (<c>NotHttp: true</c>), испорченному запросу отвечают 400 словами
    /// (<c>Request: null</c>), а разобранный уходит в <see cref="Route"/>.
    /// </summary>
    private static async Task<(PhoneHttpRequest? Request, bool NotHttp)> ReadAsync(
        NetworkStream stream, TcpClient client, CancellationToken token)
    {
        var head = new MemoryStream();
        var chunk = new byte[4096];
        var end = -1;

        while (end < 0)
        {
            if (head.Length > MaxHeaderBytes) return (TooBig(string.Empty), false);

            var read = await stream.ReadAsync(chunk.AsMemory(), token).ConfigureAwait(false);
            if (read <= 0) return (null, false);

            head.Write(chunk, 0, read);

            // Решение принимается по НАКОПЛЕННОМУ, а не по последнему куску: разрезанный запрос
            // остаётся запросом, а TLS ClientHello отсекается на первом же байте 0x16.
            if (!PlausibleHttpStart(head.GetBuffer(), (int)head.Length)) return (null, true);

            end = HeaderEnd(head.GetBuffer(), (int)head.Length);
        }

        var text = Encoding.UTF8.GetString(head.GetBuffer(), 0, end + 4);
        var lines = text.Split("\r\n");
        var first = lines[0].Split(' ');

        if (first.Length < 2) return (null, false);

        var method = first[0].Trim().ToUpperInvariant();

        // СТРОКА ЗАПРОСА БЕРЁТСЯ ЦЕЛИКОМ, а маршрут — без `?`: живому обновлению нужен
        // `?part=card`, остальным маршрутам — только путь. Разбор строки запроса в
        // <see cref="PhonePage.CardWanted"/> и больше нигде.
        var target = first[1];
        var mark = target.IndexOf('?');
        var path = mark < 0 ? target : target[..mark];
        var query = mark < 0 ? string.Empty : target[(mark + 1)..];

        var cookie = string.Empty;
        var language = string.Empty;
        var userAgent = string.Empty;
        var host = string.Empty;
        var origin = string.Empty;
        var headers = 0;
        var contentLength = 0L;

        for (var index = 1; index < lines.Length; index++)
        {
            var line = lines[index];
            if (line.Length == 0) continue;

            headers++;

            if (headers > MaxHeaders) return (TooBig(AddressOf(client), path, language), false);
            var colon = line.IndexOf(':');
            if (colon <= 0) continue;

            var name = line[..colon].Trim();
            var value = line[(colon + 1)..].Trim();

            if (string.Equals(name, "Cookie", StringComparison.OrdinalIgnoreCase)) cookie = value;

            if (string.Equals(name, "Accept-Language", StringComparison.OrdinalIgnoreCase)) language = value;

            // ⚠️ `User-Agent` читается ТОЛЬКО ЗАТЕМ, чтобы назвать телефон человеку
            // (`PhoneDecisions.DeviceName`), и ничего не решает: доступ решает файл пропуска.
            // Подделать строку ничего не даёт — она не примета устройства.
            if (string.Equals(name, "User-Agent", StringComparison.OrdinalIgnoreCase)) userAgent = value;

            // ⚠️ `Host` и `Origin` — для СВЕРКИ ДВЕРИ (B-03), и больше ни для чего. Второй такой
            // заголовок не уточняет первый, а склеивается с ним: «кто первый, тот и прав» —
            // это ровно то, чем подменяют дверь промежуточные звенья и подделки.
            if (string.Equals(name, "Host", StringComparison.OrdinalIgnoreCase)) host = Twice(host, value);

            if (string.Equals(name, "Origin", StringComparison.OrdinalIgnoreCase)) origin = Twice(origin, value);

            if (string.Equals(name, "Content-Length", StringComparison.OrdinalIgnoreCase)
                && long.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var parsed))
            {
                contentLength = parsed;
            }
        }

        if (contentLength < 0 || contentLength > MaxBodyBytes) return (TooBig(AddressOf(client), path, language), false);

        var body = new byte[contentLength];
        var carried = (int)Math.Min(head.Length - (end + 4), contentLength);

        if (carried > 0) Array.Copy(head.GetBuffer(), end + 4, body, 0, carried);

        var filled = carried;

        while (filled < contentLength)
        {
            var read = await stream
                .ReadAsync(body.AsMemory(filled, (int)contentLength - filled), token)
                .ConfigureAwait(false);

            if (read <= 0) break;

            filled += read;
        }

        return (new PhoneHttpRequest(
            method, path, query, cookie, language, AddressOf(client),
            Encoding.UTF8.GetString(body, 0, filled), false, userAgent, host, origin), false);
    }

    /// <summary>Второй такой же заголовок не уточняет первый, а склеивается с ним: сверка двери
    /// (`JudgeDoor`) такую склейку отвергает, и подмена `Host`/`Origin` не проходит ни при каком
    /// порядке разбора (B-03).</summary>
    private static string Twice(string first, string value) =>
        first.Length == 0 ? value : first + ", " + value;

    /// <summary>
    /// СЛИШКОМ БОЛЬШОЙ ЗАПРОС — с ПУТЁМ и ЯЗЫКОМ, когда они уже разобраны.
    ///
    /// **Зачем путь у «слишком большого».** У дверей S3 свой текст отказа (F-1), и без пути
    /// выбор между «задача больше, чем телефон может отправить» и общим обрывком калитки
    /// был бы невозможен: заголовки читаются раньше тела, а `TooBig` терял уже прочитанное.
    /// Предел заголовков путь не сохраняет (строки запроса ещё нет) — там он и не нужен.
    /// </summary>
    private static PhoneHttpRequest TooBig(string address, string path = "", string language = "") =>
        new(string.Empty, path, string.Empty, string.Empty, language, address, string.Empty, true,
            string.Empty, string.Empty, string.Empty);

    /// <summary>Адрес просящего — для ограничения попыток. Не разобрался — «адрес неизвестен»,
    /// и это отдельный ключ лимита, а не «пропустить мимо счёта».</summary>
    private static string AddressOf(TcpClient client)
    {
        try
        {
            return client.Client.RemoteEndPoint is IPEndPoint end
                ? PhoneDecisions.AddressOf(end.Address.ToString())
                : PhoneDecisions.UnknownAddress;
        }
        catch
        {
            return PhoneDecisions.UnknownAddress;
        }
    }

    /// <summary>Где кончаются заголовки: индекс начала <c>CRLFCRLF</c>, иначе <c>-1</c>.</summary>
    private static int HeaderEnd(byte[] buffer, int length)
    {
        for (var index = 0; index + 3 < length; index++)
        {
            if (buffer[index] == 13 && buffer[index + 1] == 10 && buffer[index + 2] == 13 && buffer[index + 3] == 10)
                return index;
        }

        return -1;
    }

    // ---- своя дверь: сверка `Host` и `Origin` (B-03) ------------------------------------------

    /// <summary>ЧЬЯ ЭТО ДВЕРЬ — ответ на сверку двух заголовков запроса.</summary>
    internal enum DoorVerdict
    {
        /// <summary>Своя дверь: имя наше, страница своя (или её не называли вовсе).</summary>
        Own,

        /// <summary>Имя двери чужое: так приходит подмена (`Host: чужой-адрес`, DNS rebinding).</summary>
        ForeignHost,

        /// <summary>Страница чужая (`Origin` не наш или `null`): так приходит ответ за человека.</summary>
        ForeignOrigin,
    }

    /// <summary>
    /// СВЕРКА ДВЕРИ ПО ДВУМ ЗАГОЛОВКАМ — чистое решение, без сети, запроса и калитки: его можно
    /// проверить само по себе, как <see cref="WildcardAddress"/>. Зовётся из <see cref="Route"/>
    /// ДО любого действия.
    ///
    /// ⚠️ **Зачем это, если телефон и так носит пропуск.** Пропуск отвечает «кто это»; сверка двери
    /// отвечает «та ли это дверь и та ли страница». Без неё остаются две дыры, и обе настоящие:
    ///   * **чужое имя двери** (`Host`) — подмена имени (DNS rebinding): страница чужого сайта
    ///     заставляет браузер звонить по нашему адресу, но под своим именем, и читает наши ответы
    ///     как свои. Норма — OWASP ASVS 5.0, **3.4.2** (L1): `Origin`/имя сверяются по списку
    ///     доверенных, а `*` не годится; здесь список доверенных — ОДНА своя дверь;
    ///   * **чужая страница** (`Origin`) — ответ за человека: `/pair` cookie не требует ни от кого,
    ///     и форма с чужого сайта завела бы устройство. Чужой `Origin` приходит и как `null`
    ///     (песочница, файл, `data:`) — это тоже НЕ наша страница.
    ///
    /// **Пустой `Origin` — не чужая страница:** к обычному переходу (GET) браузер его не прикладывает,
    /// а к форме со своей же страницы прикладывает — и тогда он совпадает с именем двери. Требовать
    /// заголовок всегда значило бы сломать вход по QR. **Пустой `Host` — отказ:** HTTP/1.1 без имени
    /// двери от телефона не приходит вовсе, а «дверь не назвали» не значит «своя».
    ///
    /// Адрес и порт — **своей** двери, а не довод запроса. `address = null` значит «калитка не знает,
    /// где она стоит», и это отказ, а не «пропустить»: своё имя — только у открытой двери.
    /// </summary>
    internal static DoorVerdict JudgeDoor(string? host, string? origin, IPAddress? address, int port)
    {
        if (!OwnHostName(host, address, port)) return DoorVerdict.ForeignHost;

        return OwnOrigin(origin, address, port) ? DoorVerdict.Own : DoorVerdict.ForeignOrigin;
    }

    /// <summary>
    /// СВОЁ ЛИ ИМЯ В `Host`. Годится ровно то, что человек видит в разделе «Телефон»: адрес калитки
    /// и её порт (`192.168.1.5:43127`; у IPv6 — в скобках, как велит HTTP). Петля принимает ещё и
    /// `localhost`: это второе имя той же двери, и прогоны проверки ходят именно так.
    ///
    /// Порт можно не называть ТОЛЬКО тогда, когда он и есть порт по умолчанию (80): браузер
    /// выбрасывает `:80` из адреса, и требовать его значило бы закрыть калитку, поставленную на 80.
    /// </summary>
    internal static bool OwnHostName(string? hostHeader, IPAddress? address, int port)
    {
        var header = (hostHeader ?? string.Empty).Trim();

        if (address is null || header.Length == 0) return false;

        if (!SplitHost(header, out var name, out var given)) return false;

        // ПОРТ: названный обязан совпасть, неназванный годится только для порта по умолчанию.
        if (given >= 0 ? given != port : port != 80) return false;

        if (SameName(name, address)) return true;

        // ПЕТЛЯ: `localhost` — второе имя той же двери, и только для двери на петле. Машинного
        // имени здесь нет намеренно: это было бы НОВОЕ имя двери, а поверхность калитки не растёт.
        return IPAddress.IsLoopback(address)
            && string.Equals(name, "localhost", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// СВОЯ ЛИ СТРАНИЦА В `Origin`. Пусто — своих не спрашивают (см. <see cref="JudgeDoor"/>).
    /// Названный `Origin` обязан быть ровно `http://` + своё имя двери: калитка отдаёт страницу
    /// только по HTTP (шифрования у неё нет — F3), поэтому `https://` здесь не бывает, а `null`,
    /// `file://` и любой чужой адрес — не наша страница.
    /// </summary>
    internal static bool OwnOrigin(string? originHeader, IPAddress? address, int port)
    {
        var origin = (originHeader ?? string.Empty).Trim();

        if (origin.Length == 0) return true;

        const string scheme = "http://";

        if (!origin.StartsWith(scheme, StringComparison.OrdinalIgnoreCase)) return false;

        var name = origin[scheme.Length..];

        // После имени двери в `Origin` ничего стоять не может: ни пути, ни `?`, ни `#`, ни пробела
        // (пробел — это уже список источников, а списков мы не принимаем).
        if (name.Length == 0 || name.IndexOfAny(new[] { '/', '?', '#', ' ' }) >= 0) return false;

        return OwnHostName(name, address, port);
    }

    /// <summary>
    /// РАЗОБРАТЬ ЗАГОЛОВОК `Host` НА ИМЯ И ПОРТ. `given` = <c>-1</c>, когда порт не назван.
    /// Имя IPv6 обязано быть в скобках (RFC 7230 §5.4): без них `fe80::1` не отличить от порта,
    /// и «двоеточий больше одного без скобок» — это мусор, а не имя.
    /// </summary>
    private static bool SplitHost(string header, out string name, out int given)
    {
        name = string.Empty;
        given = -1;

        if (header.StartsWith('['))
        {
            var close = header.IndexOf(']');

            if (close <= 1) return false;

            name = header[1..close];

            var rest = header[(close + 1)..];

            if (rest.Length == 0) return true;

            return rest.Length > 1 && rest[0] == ':' && Port(rest[1..], out given);
        }

        var colon = header.LastIndexOf(':');

        if (colon < 0)
        {
            name = header;
            return true;
        }

        if (header.IndexOf(':') != colon) return false;

        name = header[..colon];

        return name.Length > 0 && Port(header[(colon + 1)..], out given);
    }

    /// <summary>Порт — только цифры: знак, пробел и пустая строка портом не считаются.</summary>
    private static bool Port(string text, out int value) =>
        int.TryParse(text, NumberStyles.None, CultureInfo.InvariantCulture, out value)
        && value is > 0 and < 65536;

    /// <summary>ИМЯ СВОЕЙ ДВЕРИ — под замком: <see cref="Start"/> и <see cref="Stop"/> его меняют,
    /// а запросы читают из своих ниток.</summary>
    private OwnDoor? OwnDoorNow()
    {
        lock (_gate) return _own;
    }

    /// <summary>
    /// ЖИВАЯ ДВЕРЬ — имя двери, ПОКА СЛУШАТЕЛЬ СТОИТ, и <c>null</c>, когда калитка не слушает.
    ///
    /// Отдельно от <see cref="OwnDoorNow"/> намеренно: «двери нет» и «дверь не названа» — разные
    /// ответы. Сверка двери отвергает и то и другое, а запуск обязан их различать: повтор при
    /// живой двери — не ошибка, а закрытая калитка с оставшимся именем — ошибка (DEF-069).
    /// </summary>
    private OwnDoor? LiveDoor()
    {
        lock (_gate) return _listener is null ? null : _own;
    }

    /// <summary>
    /// СОВПАЛО ЛИ ИМЯ С АДРЕСОМ ДВЕРИ. Сравнение без учёта регистра: имена без регистра.
    /// ⚠️ У IPv6 в адресе бывает ЗОНА (`fe80::1%12`), а в имени двери её не бывает никогда —
    /// поэтому сверяется ещё и адрес без зоны, иначе калитка на link-local адресе закрылась бы
    /// для своего же телефона.
    /// </summary>
    private static bool SameName(string name, IPAddress address)
    {
        if (string.Equals(name, address.ToString(), StringComparison.OrdinalIgnoreCase)) return true;

        return address.AddressFamily == AddressFamily.InterNetworkV6
            && string.Equals(
                name,
                new IPAddress(address.GetAddressBytes()).ToString(),
                StringComparison.OrdinalIgnoreCase);
    }

    // ---- маршруты ---------------------------------------------------------------------------

    private PhoneHttpResponse Route(PhoneHttpRequest request)
    {
        if (request.TooBig)
        {
            // СВОЁ СЛОВО У ДВЕРЕЙ S3 (F-1): обрывок калитки говорит «запрос… (64 КиБ)» —
            // механика и единица, которой человеку нечего делать. Чужие двери остаются как были:
            // их язык — находка для t9, а не правка S3 (контракт §0.10).
            return IsTaskDoor(request.Path)
                ? PhoneHttpResponse.Words(413, false, Loc.TIn(Language(request), nameof(PanelStrings.PhoneTaskTooBig)))
                : PhoneHttpResponse.Words(
                    413, false,
                    string.Format(
                        CultureInfo.CurrentCulture, PanelStrings.PhoneGateTooBigFormat, MaxBodyBytes / 1024));
        }

        // ⚠️ ДВЕРЬ СВЕРЯЕТСЯ ЗДЕСЬ — ДО РАЗБОРА ПУТИ И ДО ЛЮБОГО ДЕЙСТВИЯ (B-03, ASVS 5.0 3.4.2).
        // Чужой `Host` — подмена имени двери, чужой `Origin` (и `Origin: null`) — чужая страница;
        // и то и другое получает отказ ОДНИМИ СЛОВАМИ, не видя ни входа, ни страницы, ни ответа
        // движка. Проверка стоит выше `if (request.Path == "/")` намеренно: иначе подменённая дверь
        // читала бы страницу входа, а «отказ до действия» держался бы порядком строк, а не кодом.
        //
        // ⚠️ 413 (слишком большой запрос) стоит ВЫШЕ намеренно: у такого запроса заголовки не
        // разобраны вовсе, и «чужая дверь» вместо «слишком много» соврала бы своему же телефону.
        var own = OwnDoorNow();

        if (JudgeDoor(request.Host, request.Origin, own?.Address, own?.Port ?? 0) != DoorVerdict.Own)
            return IsTaskDoor(request.Path)
                ? PhoneHttpResponse.Words(403, false, Loc.TIn(Language(request), nameof(PanelStrings.PhoneTaskForeignDoor)))
                : PhoneHttpResponse.Words(403, false, Loc.T(PanelStrings.PhoneGateForeignDoor));

        // КОРЕНЬ КАЛИТКИ — REACT-ОБОЛОЧКА ПУЛЬТА (S1+S2). Она же дверь: кто ещё не сопряжён,
        // получает оболочку с `authed:false` (экран входа), кто свой — работу. Второго адреса
        // телефону не заводится: он должен знать ОДИН адрес, и он у него уже есть (QR и слова раздела).
        if (request.Path == "/")
            return request.Method == "GET" ? Shell(request) : NotAllowed(request);

        // ЗАПАСНОЙ АДРЕС — ПРЕЖНЯЯ СЕРВЕРНАЯ СТРАНИЦА ЦЕЛИКОМ, со своим опросом `?part=card`.
        // Она остаётся РАБОТАЮЩЕЙ: React-пульт может не запуститься (старый телефон, выключенный
        // JavaScript, строгая политика) — и тогда прямой адрес это выход, а не обещание.
        if (request.Path == "/ask")
        {
            if (request.Method != "GET") return NotAllowed(request);

            if (!PhonePage.CardWanted(request.Query)) return Page(request);

            return Authorized(request, out var deviceId)
                ? PhoneHttpResponse.Html(PhonePage.Html(Language(request), View(deviceId), cardOnly: true))
                : PhoneHttpResponse.Html(PhoneLoginPage.Html(Language(request)));
        }

        // ФАЙЛЫ ПУЛЬТА: имя берётся из `assets.json` и сверяется с вложенными один в один.
        if (request.Path.StartsWith(PhoneWeb.AssetPath, StringComparison.Ordinal))
        {
            if (request.Method != "GET") return NotAllowed(request);

            return AssetFile(request.Path[PhoneWeb.AssetPath.Length..]);
        }

        if (request.Path == "/pair")
            return request.Method == "POST" ? Pair(request) : NotAllowed(request);

        if (request.Path == "/question")
            return request.Method == "GET" ? Question(request) : NotAllowed(request);

        if (request.Path == "/answer")
            return request.Method == "POST" ? Answer(request) : NotAllowed(request);

        if (request.Path == "/cancel")
            return request.Method == "POST" ? Cancel(request) : NotAllowed(request);

        // ДВЕ ДВЕРИ ЧТЕНИЯ S1 (контракт §2.1–§2.2). Это НЕ вызовы движка по имени: имена
        // `session/list` и `session/follow` остаются в белом списке, а наружу открыты две
        // адреса калитки — нового имени движка здесь не появляется.
        if (request.Path == "/api/phone/sessions")
            return request.Method == "GET" ? SessionsList(request) : NotAllowed(request);

        if (request.Path == "/api/phone/live")
            return request.Method == "GET" ? Live(request) : NotAllowed(request);

        // ТРЕТЬЯ ДВЕРЬ ЧТЕНИЯ — ЖИВАЯ ПОДСКАЗКА СПИСКА (G1, слово владельца 11.11.2026).
        // Своего имени движка у неё нет: она слушает тот же `$events`, а наружу отдаёт ОДИН бит.
        if (request.Path == ListLivePath)
            return request.Method == "GET" ? ListLive(request) : NotAllowed(request);
        if (request.Path == "/api/phone/question")
            return request.Method == "GET" ? PhoneQuestion(request) : NotAllowed(request);

        // ПЯТЬ ДВЕРЕЙ S3 — ЗАПИСЬ И ОЧЕРЕДЬ (слово владельца 30.10.2026, R-01/DEF-022).
        //
        // ⚠️ СТОЯТ ДО ОБЩЕЙ ВЕТКИ `/api/`, и это не порядок строк, а условие верного отказа:
        // общая ветка уводит имя целиком в движок (`phone/prompt`) и дала бы `403 «вне списка»` —
        // правдоподобный, но неверный ответ на верное действие (контракт §1.3).
        //
        // Метод сверяется ЗДЕСЬ и ДО входа — своим словом S3: обрывки калитки на экране задачи
        // стоят без вводного слова, и сорочка «этот путь не принимает метод …» человеку не читается.
        if (request.Path == PromptPath)
            return request.Method == "POST" ? PromptDoor(request) : TaskNotAllowed(request);

        if (request.Path == NewPath)
            return request.Method == "POST" ? NewDoor(request) : TaskNotAllowed(request);

        if (request.Path == StopPath)
            return request.Method == "POST" ? StopDoor(request) : TaskNotAllowed(request);

        if (request.Path == QueuePath)
            return request.Method == "GET" ? QueueDoor(request) : TaskNotAllowed(request);

        if (request.Path == QueueRemovePath)
            return request.Method == "POST" ? QueueRemoveDoor(request) : TaskNotAllowed(request);

        if (request.Path.StartsWith("/api/", StringComparison.Ordinal))
        {
            return request.Method == "POST"
                ? Api(request, request.Path[5..])
                : NotAllowed(request);
        }

        return PhoneHttpResponse.Words(
            404, false,
            string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateNotFoundFormat, request.Path));
    }

    private PhoneHttpResponse NotAllowed(PhoneHttpRequest request) =>
        PhoneHttpResponse.Words(
            405, false,
            string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneGateBadMethodFormat, request.Method, request.Path));

    // ---- двери S3: задача, новая задача, стоп, очередь, «убрать» ---------------------------------

    /// <summary>Адрес D1 — поставить задачу в открытую сессию.</summary>
    public const string PromptPath = "/api/phone/prompt";

    /// <summary>Адрес D2 — создать разговор и поставить в него задачу.</summary>
    public const string NewPath = "/api/phone/new";

    /// <summary>Адрес D3 — остановить текущий ход.</summary>
    public const string StopPath = "/api/phone/stop";

    /// <summary>Адрес D4 — прочитать очередь одной сессии.</summary>
    public const string QueuePath = "/api/phone/queue";

    /// <summary>Адрес D5 — убрать один пункт очереди.</summary>
    public const string QueueRemovePath = "/api/phone/queue/remove";

    /// <summary>Срок ответа D1/D3/D5: один вызов движка (10 с) и сборка (контракт §1.5).</summary>
    public static readonly TimeSpan TaskDoorTimeout = TimeSpan.FromSeconds(12);

    /// <summary>Срок ответа D2: ДВА вызова движка (10 + 10) — поэтому не 15 с общей двери, а 22 (§1.5).</summary>
    public static readonly TimeSpan NewDoorTimeout = TimeSpan.FromSeconds(22);

    /// <summary>Срок ответа D4: baseline ≤ 3 с и закрытие потока ДО ответа (контракт §5.4).</summary>
    public static readonly TimeSpan QueueDoorTimeout = TimeSpan.FromSeconds(3.5);

    /// <summary>Сколько ждём первый кадр <c>baseline</c>, прежде чем сказать «не прочиталась».</summary>
    public static readonly TimeSpan QueueBaselineWait = TimeSpan.FromSeconds(3);

    /// <summary>Сколько чтений очереди идёт одновременно; сверх — <c>429</c> без открытия потока (§5.4).</summary>
    public const int MaxQueueReads = 4;

    /// <summary>Защёлка «одна отправка в полёте»: D1 — по сессии, D2 — по устройству (§7.2).</summary>
    private readonly PhoneTaskLatch _taskLatch = new();

    /// <summary>Карта повторов D2: <c>requestId → sessionId</c> (§3.5).</summary>
    private readonly PhoneNewMap _newMap = new();

    /// <summary>Сколько чтений очереди идёт прямо сейчас. Счёт под <c>Interlocked</c>: двери идут из разных ниток.</summary>
    private int _queueReads;

    /// <summary>Сколько пунктов очереди отброшено в прошлый раз — по видам, чтобы журнал не повторялся (§9.3).</summary>
    private int _queueDroppedShape = -1;
    private int _queueDroppedService = -1;

    /// <summary>Дверь чтения очереди (подстановка проверок — <see cref="PhoneControlDoors.None"/>).</summary>
    private PhoneControlDoors ControlDoors => _doors.Control ?? PhoneControlDoors.None;

    /// <summary>Это адрес одной из пяти дверей S3 — по нему выбираются ИХ слова, а не общие (§0.10).</summary>
    public static bool IsTaskDoor(string? path) =>
        string.Equals(path, PromptPath, StringComparison.Ordinal)
        || string.Equals(path, NewPath, StringComparison.Ordinal)
        || string.Equals(path, StopPath, StringComparison.Ordinal)
        || string.Equals(path, QueuePath, StringComparison.Ordinal)
        || string.Equals(path, QueueRemovePath, StringComparison.Ordinal);

    /// <summary>
    /// СЛОВА ДВЕРИ S3 — НА ЯЗЫКЕ ТЕЛЕФОНА (<see cref="Loc.TIn"/>), А НЕ ПАНЕЛИ (контракт §0.10).
    ///
    /// **Почему это отдельно от старых дверей.** У S1/S2 отказы отвечают на языке панели — это
    /// названная находка для t9, а не правка S3. У новой двери своего старого поведения нет: она
    /// сразу говорит на языке того, кто пришёл.
    /// </summary>
    private static string TaskWords(PhoneHttpRequest request, string key, params object[] args)
    {
        var words = Loc.TIn(Language(request), key);

        return args.Length == 0 ? words : string.Format(CultureInfo.CurrentCulture, words, args);
    }

    /// <summary>Отказ двери S3: <c>{"ok":false,"message":…}</c> и СВОЙ срок на запись ответа.</summary>
    private static PhoneHttpResponse S3Refuse(int status, string words, TimeSpan timeout) =>
        new(status, "application/json; charset=utf-8",
            "{\"ok\":false,\"message\":" + Quote(words) + "}", null, OwnTimeout: timeout);

    /// <summary>Успех двери S3: тело уже собрано, срок — свой.</summary>
    private static PhoneHttpResponse S3Json(int status, string body, TimeSpan timeout) =>
        new(status, "application/json; charset=utf-8", body, null, OwnTimeout: timeout);

    /// <summary>Отказ МЕТОДА на двери S3 — полной фразой S3, а не обрывком калитки (F-1).</summary>
    private PhoneHttpResponse TaskNotAllowed(PhoneHttpRequest request) =>
        S3Refuse(405, Loc.TIn(Language(request), nameof(PanelStrings.PhoneTaskNotAccepted)), TaskDoorTimeout);

    /// <summary>
    /// РАЗБОР НЕ УДАЛСЯ — <c>400</c> СВОИМ СЛОВОМ ПО ВИДУ БЕДЫ (контракт §2.4, §6.4):
    /// пустой текст, слишком длинный, плохая сессия, плохой пункт, неразобранное тело.
    /// </summary>
    private PhoneHttpResponse TaskBadBody(PhoneHttpRequest request, string problem, TimeSpan timeout)
    {
        return problem switch
        {
            PhoneTaskBody.ProblemEmpty =>
                S3Refuse(400, TaskWords(request, nameof(PanelStrings.PhoneTaskEmpty)), timeout),

            PhoneTaskBody.ProblemLong =>
                S3Refuse(400, TaskWords(request, nameof(PanelStrings.PhoneTaskTooLongFormat), PhoneTaskBody.MaxText), timeout),

            PhoneTaskBody.ProblemSession =>
                S3Refuse(400, TaskWords(request, nameof(PanelStrings.PhoneTaskBadSession)), timeout),

            _ => S3Refuse(400, TaskWords(request, nameof(PanelStrings.PhoneTaskBadRequest)), timeout),
        };
    }

    /// <summary>
    /// ПОЧЕМУ ДВИЖОК НЕ ПРИНЯЛ — СЛОВАМИ И БЕЗ КОДА (F-2).
    /// Число вроде «502» человеку ничего не говорит и выдаёт механику; причина называет одно из трёх.
    /// </summary>
    private static string TaskReason(PhoneHttpRequest request, PhoneEngineAnswer answer)
    {
        var language = Language(request);

        if (answer.Status != 0) return Loc.TIn(language, nameof(PanelStrings.PhoneTaskReasonRefused));

        return string.Equals(answer.Body, PanelStrings.PhoneGateNoEngine, StringComparison.Ordinal)
            ? Loc.TIn(language, nameof(PanelStrings.PhoneTaskReasonNoConnection))
            : Loc.TIn(language, nameof(PanelStrings.PhoneTaskReasonTimeout));
    }

    /// <summary>ЖУРНАЛ ДЕЙСТВИЯ: дверь, длина текста, код ответа и его исход — БЕЗ значений (§9.3).</summary>
    private void LogTask(string door, int textLength, PhoneEngineAnswer answer, PhoneEngineOutcome outcome)
    {
        var result = outcome.Code.Length > 0
            ? outcome.Code
            : outcome.Ok
                ? (outcome.Accepted ? "accepted" : "not-accepted")
                : answer.Status == 0 ? "silent" : "shape";

        _doors.Log(string.Format(
            CultureInfo.CurrentCulture, PanelStrings.PhoneTaskLogFormat, door, textLength, answer.Status, result));
    }

    /// <summary>
    /// D1 — <c>POST /api/phone/prompt</c>: поставить задачу в СУЩЕСТВУЮЩУЮ сессию (контракт §2).
    ///
    /// **Одно действие — один вызов движка.** Доводы собирает калитка и ровно те, что в §9.2;
    /// <c>requestId</c> идёт в движок КАК ЕСТЬ — на нём держится повтор (движок идемпотентен
    /// по <c>requestId</c>), а лишнее из тела телефона не уходит вовсе.
    /// </summary>
    private PhoneHttpResponse PromptDoor(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return S3Refuse(401, TaskWords(request, nameof(PanelStrings.PhoneTaskUnauthorized)), TaskDoorTimeout);

        var fields = PhoneTaskBody.Parse(request.Body, session: true, request: true, text: true, item: false);

        if (!fields.Ok) return TaskBadBody(request, fields.Problem, TaskDoorTimeout);

        // ЗАЩЁЛКА ПО СЕССИИ: два человека (или две вкладки) в одну сессию — вторая отправка ждёт.
        // Движок зовётся ТОЛЬКО после занятия места, иначе защёлка не значила бы ничего (DEF-072).
        if (!_taskLatch.TryTake(fields.SessionId, _doors.Clock()))
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneTaskLogFormat, "prompt-busy", fields.Text.Length, 0, "busy"));

            return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneTaskBusy)), TaskDoorTimeout);
        }

        try
        {
            var answer = _doors.Engine(
                PhoneDecisions.SessionPromptEndpoint,
                PhoneTaskArguments.Prompt(fields.SessionId, fields.RequestId, fields.Text));

            var outcome = PhoneEngineResult.Read(answer);

            LogTask("prompt", fields.Text.Length, answer, outcome);

            if (outcome.SubagentBound)
                return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneWebSubagentRefused)), TaskDoorTimeout);

            if (outcome.SessionGone)
                return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneTaskSessionGone)), TaskDoorTimeout);

            if (!outcome.Ok || !outcome.Accepted)
                return S3Refuse(
                    502,
                    TaskWords(request, nameof(PanelStrings.PhoneTaskNotTakenFormat), TaskReason(request, answer)),
                    TaskDoorTimeout);

            return S3Json(
                200,
                "{\"ok\":true,\"accepted\":true,\"sessionId\":" + Quote(fields.SessionId)
                + ",\"requestId\":" + Quote(fields.RequestId)
                + ",\"message\":" + Quote(TaskWords(request, nameof(PanelStrings.PhoneTaskAccepted))) + "}",
                TaskDoorTimeout);
        }
        finally
        {
            _taskLatch.Release(fields.SessionId);
        }
    }

    /// <summary>
    /// D2 — <c>POST /api/phone/new</c>: создать разговор и поставить в него задачу (контракт §3).
    ///
    /// **ДВА вызова движка** (<c>session/create</c> и <c>session/prompt</c>) — отсюда свой срок 22 с.
    /// **Папка не выбирается и телефону не показывается:** в доводах создания — пустой <c>request</c>,
    /// и рабочую папку берёт движок по умолчанию.
    /// </summary>
    private PhoneHttpResponse NewDoor(PhoneHttpRequest request)
    {
        if (!Authorized(request, out var deviceId))
            return S3Refuse(401, TaskWords(request, nameof(PanelStrings.PhoneTaskUnauthorized)), NewDoorTimeout);

        var fields = PhoneTaskBody.Parse(request.Body, session: false, request: true, text: true, item: false);

        if (!fields.Ok) return TaskBadBody(request, fields.Problem, NewDoorTimeout);

        // ЗАЩЁЛКА ПО УСТРОЙСТВУ: разговора ещё нет, а два разных `requestId` от двойного нажатия
        // родили бы ДВА разговора (§3.4, §7.2).
        var latch = "phone:" + deviceId;

        if (!_taskLatch.TryTake(latch, _doors.Clock()))
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneTaskLogFormat, "new-busy", fields.Text.Length, 0, "busy"));

            return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneTaskBusy)), NewDoorTimeout);
        }

        try
        {
            var repeated = _newMap.TryGet(fields.RequestId, _doors.Clock(), out var sessionId);

            if (!repeated)
            {
                var created = _doors.Engine(PhoneDecisions.SessionCreateEndpoint, PhoneTaskArguments.Create());
                var createdOutcome = PhoneEngineResult.Read(created);

                LogTask("new-create", 0, created, createdOutcome);

                if (!createdOutcome.Ok || !PhoneTaskBody.ValidId(createdOutcome.SessionId))
                    return S3Refuse(
                        502,
                        TaskWords(request, nameof(PanelStrings.PhoneTaskNewFailedFormat), TaskReason(request, created)),
                        NewDoorTimeout);

                sessionId = createdOutcome.SessionId;

                // ЗАПИСЬ СРАЗУ ПОСЛЕ СОЗДАНИЯ, ДО ЗАДАЧИ: если задача не принялась, повтор обязан
                // уйти в ЭТОТ разговор, а не создать второй (§3.4).
                _newMap.Put(fields.RequestId, sessionId, _doors.Clock());
            }

            var answer = _doors.Engine(
                PhoneDecisions.SessionPromptEndpoint,
                PhoneTaskArguments.Prompt(sessionId, fields.RequestId, fields.Text));

            var outcome = PhoneEngineResult.Read(answer);

            LogTask("new-prompt", fields.Text.Length, answer, outcome);

            if (outcome.SubagentBound)
                return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneWebSubagentRefused)), NewDoorTimeout);

            if (outcome.SessionGone)
                return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneTaskSessionGone)), NewDoorTimeout);

            if (!outcome.Ok || !outcome.Accepted)
                return S3Refuse(
                    502,
                    TaskWords(request, nameof(PanelStrings.PhoneTaskNotTakenFormat), TaskReason(request, answer)),
                    NewDoorTimeout);

            return S3Json(
                200,
                "{\"ok\":true,\"accepted\":true,\"sessionId\":" + Quote(sessionId)
                + ",\"requestId\":" + Quote(fields.RequestId)
                + ",\"repeated\":" + (repeated ? "true" : "false")
                + ",\"message\":" + Quote(TaskWords(request, nameof(PanelStrings.PhoneTaskNewAccepted))) + "}",
                NewDoorTimeout);
        }
        finally
        {
            _taskLatch.Release(latch);
        }
    }

    /// <summary>
    /// D3 — <c>POST /api/phone/stop</c>: отменить ТЕКУЩИЙ ХОД сессии (контракт §4).
    ///
    /// **Два честных исхода `200`:** <c>stopped</c> (движок сказал <c>accepted</c>) и <c>idle</c>
    /// («not attached» — останавливать нечего). Второй — НЕ ошибка: повтор нажатия «стоп» даёт
    /// ровно его, и человек читает «уже не работает», а не «не удалось» (§4.3).
    /// Очередь при этом сохраняется — это поведение движка (<c>keepInbox</c>), и дверь его не меняет.
    /// </summary>
    private PhoneHttpResponse StopDoor(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return S3Refuse(401, TaskWords(request, nameof(PanelStrings.PhoneTaskUnauthorized)), TaskDoorTimeout);

        var fields = PhoneTaskBody.Parse(request.Body, session: true, request: false, text: false, item: false);

        if (!fields.Ok) return TaskBadBody(request, fields.Problem, TaskDoorTimeout);

        var answer = _doors.Engine(
            PhoneDecisions.SessionCancelEndpoint, PhoneTaskArguments.Cancel(fields.SessionId));

        var outcome = PhoneEngineResult.Read(answer);

        LogTask("stop", 0, answer, outcome);

        if (outcome.SessionGone)
            return S3Json(
                200,
                "{\"ok\":true,\"stopped\":false,\"state\":\"idle\",\"message\":"
                + Quote(TaskWords(request, nameof(PanelStrings.PhoneStopIdle))) + "}",
                TaskDoorTimeout);

        if (outcome.SubagentBound)
            return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneWebSubagentRefused)), TaskDoorTimeout);

        if (outcome.Ok && outcome.Accepted)
            return S3Json(
                200,
                "{\"ok\":true,\"stopped\":true,\"state\":\"stopped\",\"message\":"
                + Quote(TaskWords(request, nameof(PanelStrings.PhoneStopDone))) + "}",
                TaskDoorTimeout);

        return S3Refuse(
            502,
            TaskWords(request, nameof(PanelStrings.PhoneStopFailedFormat), TaskReason(request, answer)),
            TaskDoorTimeout);
    }

    /// <summary>
    /// D4 — <c>GET /api/phone/queue?session=…</c>: очередь одной сессии (контракт §5).
    ///
    /// **Тело собирается АСИНХРОННО** (<c>Late</c>): очередь лежит в первом кадре потока
    /// <c>session/control</c>, а блокировать нитку синхронной двери нельзя (§0.10). Поток
    /// закрывается ДО ответа — он не переживает дверь (§5.4, M9).
    /// </summary>
    private PhoneHttpResponse QueueDoor(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return S3Refuse(401, TaskWords(request, nameof(PanelStrings.PhoneTaskUnauthorized)), QueueDoorTimeout);

        var sessionId = QueryValue(request.Query, "session");

        if (!PhoneLiveFrames.ValidSession(sessionId))
            return S3Refuse(400, TaskWords(request, nameof(PanelStrings.PhoneTaskBadSession)), QueueDoorTimeout);

        // ПОДЧИНЁННАЯ СЕССИЯ — 403: её переписку показывают только на компьютере (S1, §2.2).
        if (Sessions().TryRoot(sessionId, out _, out var subagent) && subagent)
            return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneWebSubagentRefused)), QueueDoorTimeout);

        // МЕСТО ЧТЕНИЯ ЗАНИМАЕТСЯ ЗДЕСЬ И ВОЗВРАЩАЕТСЯ ВСЕГДА (`Lease` в `ServeAsync`):
        // иначе пятое чтение отняло бы место у себя же.
        if (Interlocked.Increment(ref _queueReads) > MaxQueueReads)
        {
            Interlocked.Decrement(ref _queueReads);

            return S3Refuse(429, TaskWords(request, nameof(PanelStrings.PhoneQueueBusy)), QueueDoorTimeout);
        }

        var language = Language(request);

        return new PhoneHttpResponse(
            200, "application/json; charset=utf-8", string.Empty, null,
            Lease: new QueueRead(this),
            OwnTimeout: QueueDoorTimeout,
            Late: token => RunQueueAsync(token, sessionId, language));
    }

    /// <summary>
    /// САМО ЧТЕНИЕ ОЧЕРЕДИ: открыть поток, дождаться <c>baseline</c> ≤ 3 с, ЗАКРЫТЬ ПОТОК, собрать ответ.
    ///
    /// **Порядок назван не зря:** закрытие потока стоит ДО сборки и ДО ответа (§5.4). Иначе телефон
    /// получил бы очередь, а калитка продолжала бы держать <c>WS</c> у движка — и «живых потоков после
    /// ответа: 0» перестало бы быть правдой (M9).
    /// </summary>
    private async Task<PhoneHttpResponse> RunQueueAsync(CancellationToken token, string sessionId, string language)
    {
        var control = ControlDoors;

        if (!control.Present)
        {
            _doors.Log(string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, "no-door"));

            return S3Json(502, Words(language, nameof(PanelStrings.PhoneQueueUnreadable), 502), QueueDoorTimeout);
        }

        var frames = Channel.CreateBounded<string>(new BoundedChannelOptions(64)
        {
            SingleReader = true,
            SingleWriter = false,
            FullMode = BoundedChannelFullMode.DropOldest,
        });

        var link = control.Open(frame => frames.Writer.TryWrite(frame));

        if (link is null)
        {
            _doors.Log(string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, "open"));

            return S3Json(502, Words(language, nameof(PanelStrings.PhoneQueueUnreadable), 502), QueueDoorTimeout);
        }

        string? baseline = null;

        try
        {
            using var wait = CancellationTokenSource.CreateLinkedTokenSource(token);

            wait.CancelAfter(QueueBaselineWait);

            while (!wait.IsCancellationRequested)
            {
                string frame;

                try
                {
                    frame = await frames.Reader.ReadAsync(wait.Token).ConfigureAwait(false);
                }
                catch (OperationCanceledException)
                {
                    break;
                }
                catch (ChannelClosedException)
                {
                    break;
                }

                if (PhoneQueue.IsBaseline(frame))
                {
                    baseline = frame;

                    break;
                }

                if (!link.Alive) break;
            }
        }
        finally
        {
            // ПОТОК ЗАКРЫВАЕТСЯ ДО ОТВЕТА — обязанность калитки, а не движка (§5.4).
            link.Dispose();
        }

        if (baseline is null)
        {
            _doors.Log(string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, "baseline"));

            return S3Json(502, Words(language, nameof(PanelStrings.PhoneQueueUnreadable), 502), QueueDoorTimeout);
        }

        var view = PhoneQueue.Read(baseline, sessionId, Loc.TIn(language, nameof(PanelStrings.PhoneQueueNoLive)));

        if (!view.Ok)
        {
            _doors.Log(string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, view.Error));

            return S3Json(502, Words(language, nameof(PanelStrings.PhoneQueueUnreadable), 502), QueueDoorTimeout);
        }

        _doors.Log(string.Format(
            CultureInfo.CurrentCulture,
            PanelStrings.PhoneQueueReadLogFormat,
            view.LiveSessions,
            view.Total,
            view.DroppedShape + view.DroppedService + view.Trimmed));

        if (view.DroppedShape != _queueDroppedShape || view.DroppedService != _queueDroppedService)
        {
            _queueDroppedShape = view.DroppedShape;
            _queueDroppedService = view.DroppedService;

            _doors.Log(string.Format(
                CultureInfo.CurrentCulture,
                PanelStrings.PhoneRecordsDroppedLogFormat,
                view.DroppedShape + view.DroppedService,
                view.Total + view.DroppedShape + view.DroppedService));
        }

        return S3Json(200, view.Json, QueueDoorTimeout);
    }

    /// <summary>Слова по ключу на ЯЗЫКЕ ТЕЛЕФОНА — одним местом (для ответов, собранных не из запроса).</summary>
    private static string Words(string language, string key, params object[] args)
    {
        var words = Loc.TIn(language, key);

        return args.Length == 0 ? words : string.Format(CultureInfo.CurrentCulture, words, args);
    }

    /// <summary>МЕСТО ЧТЕНИЯ ОЧЕРЕДИ: возвращается ровно один раз, когда ответ закончился.</summary>
    private sealed class QueueRead : IDisposable
    {
        private PhoneGate? _gate;

        public QueueRead(PhoneGate gate) => _gate = gate;

        public void Dispose()
        {
            var gate = Interlocked.Exchange(ref _gate, null);

            if (gate is not null) Interlocked.Decrement(ref gate._queueReads);
        }
    }

    /// <summary>
    /// D5 — <c>POST /api/phone/queue/remove</c>: убрать ОДИН пункт очереди (контракт §6).
    ///
    /// **«Убрано» и «уже нет» одинаково успешны.** Код движка <c>session/queue-item-not-found</c>
    /// значит «пункта уже нет» (его взяли в работу или убрали на компьютере) — человек хотел, чтобы
    /// пункта не было, и его нет: <c>200 gone</c>, а не ошибка (§6.3). Код в слова не попадает.
    /// </summary>
    private PhoneHttpResponse QueueRemoveDoor(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return S3Refuse(401, TaskWords(request, nameof(PanelStrings.PhoneTaskUnauthorized)), TaskDoorTimeout);

        var fields = PhoneTaskBody.Parse(request.Body, session: true, request: false, text: false, item: true);

        if (!fields.Ok) return TaskBadBody(request, fields.Problem, TaskDoorTimeout);

        var answer = _doors.Engine(
            PhoneDecisions.SessionQueueEndpoint, PhoneTaskArguments.Remove(fields.SessionId, fields.ItemId));

        var outcome = PhoneEngineResult.Read(answer);

        LogTask("remove", 0, answer, outcome);

        if (outcome.ItemGone)
            return S3Json(
                200,
                "{\"ok\":true,\"state\":\"gone\",\"message\":"
                + Quote(TaskWords(request, nameof(PanelStrings.PhoneQueueAlreadyGone))) + "}",
                TaskDoorTimeout);

        if (outcome.SubagentBound)
            return S3Refuse(403, TaskWords(request, nameof(PanelStrings.PhoneWebSubagentRefused)), TaskDoorTimeout);

        if (outcome.Ok && outcome.Accepted)
            return S3Json(
                200,
                "{\"ok\":true,\"state\":\"removed\",\"message\":"
                + Quote(TaskWords(request, nameof(PanelStrings.PhoneQueueRemoved))) + "}",
                TaskDoorTimeout);

        return S3Refuse(
            502,
            TaskWords(request, nameof(PanelStrings.PhoneQueueRemoveFailedFormat), TaskReason(request, answer)),
            TaskDoorTimeout);
    }

    /// <summary>
    /// КОРЕНЬ КАЛИТКИ — И ЭТО СТРАНИЦА (этап F2).
    ///
    /// ⚠️ **Без cookie — прежняя страница ВХОДА, с cookie — СТРАНИЦА ТЕЛЕФОНА.** Это не две двери,
    /// а одна: кто ещё не сопряжён, получает вход; кто свой — работу. Второго адреса телефону
    /// не заводится: он должен знать ОДИН адрес, и он у него уже есть (QR и слова раздела).
    ///
    /// Язык берётся у САМОГО телефона (<see cref="PhoneGateLanguages"/>), а не у панели: у телефона
    /// свой язык, и он говорит его заголовком <c>Accept-Language</c>.
    /// </summary>
    private PhoneHttpResponse Page(PhoneHttpRequest request)
    {
        var language = Language(request);

        return Authorized(request, out var deviceId)
            ? PhoneHttpResponse.Html(PhonePage.Html(language, View(deviceId)))
            : PhoneHttpResponse.Html(PhoneLoginPage.Html(language));
    }

    /// <summary>
    /// ОБОЛОЧКА ПУЛЬТА — ТО, ЧТО ОТДАЁТСЯ НА КОРНЕ (`/`), и это новая поверхность S1+S2.
    ///
    /// **Слова и язык — наши:** `boot.words` собирается из словарей панели на языке телефона
    /// (`Accept-Language`), а `data-boot` уходит в АТРИБУТ, поэтому экранируется как атрибут.
    /// **Вход — дверью, как раньше:** кто не сопряжён, получает `authed:false` и экран входа;
    /// сервер ничего не решает за React, кроме правды о входе.
    /// </summary>
    private PhoneHttpResponse Shell(PhoneHttpRequest request)
    {
        var language = Language(request);
        var authed = Authorized(request, out var deviceId);
        var html = PhoneWeb.Shell(language, authed, authed ? DeviceName(deviceId) : string.Empty);

        if (html is null)
        {
            // СБОРКА НЕПОЛНА: оболочки нет в exe. Говорим словами и пишем в журнал — пустой
            // страницы тут быть не должно: человек прочитал бы «тут ничего нет» про свою панель.
            _doors.Log(Loc.T(PanelStrings.PhoneWebCrash));

            return PhoneHttpResponse.Words(500, false, Loc.T(PanelStrings.PhoneWebCrash));
        }

        // НОВАЯ ПОВЕРХНОСТЬ — СВОЯ ПОЛИТИКА (не только `frame-ancestors`): скрипты — только свои,
        // соединения — только свои (fetch/EventSource), внешних ресурсов ноль.
        return new PhoneHttpResponse(
            200, "text/html; charset=utf-8", html, null, null,
            Headers: new[] { ("Content-Security-Policy", PhoneWeb.Csp) });
    }

    /// <summary>ИМЯ УСТРОЙСТВА ДЛЯ ПУЛЬТА: из записи пропуска по cookie, а не из доводов запроса.</summary>
    private string DeviceName(string deviceId)
    {
        var name = PhonePass.Load(_doors.Pass).SafeDevices
            .FirstOrDefault(device => string.Equals(device.Id, deviceId, StringComparison.OrdinalIgnoreCase))
            ?.Name ?? string.Empty;

        return PhoneDecisions.DeviceDisplay(name, Loc.T(PanelStrings.PhonePageDeviceFallback));
    }

    /// <summary>
    /// ФАЙЛ ПУЛЬТА — ОДНИМ РЕСУРСОМ СБОРКИ. Имя сверяется с именами вложенных один в один
    /// (`PhoneWeb.Asset`), поэтому «похожего» файла не ищется и выйти из каталога нечем.
    /// Кэш — надолго: имя файла содержит хеш содержимого.
    /// </summary>
    private PhoneHttpResponse AssetFile(string name)
    {
        var body = PhoneWeb.Asset(name, out var contentType);

        if (body is null)
        {
            return PhoneHttpResponse.Words(
                404, false,
                string.Format(
                    CultureInfo.CurrentCulture, PanelStrings.PhoneGateNotFoundFormat, PhoneWeb.AssetPath + name));
        }

        return new PhoneHttpResponse(
            200, contentType, body, null, null,
            Headers: new[]
            {
                ("Cache-Control", PhoneWeb.AssetCache),
                ("Content-Security-Policy", PhoneWeb.Csp),
            });
    }

    /// <summary>
    /// ТА ЖЕ ЗАПИСЬ, НО С ИМЕНЕМ УСТРОЙСТВА (решение владельца 12.10.2026): страница говорит
    /// человеку, каким устройством он вошёл, — с двух телефонов иначе не отличить, чей это экран
    /// и чей ответ уйдёт движку. Имя берётся ИЗ COOKIE (`Authorized`), а не из доводов запроса:
    /// подставить чужое телефон не может.
    ///
    /// ⚠️ **Показывается КОРОТКОЕ ИМЯ ТЕЛЕФОНА, а не внутренний `phone-N`** (решение владельца
    /// 12.10.2026): имя разобрано из <c>User-Agent</c> при сопряжении и лежит в записи устройства.
    /// Телефон себя не назвал — страница говорит честное «телефон» (`PhonePageDeviceFallback`),
    /// а не номер, которого человек не выбирал.
    /// </summary>
    private PhonePageView View(string deviceId)
    {
        var name = PhonePass.Load(_doors.Pass).SafeDevices
            .FirstOrDefault(device => string.Equals(device.Id, deviceId, StringComparison.OrdinalIgnoreCase))
            ?.Name ?? string.Empty;

        return View() with
        {
            Device = PhoneDecisions.DeviceDisplay(name, Loc.T(PanelStrings.PhonePageDeviceFallback)),
        };
    }

    /// <summary>Язык телефона — по <c>Accept-Language</c>, а не по языку панели (см. <see cref="Page"/>).</summary>
    private static string Language(PhoneHttpRequest request) =>
        PhoneGateLanguages.For(request.Language, Loc.Language);

    /// <summary>
    /// ЧТО СТРАНИЦА ПОКАЗЫВАЕТ ПРЯМО СЕЙЧАС — одной записью, по состоянию калитки.
    ///
    /// ⚠️ Порядок решений назван: ВИСЯЩИЙ ВОПРОС главнее «чем кончился прошлый», потому что
    /// за время, пока человек читал ответ, мог прийти новый вопрос — и показать ему «вы ответили»
    /// вместо нового вопроса значило бы потерять работу агента.
    ///
    /// ⚠️ **ОДИН ВОПРОС НА ЭКРАН — вариант A** (решение владельца 11.10.2026): странице отдаётся
    /// РОВНО ОДИН вопрос — тот, на который человек отвечает сейчас, — а строку «Вопрос N из M»
    /// она собирает из <see cref="PhonePageView.Screen"/> и <see cref="PhonePageView.Total"/>.
    /// Полный набор накапливает калитка (<see cref="_screen"/>), а не страница.
    ///
    /// ⚠️ Вопрос, который не разобрался (`PhonePage.Parse` вернул пусто), показывается как
    /// <see cref="PhonePageKind.Unreadable"/>: отвечать без вопроса нечем, а «вопросов нет» было бы
    /// неправдой — телефон ждал бы, глядя на висящий вопрос.
    /// </summary>
    private PhonePageView View()
    {
        lock (_gate)
        {
            if (_question is not null)
            {
                var questions = PhonePage.Parse(_question.Questions);

                if (questions.Count == 0)
                    return new PhonePageView(PhonePageKind.Unreadable, _question.EventId, questions, true);

                // ЭКРАН — ПЕРВЫЙ НЕОТВЕЧЕННЫЙ, и он же запоминается как текущий: на него смотрит
                // сверка формы в `AnswerScreen`. Человек мог вернуться на прежний экран, но
                // показано ему то, что он ещё не отвечал.
                var screen = NextScreen(questions);

                _screen = screen;

                // ЖИВОЕ ОБНОВЛЕНИЕ У ВОПРОСА ЕСТЬ, и это не возврат прежнего дефекта: подмена
                // карточки ломала выбор только у meta refresh (перезагрузка стирала форму).
                // Здесь карточка подменяется ЦЕЛИКОМ заново, ответы с прошлых экранов лежат в
                // калитке (`_screenAnswers`), а пока человек пишет свой ответ — опрос приостановлен.
                return new PhonePageView(
                    PhonePageKind.Question,
                    _question.EventId,
                    new[] { questions[screen] },
                    true,
                    string.Empty,
                    screen,
                    questions.Count,
                    Answered(questions[screen].Id));
            }

            return _outcome switch
            {
                QuestionOutcome.Answered => PhonePageView.Outcome(PhonePageKind.Answered),
                QuestionOutcome.Taken => PhonePageView.Outcome(PhonePageKind.Taken),
                QuestionOutcome.Cancelled => PhonePageView.Outcome(PhonePageKind.Cancelled),

                // СНЯТО ПО ПРЕДЕЛУ (B-05): человеку страница говорит те же слова, что и после
                // отмены с телефона («ход агента отменён»), — и это ПРАВДА. Своё состояние на
                // странице («ответа не было N минут») потребовало бы нового вида страницы и её
                // разметки; причина названа машинной дверью (`GET /question`), отказом на ответ
                // и строкой в журнале, а не выдуманным видом экрана.
                QuestionOutcome.NoAnswer => PhonePageView.Outcome(PhonePageKind.Cancelled),

                // СВЯЗИ С СЕРВЕРОМ DSH НЕТ — И ЭТО НАДО СКАЗАТЬ, А НЕ ЖДАТЬ МОЛЧА (решение
                // владельца 13.10.2026, вариант «а»). Прежняя страница в этом положении говорила
                // «панель на связи и ждёт вопроса от агента» — обещала вопрос, которому неоткуда
                // взяться: двери к событиям движка нет вовсе (пустая ссылка входа — сервер поднят
                // не панелью). Своё состояние вместо обещания, и оно же проверяемо.
                _ when !_doors.Events.Present => PhonePageView.NoEngine(),

                _ => PhonePageView.Waiting(),
            };
        }
    }

    /// <summary>
    /// ЧТО НА ЭТОМ ЭКРАНЕ УЖЕ ОТВЕЧЕНО — по `id` вопроса. Один ответ и не больше: экран
    /// показывает ровно один вопрос. Пусто — человек ещё ничего не выбрал и не написал.
    /// </summary>
    private IReadOnlyDictionary<string, string> Answered(string questionId)
    {
        var answers = new Dictionary<string, string>(StringComparer.Ordinal);

        if (_screenAnswers.TryGetValue(questionId, out var answer)) answers[questionId] = answer;

        return answers;
    }

    /// <summary>
    /// КАКОЙ ЭКРАН ПОКАЗЫВАТЬ: ПЕРВЫЙ, НА КОТОРЫЙ ЧЕЛОВЕК ЕЩЁ НЕ ОТВЕЧАЛ.
    ///
    /// **Почему так, а не «сдвиг после удачи».** Удача у вопроса ОДНА: ответ уходит движку одним
    /// вызовом (`$events/result`), когда отвечены ВСЕ экраны. Между экранами никакой удачи нет,
    /// и сдвигать счётчик было бы нечем — а сдвиг при отказе движка потерялся бы, и человек
    /// застрял бы на отвеченном экране. Спросить «чего ещё не хватает» надёжнее: состояние одно
    /// (накопленные ответы), и оно же — правда о том, что показывать.
    ///
    /// Все отвечены — показывается ПЕРВЫЙ: это состояние «вот-вот уйдёт целиком» и одновременно
    /// «человек может поправить первый ответ», а не пустой экран.
    /// </summary>
    private int NextScreen(IReadOnlyList<PhoneQuestion> questions)
    {
        for (var index = 0; index < questions.Count; index++)
        {
            if (!_screenAnswers.ContainsKey(questions[index].Id)) return index;
        }

        return 0;
    }

    /// <summary>
    /// БЕДА СЛОВАМИ — СТРАНИЦЕЙ, а не текстом: телефон показывает ответ целиком, и «Ответ не
    /// отправлен: …» обязан быть страницей, а не голой строкой. Путь из беды у страницы есть —
    /// «Повторить» ссылкой на корень.
    /// </summary>
    private static PhoneHttpResponse Problem(string language, int status, string words) =>
        new(status, "text/html; charset=utf-8", PhonePage.Html(language, PhonePageView.Problem(words)), null);

    private PhoneHttpResponse Pair(PhoneHttpRequest request)
    {
        var language = PhoneGateLanguages.For(request.Language, Loc.Language);

        // ⚠️ ФОРМА ИЛИ JSON — как и у ответа: страница входа шлёт ОБЫЧНУЮ форму (скрипта на ней
        // больше нет), а машинный путь остался для проверок и скриптов. Форме отвечают СТРАНИЦЕЙ
        // (успех — перенаправлением на корень, беда — страницей входа со словами), JSON — словами.
        var form = !LooksJson(request.Body);

        // ЧТО ЧЕЛОВЕК НАБРАЛ — читается ДО всяких решений: и «не та форма кода», и «пауза после
        // перебора» возвращают его на страницу с тем же набранным (норма GOV.UK: форма приходит
        // «as the user filled them in»; `30-mobile-web.md` §4).
        var typed = form ? PhoneAnswer.Field(request.Body, "code") : null;
        var typedCode = (typed ?? string.Empty).Trim();

        // ⚠️ СТРАНИЦА БЕДЫ СТАВИТСЯ С ТЕМ ЖЕ КОДОМ, ЧТО И СЛОВА: отказ обязан быть отказом и по
        // коду ответа тоже, а не «200 со страницей, на которой написано, что не пустили». Тем же
        // правилом живёт страница беды у формы ответа (`Problem`).
        PhoneHttpResponse Say(int status, bool ok, string words) =>
            form
                ? PhoneHttpResponse.Html(PhoneLoginPage.Html(language, ok ? string.Empty : words, typedCode))
                    with { Status = status }
                : PhoneHttpResponse.Words(status, ok, words);

        var now = _doors.Clock();
        var address = PhoneDecisions.AddressOf(request.Address);

        // (1) ЛИМИТЫ. Спрашиваются ДО разбора кода: перебор обязан упираться в паузу, а не
        //     получать «ещё одну попытку угадать».
        var verdict = PhoneDecisions.DecideAttempt(_attempts, address, now);

        if (!verdict.Allowed) return Say(429, false, verdict.Text());

        // Поле формы `code` — тем же разбором, что и поля ответа: значение раскодируется, а «не та
        // форма» (не шесть цифр) остаётся ОТДЕЛЬНЫМ отказом от «не тот код».
        var code = form
            ? PhoneDecisions.CodeValid(typedCode) ? typedCode : null
            : CodeOf(request.Body);

        if (code is null)
        {
            Remember(address, now);
            return Say(403, false, Loc.T(PanelStrings.PhoneGateCodeWrongShape));
        }

        Pairing? pairing;

        lock (_gate) pairing = _pairing;

        if (pairing is null)
        {
            Remember(address, now);
            return Say(403, false, Loc.T(PanelStrings.PhoneGateNoCode));
        }

        if (!PhoneDecisions.CodeAlive(now, pairing.ExpiresAt))
        {
            Remember(address, now);
            return Say(403, false, Loc.T(PanelStrings.PhoneGateCodeExpired));
        }

        if (!PhoneDecisions.CodeMatches(code, pairing.Code))
        {
            Remember(address, now);
            return Say(403, false, Loc.T(PanelStrings.PhoneGateBadCode));
        }

        // (2) УСПЕХ. КОД УМИРАЕТ ПЕРВЫМ ДЕЛОМ — до записи пропуска: не запишись файл, человек
        //     получит отказ и возьмёт новый код, а не сможет войти тем же (подсмотренным) кодом.
        lock (_gate) _pairing = null;

        // ⚠️ ЧТЕНИЕ-ИЗМЕНЕНИЕ-ЗАПИСЬ ПОД ЗАМКОМ ПРОПУСКА (дефект CH-01): имя устройства считается
        // ПО ЧИСЛУ записанных, поэтому два одновременных сопряжения без замка выбрали бы одно имя
        // и затёрли друг друга. Дверь при этом уже не мешает: файл читается с разрешением на
        // запись (`PhonePassFiles.OpenRead`), а пишется во временный файл и переименовывается.
        string device;
        PhonePass pass;

        lock (_pass)
        {
            device = DeviceIdFor(PhonePass.Load(_doors.Pass).DeviceCount);

            // ⚠️ ЗАВОДИТСЯ НОВОЕ УСТРОЙСТВО, А НЕ НОВЫЙ ПРОПУСК: `WithNewDevice`, а не `Create`.
            // Иначе каждое сопряжение стирало бы прежние устройства, и «список подключённых» всегда
            // состоял бы из одного — человек увидел бы, что второй телефон отвязал первый.
            pass = PhonePass.Load(_doors.Pass).WithNewDevice(
                device, address, PricingDecisions.Stamp(now), PhoneDecisions.DeviceName(request.UserAgent));

            if (!pass.Save(_doors.Pass))
            {
                // Пропуск в памяти никому не нужен: он не переживёт перезапуск панели, и телефон
                // остался бы с cookie, которой на следующем запуске не соответствует ничего.
                // ПРИЧИНА отказа уже в журнале — её пишет `PhonePass.Save` (`PhonePassSaveFailedLogFormat`).
                return Say(500, false, Loc.T(PanelStrings.PhoneGatePassNotSaved));
            }
        }

        var signature = pass.DeviceSignature(device);

        if (signature.Length == 0) return Say(500, false, Loc.T(PanelStrings.PhoneGatePassNotSaved));

        // СЛЕД В ЖУРНАЛЕ: телефон сопряжён. Имя устройства (`phone-1`) и адрес, с которого он
        // пришёл, — НЕ пропуск и НЕ подпись: пропуск машины не покидает, а подпись не показывается
        // никому и никогда (уточнение владельца 11.10.2026: «следы без секретов»).
        _doors.Log(string.Format(
            CultureInfo.CurrentCulture, PanelStrings.PhoneGatePairedLogFormat, device, address));

        var cookie = SetCookie(CookieValue(device, signature));

        // ФОРМЕ — ПЕРЕНАПРАВЛЕНИЕ НА КОРЕНЬ: cookie уже стоит, и человек попадает на страницу
        // телефона (F5 не повторит отправку кода). Машинному пути — слова и cookie, как было.
        return form
            ? PhoneHttpResponse.Redirect(PhoneGateRoot) with { Cookie = cookie }
            : PhoneHttpResponse.Words(200, true, Loc.T(PanelStrings.PhoneGatePaired)) with { Cookie = cookie };
    }

    /// <summary>Код из тела <c>{"code":"123456"}</c>. <c>null</c> — тела нет, оно не JSON или поле
    /// не строка; «не та форма» и «не тот код» — РАЗНЫЕ отказы, и человеку они говорят разное.</summary>
    private static string? CodeOf(string body)
    {
        if (string.IsNullOrWhiteSpace(body)) return null;

        try
        {
            using var document = JsonDocument.Parse(body);

            if (document.RootElement.ValueKind != JsonValueKind.Object) return null;
            if (!document.RootElement.TryGetProperty("code", out var code)) return null;
            if (code.ValueKind != JsonValueKind.String) return null;

            var text = code.GetString() ?? string.Empty;

            return PhoneDecisions.CodeValid(text) ? text : null;
        }
        catch
        {
            return null;
        }
    }

    /// <summary>
    /// ЧТО ВИСИТ ПРЯМО СЕЙЧАС. Отдаются ТОЛЬКО `eventId` и `questions` — и ничего из кадра `ready`:
    /// в нём лежит домашний каталог машины, и телефону его показывать нечего (замер §3).
    /// </summary>
    private PhoneHttpResponse Question(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return PhoneHttpResponse.Words(401, false, Loc.T(PanelStrings.PhoneGateUnauthorized));

        lock (_gate)
        {
            if (_question is not null)
            {
                // ТОЛЬКО РАЗРЕШЁННЫЕ ПОЛЯ И ЗДЕСЬ (S2, контракт §2.3): сырые вопросы кадра
                // несут `intent` и служебные поля движка. Эта дверь остаётся для старой страницы
                // и проверок, но белый список на калитке ОДИН — React ходит в `/api/phone/question`.
                if (!PhoneQuestionCards.TryBuild(_question.Questions, out var card, out _))
                {
                    return PhoneHttpResponse.Json(
                        200,
                        "{\"state\":\"unreadable\",\"eventId\":" + Quote(_question.EventId)
                            + ",\"message\":" + Quote(Loc.T(PanelStrings.PhonePageUnreadable)) + "}");
                }

                return PhoneHttpResponse.Json(
                    200,
                    "{\"state\":\"question\",\"eventId\":" + Quote(_question.EventId)
                        + ",\"questions\":" + card + "}");
            }

            // ЧЕМ КОНЧИЛСЯ ПРЕДЫДУЩИЙ — говорится и здесь, машинной дверью (`GET /question`
            // остаётся ею для проверок и для тех, кто читает JSON). ⚠️ Слова одни и те же для
            // всех исходов НАМЕРЕННО: менять их значило бы менять поведение двери, которую уже
            // стерегут проверки самотеста. Разные слова человеку говорит СТРАНИЦА (F2) — по
            // <see cref="_outcome"/>.
            //
            // ⚠️ ОДНО ИСКЛЮЧЕНИЕ — ПРЕДЕЛ ОЖИДАНИЯ (B-05): «на него уже ответили» было бы
            // неправдой, когда вопрос сняла сама калитка, потому что человек не ответил вовсе.
            if (_outcome == QuestionOutcome.NoAnswer)
            {
                return PhoneHttpResponse.Json(
                    200,
                    "{\"state\":\"cancelled\",\"message\":" + Quote(NoAnswerWords()) + "}");
            }

            if (_outcome != QuestionOutcome.None)
            {
                return PhoneHttpResponse.Json(
                    200,
                    "{\"state\":\"cancelled\",\"message\":"
                        + Quote(Loc.T(PanelStrings.PhoneGateQuestionCancelled)) + "}");
            }

            return PhoneHttpResponse.Json(
                200,
                "{\"state\":\"none\",\"message\":" + Quote(Loc.T(PanelStrings.PhoneGateNoQuestionNow)) + "}");
        }
    }

    /// <summary>
    /// ОЖИДАЮЩИЙ ВОПРОС ДЛЯ ПУЛЬТА — <c>GET /api/phone/question</c> (S2, контракт §2.3).
    ///
    /// **Только чтение и только разрешённое.** Наружу уходят `eventId`, карточки вопросов
    /// (id/question/detail/header/options[{label,description}]/multiSelect), `sessionId`
    /// (КОРНЕВАЯ сессия — вопрос подчинённого приезжает карточкой в неё, а не отдельным экраном),
    /// `fromSubagent`, `expiresAt` и `remainingSeconds`. НЕ уходят: `clientId`, cookie движка,
    /// `agentId` и `intent`.
    ///
    /// **Состояние — это ответ, а не ошибка:** вопроса нет — `none`, ответили — `answered`,
    /// взял другой — `taken`, сняли — `cancelled`, снят по пределу — `no-answer`,
    /// не уложился в пределы — `unreadable` (контракт §2.3).
    /// </summary>
    private PhoneHttpResponse PhoneQuestion(PhoneHttpRequest request)
    {
        if (!Authorized(request, out _))
            return PhoneHttpResponse.Words(401, false, Loc.T(PanelStrings.PhoneGateUnauthorized));

        string eventId, questions, agentId;
        DateTimeOffset at;
        QuestionOutcome outcome;
        string lastEventId;

        lock (_gate)
        {
            eventId = _question?.EventId ?? string.Empty;
            questions = _question?.Questions ?? "[]";
            agentId = _question?.AgentId ?? string.Empty;
            at = _question?.At ?? _doors.Clock();
            outcome = _outcome;
            lastEventId = _lastEventId;
        }

        if (eventId.Length == 0)
        {
            return outcome switch
            {
                QuestionOutcome.Answered => QuestionState(
                    "answered", lastEventId, Loc.T(PanelStrings.PhonePageAnswered)),
                QuestionOutcome.Taken => QuestionState(
                    "taken", lastEventId, Loc.T(PanelStrings.PhonePageTaken)),
                QuestionOutcome.Cancelled => QuestionState(
                    "cancelled", lastEventId, Loc.T(PanelStrings.PhonePageCancelled)),
                QuestionOutcome.NoAnswer => QuestionState("no-answer", lastEventId, NoAnswerWords()),
                _ => QuestionState("none", string.Empty, Loc.T(PanelStrings.PhoneGateNoQuestionNow)),
            };
        }

        if (!PhoneQuestionCards.TryBuild(questions, out var cards, out var problem))
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneQuestionUnreadableLogFormat, problem));

            return QuestionState("unreadable", eventId, Loc.T(PanelStrings.PhonePageUnreadable));
        }

        var (root, subagent) = ResolveQuestionSession(eventId, agentId);

        var now = _doors.Clock();
        var left = (int)Math.Max(0, (at + QuestionWaitLimit - now).TotalSeconds);

        var json = new StringBuilder("{\"state\":\"question\",\"eventId\":");
        json.Append(Quote(eventId));
        json.Append(",\"sessionId\":").Append(Quote(root));
        json.Append(",\"fromSubagent\":").Append(subagent ? "true" : "false");
        json.Append(",\"questions\":").Append(cards);
        json.Append(",\"expiresAt\":").Append(Quote((at + QuestionWaitLimit).ToString("o", CultureInfo.InvariantCulture)));
        json.Append(",\"remainingSeconds\":").Append(left.ToString(CultureInfo.InvariantCulture));
        json.Append('}');

        return PhoneHttpResponse.Json(200, json.ToString());
    }

    /// <summary>ОТВЕТ-СОСТОЯНИЕ: <c>{state,eventId?,message}</c> — без кода движка и без подсказок.</summary>
    private static PhoneHttpResponse QuestionState(string state, string eventId, string words)
    {
        var json = "{\"state\":" + Quote(state)
            + (eventId.Length > 0 ? ",\"eventId\":" + Quote(eventId) : string.Empty)
            + ",\"message\":" + Quote(words) + "}";

        return PhoneHttpResponse.Json(200, json);
    }

    /// <summary>
    /// КОРЕНЬ ВОПРОСА — СНИМОК НА ОДИН ВОПРОС. Ответ подчинённого приходит карточкой в КОРНЕВУЮ
    /// сессию (контракт §2.3); сам `agentId` наружу не уходит никогда. Снимок нужен потому, что
    /// телефон опрашивает часто, а `session/list` — тяжёлый ответ.
    /// </summary>
    private (string Root, bool Subagent) ResolveQuestionSession(string eventId, string agentId)
    {
        lock (_gate)
        {
            if (string.Equals(_questionRootEvent, eventId, StringComparison.Ordinal))
                return (_questionRoot, _questionSubagent);
        }

        var root = string.Empty;
        var subagent = false;

        if (agentId.Length > 0)
        {
            var index = Sessions();

            if (index.TryRoot(agentId, out var found, out var sub))
            {
                root = found;
                subagent = sub;
            }
            else
            {
                // ЗНАНИЯ НЕ ХВАТИЛО: карточка всё равно показывается, но строку списка не называет
                // (контракт §2.3: `sessionId:""`, карточка в списке — fallback).
                subagent = true;
            }
        }

        lock (_gate)
        {
            _questionRootEvent = eventId;
            _questionRoot = root;
            _questionSubagent = subagent;
        }

        return (root, subagent);
    }

    /// <summary>
    /// ОТВЕТ НА ВОПРОС АГЕНТА — ДВУМЯ ПУТЯМИ, И ОБА ИДУТ ЧЕРЕЗ НАС (этап F2).
    ///
    /// * **СТРАНИЦА ТЕЛЕФОНА** шлёт ФОРМУ (`application/x-www-form-urlencoded`: `eventId` и выборы
    ///   `q0`, `q1`, …). ⚠️ Подписи вариантов калитка берёт ИЗ СВОЕГО вопроса, а не из формы:
    ///   телефон присылает НОМЕР варианта, поэтому подделать ответ он не может. Ответ формы —
    ///   СТРАНИЦА, а не строка: телефон показывает её целиком;
    /// * **МАШИННЫЙ путь** шлёт JSON `{eventId, answers}` — он остаётся для проверок и для тех,
    ///   кто читает JSON, и отвечает он словами, как отвечал.
    ///
    /// `clientId` и cookie движка подставляет калитка: телефону вход в движок не показывается
    /// и знать его не нужно.
    ///
    /// ⚠️ **ОТВЕТ УХОДИТ ОДИН РАЗ.** Два нажатия на странице приходят ДВУМЯ запросами в разных
    /// задачах (<c>Task.Run</c> в цикле приёма), поэтому между «взял вопрос» и «ушёл в движок»
    /// стоит <see cref="_answering"/>: второй запрос получает СЛОВА, а не второй ответ движку.
    /// </summary>
    private PhoneHttpResponse Answer(PhoneHttpRequest request)
    {
        var language = PhoneGateLanguages.For(request.Language, Loc.Language);

        // ФОРМА ИЛИ JSON — решает ФОРМА ТЕЛА, а не заголовок: заголовков калитка хранит три
        // и только три (`Cookie`, `Accept-Language`, адрес), а `Content-Type` в них нет.
        // JSON начинается с `{` — значит это машинный путь; всё прочее пробуем разобрать формой.
        //
        // ⚠️ **Разбор — это ещё не «наша форма».** Тело `eventId=…` БЕЗ имени выбора (`q0`) тоже
        // разбирается, но формой ОТВЕТА не является: им отвечает `POST /cancel`. Поэтому
        // `PhoneAnswer.ParseForm` отказывает, когда экран не назван, а «форма ли это» решается
        // ЗДЕСЬ — тем, разобралось ли тело целиком (<see cref="LooksForm"/>).
        var fields = LooksJson(request.Body) ? null : PhoneAnswer.ParseForm(request.Body);
        var form = PhoneAnswer.LooksForm(request.Body);

        // ⚠️ ОТКАЗ ФОРМЕ — ТОЖЕ СТРАНИЦА (решение владельца 11.10.2026): сырой JSON человек
        // на телефоне видеть не должен НИКОГДА, а форма шлётся именно человеком.
        if (!Authorized(request, out var deviceId))
        {
            return form
                ? Problem(language, 401, Loc.T(PanelStrings.PhoneGateUnauthorized))
                : PhoneHttpResponse.Words(401, false, Loc.T(PanelStrings.PhoneGateUnauthorized));
        }

        // «СЛОВАМИ ИЛИ СТРАНИЦЕЙ» — одним решением: у формы и у машинного пути слова одни и те же,
        // а вот ответ разный, и разойтись они не должны. ⚠️ Здесь же остаётся СЛЕД В ЖУРНАЛЕ, когда
        // ответ НЕ ушёл: причина называется коротко, и в ней нет ни пропуска, ни подписи, ни cookie
        // (уточнение владельца 11.10.2026: «следы без секретов»).
        PhoneHttpResponse Say(int status, bool ok, string words, string reason)
        {
            if (!ok)
            {
                _doors.Log(string.Format(
                    CultureInfo.CurrentCulture, PanelStrings.PhoneGateAnswerRefusedLogFormat, reason));
            }

            return form
                ? Problem(language, status, words)
                : PhoneHttpResponse.Words(status, ok, words);
        }

        string eventId;
        string answers;

        if (form)
        {
            // ФОРМА ЕСТЬ, А РАЗОБРАТЬ ЕЁ НЕ ВЫШЛО — это «не наша форма»: имени выбора в теле нет,
            // и отвечать не на что. Словами, а не пятисотой: человек мог прислать что угодно.
            if (fields is null)
                return Say(400, false, Loc.T(PanelStrings.PhoneGateBadRequest), "форма ответа не разобрана");

            // ⚠️ ЭКРАН ПРИНИМАЕТСЯ ЗДЕСЬ, ПОД ЗАМКОМ, И ВМЕСТЕ С НАКОПЛЕННЫМ: ответ уходит движку
            // ПОЛНЫМ набором, а экран двигается ТОЛЬКО после удачи (решение владельца 11.10.2026).
            var collected = AnswerScreen(fields, out var refusal, out eventId);

            if (collected is null) return Say(400, false, refusal, "ответ не собран");

            answers = collected;
        }
        else
        {
            // МАШИННЫЙ ПУТЬ: "answers" СОБИРАЕТСЯ ЗАНОВО (контракт §2.5) — в движок уезжают только
            // id/selected/custom; всё прочее (и любое поле сверх пределов) — отказ СЛОВАМИ, а не
            // молчаливая передача того, чего мы не разобрали.
            if (!TryAnswer(request.Body, out eventId, out var raw)
                || !PhoneAnswerCards.TryBuild(raw, out answers, out var answerProblem))
            {
                return PhoneHttpResponse.Words(400, false, Loc.T(PanelStrings.PhoneGateBadRequest));
            }
        }

        string clientId;

        lock (_gate)
        {
            // ⚠️ «ПЕРВЫЙ ОТВЕТИВШИЙ» — И НА МАШИННОМ ПУТИ (контракт §2.5): два нажатия в React
            // приходят ДВУМЯ запросами, и второй не должен уйти движку вторым ответом.
            // Форма сюда приходит уже с поднятым `_answering` (его ставит `AnswerScreen`).
            if (!form && _answering)
            {
                return Say(403, false, Loc.T(PanelStrings.PhonePageAnsweredAgain), "ответ уже отправляется");
            }

            if (_question is null)
            {
                _answering = false;

                return Say(403, false, !form
                    ? Loc.T(PanelStrings.PhoneGateNoQuestion)
                    : NoQuestionWords(), "нет вопроса");
            }

            // ЧУЖОЙ И УСТАРЕВШИЙ ВОПРОС — отказ СЛОВАМИ, а не молчание: телефон обязан понять,
            // что отвечает не на тот вопрос, который видит человек.
            if (!string.Equals(_question.EventId, eventId, StringComparison.Ordinal))
            {
                _answering = false;

                return Say(403, false, !form
                    ? Loc.T(PanelStrings.PhoneGateStaleQuestion)
                    : Loc.T(PanelStrings.PhonePageTaken), "устаревший вопрос");
            }

            if (_clientId.Length == 0)
            {
                _answering = false;

                return Say(503, false, !form
                    ? Loc.T(PanelStrings.PhoneGateNoChannel)
                    : string.Format(CultureInfo.CurrentCulture, PanelStrings.PhonePageAnswerFailedFormat, Loc.T(PanelStrings.PhoneGateNoChannel)),
                    "нет канала к движку");
            }

            // ОТВЕТ УЖЕ ОТПРАВЛЯЕТСЯ: второй такой же не уйдёт движку (см. проверку выше).
            if (!form) _answering = true;

            clientId = _clientId;
        }

        // Конверт ответа — ЗАМЕР (замер §4): `clientId`, `eventId`, `outcome` с ответами.
        var args = "{\"clientId\":" + Quote(clientId)
            + ",\"eventId\":" + Quote(eventId)
            + ",\"outcome\":{\"kind\":\"result\",\"value\":{\"answers\":" + answers + "}}}";

        var answer = _doors.Engine(PhoneDecisions.EventsResultEndpoint, args);

        if (answer.Status == 0)
        {
            _answering = false;

            return Say(
                502, false,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateEngineSilentFormat, answer.Body),
                "движок молчит");
        }

        // ⚠️ Отказ НАШЕГО входа в движок телефону показывать нельзя: он прочитал бы это как
        // «моя cookie плоха» и пошёл бы сопрягаться заново. Это беда панели, и она говорит о ней
        // сама, а телефону достаётся честное «движок сейчас не отвечает».
        if (answer.RefusedOurLogin || !answer.Ok)
        {
            _answering = false;

            return Say(
                502, false,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateEngineRefusedFormat, answer.Status),
                "движок отказал");
        }

        // ДВИЖОК ОТВЕЧАЕТ `200` И НА ОТКАЗ: чужой или уже снятый `eventId` приходит как
        // `gateway/internal` «identifies no active event stream» (замер §4). Поэтому «принято»
        // решает не код HTTP, а конверт; иначе телефону сказали бы «ответ отправлен» там,
        // где ответ никуда не пошёл.
        var judged = PhoneDecisions.JudgeAnswer(answer.Body);

        if (judged == PhoneDecisions.AnswerJudge.EnvelopeError)
        {
            lock (_gate)
            {
                _answering = false;

                if (_question is not null && _question.EventId == eventId)
                {
                    _question = null;
                    _outcome = QuestionOutcome.Taken;
                }
            }

            return Say(403, false, !form
                ? Loc.T(PanelStrings.PhoneGateStaleQuestion)
                : Loc.T(PanelStrings.PhonePageTaken), "движок не знает такого события");
        }

        // ⚠️ КОНВЕРТ БЕЗ ОШИБКИ, А ОТВЕТ НЕ ПРИНЯТ (блок D плана 2.2.0, риск назван в L1): движок
        // может ответить `200 {ok:true, value:false}` — так ведёт себя `userQuestions/answer` при
        // профиле `mode: legacy`. Сегодня наша дверь (`$events/result`) принимает ответ на обеих
        // версиях, но если апстрим переключит профиль на `mode: timed`, она начнёт отвечать так же
        // — и без этой проверки человек прочитал бы «ответ отправлен», а вопрос остался бы висеть.
        if (judged == PhoneDecisions.AnswerJudge.NotTaken)
        {
            _answering = false;

            return Say(
                502, false,
                Loc.T(PanelStrings.PhoneGateAnswerNotTaken),
                "движок ответ не принял");
        }

        lock (_gate)
        {
            _answering = false;

            // Вопрос снимается, только если он ТОТ ЖЕ: за время ответа мог прийти новый.
            if (_question is not null && _question.EventId == eventId)
            {
                _question = null;
                _outcome = QuestionOutcome.Answered;
            }

            _screen = 0;
            _screenAnswers.Clear();
        }

        // СЛЕД В ЖУРНАЛЕ: ответ телефона УШЁЛ в движок. Номер события и имя устройства —
        // ни пропуска, ни подписи, ни cookie.
        _doors.Log(string.Format(
            CultureInfo.CurrentCulture, PanelStrings.PhoneGateAnswerLogFormat, eventId, deviceId));

        // ОТВЕТИВШЕМУ — НА СТРАНИЦУ ЗАНОВО (303 + `Location: /`), а не страница с обновлением:
        // после ответа человек должен увидеть «ответ отправлен», а не повторно отправлять ту же
        // форму по F5 (уточнение владельца 11.10.2026).
        return !form
            ? PhoneHttpResponse.Words(200, true, Loc.T(PanelStrings.PhoneGateAnswerSent))
            : PhoneHttpResponse.Redirect(PhoneGateRoot);
    }

    /// <summary>
    /// ОТМЕНИТЬ ХОД АГЕНТА, КОТОРЫЙ СПРАШИВАЕТ (этап F2).
    ///
    /// **Зачем это на странице.** Замер <c>docs\PHONE-LIVE.md</c> §4: **вопрос без ответившего
    /// висит вечно** и освобождается ТОЛЬКО отменой. Если телефон увидел вопрос, на который
    /// ответить не хочет (или не может), у него должен быть выход — иначе ход агента останется
    /// стоять, а человек будет думать, что панель сломалась.
    ///
    /// * отменяет калитка **той же дверью, что и панель**: <c>session/cancel</c> с `sessionId`
    ///   (движок ищет агента в реестре по `sessionId` — замер чтением §4 отчёта F2);
    /// * `eventId` формы сверяется с висящим вопросом: отменить ЧУЖОЙ ход телефоном нельзя;
    /// * ⚠️ **панель сама не отвечает никогда** (решение владельца 11.10.2026) — и здесь тоже:
    ///   отмена не подставляет ответ, а снимает ожидание.
    ///
    /// Отказ движка говорится СЛОВАМИ (`PhonePageCancelFailedFormat`), а не выдаётся за сделанное.
    /// </summary>
    private PhoneHttpResponse Cancel(PhoneHttpRequest request)
    {
        var language = PhoneGateLanguages.For(request.Language, Loc.Language);

        // ⚠️ ОТМЕНА — НЕ ОТВЕТ: у неё ОДНО поле (`eventId`), и разбирать её формой ответа нельзя
        // (та требует имени выбора `q0`, которого у отмены нет и быть не должно). «Форма ли это»
        // решается тем же признаком, что и у ответа (<see cref="PhoneAnswer.LooksForm"/>).
        // ⚠️ JSON ИЛИ ФОРМА — ответим ТЕМ ЖЕ, чем спросили: React-пульт не может отличить «отменено»
        // от HTML-страницы (поправка §0.6 контракта), а форма остаётся: её шлёт старая страница.
        var json = LooksJson(request.Body);
        var form = !json && PhoneAnswer.LooksForm(request.Body);

        // ОТКАЗ — ТОЖЕ ТЕМ ЖЕ: JSON-путь получает слова, форма — страницу.
        PhoneHttpResponse Say(int status, string words) =>
            json ? PhoneHttpResponse.Words(status, false, words) : Problem(language, status, words);

        if (!Authorized(request, out var deviceId))
        {
            return form
                ? Problem(language, 401, Loc.T(PanelStrings.PhoneGateUnauthorized))
                : PhoneHttpResponse.Words(401, false, Loc.T(PanelStrings.PhoneGateUnauthorized));
        }

        var eventId = form ? PhoneAnswer.Field(request.Body, "eventId") ?? string.Empty : string.Empty;
        string agentId;

        lock (_gate)
        {
            if (_question is null)
                return Say(403, Loc.T(PanelStrings.PhonePageNoQuestion));

            if (eventId.Length == 0 && !TryCancel(request.Body, out eventId))
                return Say(400, Loc.T(PanelStrings.PhonePageNoQuestion));

            if (!string.Equals(_question.EventId, eventId, StringComparison.Ordinal))
                return Say(403, Loc.T(PanelStrings.PhonePageTaken));

            if (_question.AgentId.Length == 0)
            {
                return Say(
                    503,
                    string.Format(
                        CultureInfo.CurrentCulture,
                        PanelStrings.PhonePageCancelFailedFormat,
                        Loc.T(PanelStrings.PhoneGateNoChannel)));
            }

            agentId = _question.AgentId;
        }

        var refused = CancelTurn(agentId);

        if (refused.Length > 0)
        {
            return Say(
                502,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhonePageCancelFailedFormat, refused));
        }

        lock (_gate)
        {
            // СНИМАЕТСЯ ТОЛЬКО ТОТ ЖЕ ВОПРОС: за время отмены мог прийти новый, и снять его
            // «за компанию» значило бы отменить чужой ход.
            if (_question is not null && _question.EventId == eventId)
            {
                _question = null;
                _outcome = QuestionOutcome.Cancelled;
            }

            _answering = false;
        }

        // СЛЕД В ЖУРНАЛЕ: ход агента отменён С ТЕЛЕФОНА. Номер события и имя устройства.
        _doors.Log(string.Format(
            CultureInfo.CurrentCulture, PanelStrings.PhoneGateCancelledLogFormat, eventId, deviceId));

        // ОТМЕНИВШЕМУ — НА СТРАНИЦУ ЗАНОВО (303 + `Location: /`): сказанное «ход отменён» человек
        // читает уже на странице, а не в теле ответа на POST (F5 не повторяет отмену).
        // ФОРМЕ — НА СТРАНИЦУ ЗАНОВО (303 + `Location: /`): сказанное «ход отменён» человек
        // читает уже на странице; JSON-путь получает СЛОВА, как и положено машинной двери.
        return json
            ? PhoneHttpResponse.Words(200, true, Loc.T(PanelStrings.PhonePageCancelled))
            : PhoneHttpResponse.Redirect(PhoneGateRoot);
    }

    /// <summary>Корень калитки — одна дверь и для входа, и для страницы телефона.</summary>
    private const string PhoneGateRoot = "/";

    /// <summary>
    /// СЛОВА «ОТВЕЧАТЬ НЕ НА ЧТО» — ПО ИСХОДУ, а не одни и те же: «вы уже ответили», «вопрос снят»
    /// и «вопроса не было» — три РАЗНЫХ ответа человеку, и один на всех заставил бы его гадать,
    /// отправился ли его ответ. Читается под тем же замком, что и состояние.
    /// </summary>
    private string NoQuestionWords() => _outcome switch
    {
        QuestionOutcome.Answered => Loc.T(PanelStrings.PhonePageAnsweredAgain),
        QuestionOutcome.Taken => Loc.T(PanelStrings.PhonePageTaken),
        QuestionOutcome.Cancelled => Loc.T(PanelStrings.PhonePageCancelled),

        // СНЯТО ПО ПРЕДЕЛУ — причина СЛОВАМИ (B-05): «ответа не было 10 мин. — ход отменён».
        // Без неё человек прочитал бы «вы отменили», хотя не отменял.
        QuestionOutcome.NoAnswer => NoAnswerWords(),

        _ => Loc.T(PanelStrings.PhonePageNoQuestion),
    };

    /// <summary>СЛОВА «ВОПРОС СНЯТ ПО ПРЕДЕЛУ» — одним местом: их читают и машинная дверь
    /// (<c>GET /question</c>), и отказ на ответ, и журнал (там предел назван минутами).</summary>
    private static string NoAnswerWords() => string.Format(
        CultureInfo.CurrentCulture,
        PanelStrings.PhoneGateQuestionNoAnswerFormat,
        (int)QuestionWaitLimit.TotalMinutes);

    /// <summary>
    /// ПРИНЯТЬ ОТВЕТ ОДНОГО ЭКРАНА И СОБРАТЬ ПОЛНЫЙ НАБОР. <c>null</c> — ответ не принят,
    /// и <paramref name="words"/> говорит человеку, почему.
    ///
    /// **Что здесь происходит, по порядку.**
    ///
    /// 1. **Вопроса нет** — отвечать не на что (слова по исходу, <see cref="NoQuestionWords"/>).
    /// 2. **Ответ уже отправляется** (<see cref="_answering"/>) — второй раз не отправляем.
    /// 3. **Вопрос не разобрался** — отвечать нечем.
    /// 4. **Экран показывается не тот**, на который отвечают: браузер мог отправить форму
    ///    устаревшей карточки. Экран НЕ сдвигается, ответ не уходит, и ответ НЕ ЗАПОМИНАЕТСЯ.
    /// 5. **ЧТО ЧЕЛОВЕК ОТВЕТИЛ.** Правило названо ОДНО и действует всегда: **заполнен свой ответ —
    ///    уходит СВОЙ ОТВЕТ, даже когда выбран вариант.** Он явнее: человек написал слова, а не
    ///    ткнул в готовое. Уходит он ТОЙ ЖЕ строкой, что и выбор (<c>selected</c>) — форма движка
    ///    одна (`docs\PHONE-LIVE.md` §3.5), и своего поля для «своего» у неё нет.
    /// 6. **ПОЛНЫЙ НАБОР — ОДНИМ ОТПРАВЛЕНИЕМ.** Не отвечен хоть один вопрос — отказ целиком:
    ///    неполный ответ движок примет за ответ, и агент пойдёт дальше по решению, которого
    ///    человек не принимал. Не отвечен МОГУТ быть только следующие экраны: до них человек
    ///    ещё не дошёл, и экран НЕ СДВИГАЕТСЯ — он ждёт ответа на этот.
    ///
    /// ⚠️ **Экран сдвигается только после того, как ответ УШЁЛ движку** (успех — сдвиг, отказ —
    /// тот же экран). Поэтому «отвечено» и «отправлено» здесь идут разными шагами, и промежуточный
    /// отказ ничего не теряет: текущий экран уже отвечен, а следующие ждут своей очереди.
    /// </summary>
    private string? AnswerScreen(PhoneAnswerFields form, out string words, out string eventId)
    {
        words = string.Empty;
        eventId = string.Empty;

        lock (_gate)
        {
            if (_question is null)
            {
                words = NoQuestionWords();
                return null;
            }

            if (_answering)
            {
                words = Loc.T(PanelStrings.PhonePageAnsweredAgain);
                return null;
            }

            var questions = PhonePage.Parse(_question.Questions);

            if (questions.Count == 0)
            {
                words = Loc.T(PanelStrings.PhonePageUnreadable);
                return null;
            }

            // ЭКРАН НАЗВАН ФОРМОЙ, А НЕ УГАДАН. Ноль здесь — «первый экран», и это не «пусто».
            // Ответ на ДРУГОЙ экран не запоминается: это ответ не на то, что человек видит.
            //
            // ⚠️ Экран сверяется с ТЕМ, ЧТО ПОКАЗАНО, и показывается ВСЕГДА первый неотвеченный
            // (<see cref="NextScreen"/>). Поэтому «ответил на первый» само делает второй текущим —
            // отдельного сдвига после удачи не нужно, и он не потерялся бы при отказе движка.
            if (form.Screen != _screen)
            {
                words = Loc.T(PanelStrings.PhonePageTaken);
                return null;
            }
            var question = questions[_screen];
            var own = form.Own.Trim();
            string answer;

            if (own.Length > 0)
            {
                answer = own;
            }
            else
            {
                if (!int.TryParse(form.Choice, NumberStyles.Integer, CultureInfo.InvariantCulture, out var chosen))
                {
                    words = Loc.T(PanelStrings.PhonePageChooseAll);
                    return null;
                }

                var options = question.Options ?? Array.Empty<string>();

                if (chosen < 0 || chosen >= options.Count)
                {
                    words = Loc.T(PanelStrings.PhonePageChooseAll);
                    return null;
                }

                answer = options[chosen];
            }

            // ОТВЕТ ЭТОГО ЭКРАНА ЗАПОМИНАЕТСЯ ДО ПОПЫТКИ СБОРКИ — и это не мелочь: полного набора
            // ещё нет (следующие экраны впереди), но ЭТОТ экран уже отвечен. Запомни его после
            // проверки полноты — и экран застрял бы навсегда: `Build` вернул бы `null`, ответ
            // не записался бы, и следующий показ снова показал бы тот же экран.
            _screenAnswers[question.Id] = answer;

            eventId = _question.EventId;

            // ⚠️ ПОЛНЫЙ НАБОР: ответы идут В ПОРЯДКЕ ВОПРОСОВ КАДРА, а не в порядке экранов —
            // движок ищет вопрос по `id`, но порядок здесь часть формы ответа, и он же виден
            // в теле вызова при разборе живого прогона.
            var built = PhoneAnswer.Build(questions, _screenAnswers);

            // НЕПОЛНЫЙ НАБОР — ОТКАЗ, НО ЭКРАН УЖЕ ОТВЕЧЕН: следующий покажет `View()`, а не это
            // место. Ничего не «съезжает»: `PhoneAnswer.Build` порядок не меняет.
            if (built is null)
            {
                words = Loc.T(PanelStrings.PhonePageChooseAll);
                return null;
            }

            _answering = true;

            return built;
        }
    }

    /// <summary>ТЕЛО — ЭТО JSON? Смотрим на первый непробельный знак: `{` бывает только у JSON,
    /// а форма начинается с имени поля.</summary>
    private static bool LooksJson(string body)
    {
        var text = (body ?? string.Empty).TrimStart();

        return text.StartsWith('{');
    }

    /// <summary>Тело отмены: <c>{"eventId":"…"}</c>. Машинный путь рядом с формой — по той же причине,
    /// что у ответа: проверкам и скриптам нужен JSON, а странице — форма.</summary>
    private static bool TryCancel(string body, out string eventId)
    {
        eventId = string.Empty;

        if (string.IsNullOrWhiteSpace(body)) return false;

        try
        {
            using var document = JsonDocument.Parse(body);

            if (document.RootElement.ValueKind != JsonValueKind.Object) return false;
            if (!document.RootElement.TryGetProperty("eventId", out var id)) return false;
            if (id.ValueKind != JsonValueKind.String) return false;

            eventId = id.GetString() ?? string.Empty;

            return eventId.Length > 0;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>Ответ телефона: <c>{"eventId":"…","answers":[…]}</c>. Ответы передаются движку
    /// КАК ЕСТЬ — панель их не толкует: она их не понимает и понимать не должна.</summary>
    private static bool TryAnswer(string body, out string eventId, out string answers)
    {
        eventId = string.Empty;
        answers = "[]";

        if (string.IsNullOrWhiteSpace(body)) return false;

        try
        {
            using var document = JsonDocument.Parse(body);

            if (document.RootElement.ValueKind != JsonValueKind.Object) return false;
            if (!document.RootElement.TryGetProperty("eventId", out var id)) return false;
            if (id.ValueKind != JsonValueKind.String) return false;

            eventId = id.GetString() ?? string.Empty;
            if (eventId.Length == 0) return false;

            if (!document.RootElement.TryGetProperty("answers", out var list)) return false;
            if (list.ValueKind != JsonValueKind.Array) return false;

            answers = list.GetRawText();

            return true;
        }
        catch
        {
            return false;
        }
    }

    /// <summary>
    /// ВЫЗОВ ДВИЖКА — БЕЛЫМ СПИСКОМ, А НЕ МОСТОМ.
    ///
    /// Порядок здесь — тоже правило: сначала «пустили ли тебя», потом «можно ли это имя», потом
    /// «не поток ли это», потом «есть ли доводы», и только потом движок. Обратный порядок означал бы,
    /// что чужое имя уходит в движок «на проверку», то есть что белого списка нет вовсе.
    /// </summary>
    private PhoneHttpResponse Api(PhoneHttpRequest request, string endpoint)
    {
        if (!Authorized(request, out _))
            return PhoneHttpResponse.Words(401, false, Loc.T(PanelStrings.PhoneGateUnauthorized));

        var verdict = PhoneDecisions.DecideCall(endpoint);

        if (!verdict.Allowed) return PhoneHttpResponse.Words(403, false, verdict.Text());

        var call = PhoneDecisions.Allowed.First(item =>
            string.Equals(item.Endpoint, verdict.Endpoint, StringComparison.Ordinal));

        // ПОТОК ОДИНОЧНЫМ POST НЕ ЗОВЁТСЯ — и это сказано СЛОВАМИ, а не молчанием: молчание
        // выглядело бы «телефон ничего не получил», а на деле он зовёт то, чего так не зовут
        // (`docs\PHONE-LIVE.md` §2: движок отвечает `gateway/signature-invalid`). Поток телефону
        // открывает страница телефона (F2) — своей дверью, а не сырым POST.
        if (call.Mode == EngineRpcMode.Stream)
        {
            return PhoneHttpResponse.Words(
                403, false,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateStreamRefusedFormat, endpoint));
        }

        // `$events/result` — СЛУЖЕБНАЯ ДВЕРЬ ДВИЖКА. Телефон отвечает на вопрос своей дверью
        // (`POST /answer`): там калитка подставляет НАШ `clientId`, и телефон его не видит.
        if (string.Equals(endpoint, PhoneDecisions.EventsResultEndpoint, StringComparison.Ordinal))
            return PhoneHttpResponse.Words(403, false, Loc.T(PanelStrings.PhoneGateInternalRefused));

        // ДОВОДЫ — СВОИ, ЗАНОВО. У догона они собираются по белому списку (address/throughSeq/
        // beforeSeq/maxMessages): всё остальное, что мог прислать телефон, в движок не уйдёт.
        string? args;

        if (string.Equals(verdict.Endpoint, PhoneDecisions.SessionPageEndpoint, StringComparison.Ordinal))
        {
            if (!PhoneOlder.TryArgs(request.Body, out var older, out var problem, out var foreign))
            {
                _doors.Log(string.Format(
                    CultureInfo.CurrentCulture, PanelStrings.PhoneOlderArgsLogFormat, problem));

                return foreign
                    ? PhoneHttpResponse.Words(403, false, Loc.T(PanelStrings.PhoneWebSubagentRefused))
                    : PhoneHttpResponse.Words(400, false, Loc.T(PanelStrings.PhoneGateBadRequest));
            }

            args = older;
        }
        else
        {
            args = ArgsOf(request.Body);
        }

        if (args is null)
        {
            return PhoneHttpResponse.Words(
                400, false,
                string.Format(
                    CultureInfo.CurrentCulture,
                    PanelStrings.PhoneGateNoArgumentsFormat,
                    PhoneDecisions.ArgumentKeyFor(endpoint)));
        }

        var engine = _doors.Engine(endpoint, args);

        if (engine.Status == 0)
        {
            return PhoneHttpResponse.Words(
                502, false,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateEngineSilentFormat, engine.Body));
        }

        if (engine.RefusedOurLogin)
        {
            return PhoneHttpResponse.Words(
                502, false,
                string.Format(CultureInfo.CurrentCulture, PanelStrings.PhoneGateEngineRefusedFormat, engine.Status));
        }

        // ДВА ОТВЕТА, КОТОРЫЕ КАЛИТКА ПЕРЕСОБИРАЕТ (поправки §0.4 и §0.5 контракта): список —
        // свои строки по allowlist; догон — свои записи по тому же белому списку, что у ленты.
        // Остальные вызовы по-прежнему уходят телефону без разбора и обрезки.
        if (string.Equals(verdict.Endpoint, PhoneDecisions.SessionListEndpoint, StringComparison.Ordinal))
            return ListAnswer(engine);

        if (string.Equals(verdict.Endpoint, PhoneDecisions.SessionPageEndpoint, StringComparison.Ordinal))
            return OlderAnswer(engine);

        return new PhoneHttpResponse(engine.Status, "application/json; charset=utf-8", engine.Body, null);
    }

    /// <summary>
    /// ОТВЕТ НА СПИСОК РАЗГОВОРОВ — СВОИ СТРОКИ ПО БЕЛОМУ СПИСКУ (контракт §2.1), ОДИН НА ДВЕ ДВЕРИ.
    ///
    /// **От какого случая (поправка §0.4 контракта).** Прежняя редакция переносила строки движка
    /// СЫРЫМ текстом, и телефону уезжали `cwd` и `projections.workingDirectory`. Теперь и старая дверь
    /// (`POST /api/session/list`), и пульт (`GET /api/phone/sessions`) отдают одно и то же: объекты,
    /// собранные <see cref="PhoneList"/>.
    ///
    /// **Не молча:** сколько подчинённых убрано, сколько строк отброшено и сколько очерков урезано —
    /// числами в журнал, и только когда число изменилось (иначе открытие списка затопило бы журнал).
    /// Не та форма — 502 СЛОВАМИ: списка нет, а не «пусто».
    /// </summary>
    private PhoneHttpResponse ListAnswer(PhoneEngineAnswer engine, bool stale = false)
    {
        // ИНДЕКС «КТО ЧЕЙ РОДИТЕЛЬ» — из ЭТОГО ЖЕ ответа: он нужен, чтобы пометить строку, в которой
        // ждёт ответа подчинённый агент (вопрос подчинённого живёт в корневой сессии, контракт §2.3).
        var index = PhoneSessionIndex.Parse(engine.Body);
        Publish(index);

        var asked = PendingQuestionRoot(index);

        // АРХИВ — ДО СБОРКИ: набор из workspace/follow (кэш 30 с), и только адреса. `null` — не
        // прочитался, и тогда поведение прежнее байт в байт (R1 §3.2). Набор — из калитки, а не
        // из строк движка: телефон не должен знать имён архивных сессий вовсе.
        var archived = Archived();

        var list = PhoneList.Build(
            engine.Body,
            id => asked.Length > 0 && string.Equals(id, asked, StringComparison.Ordinal),
            archived is null ? null : id => archived.Contains(id),
            stale);

        if (list.Hidden > 0 && list.Hidden != _subordinateSessions)
        {
            _subordinateSessions = list.Hidden;

            _doors.Log(string.Format(
                CultureInfo.CurrentCulture,
                PanelStrings.PhoneSessionsHiddenLogFormat,
                list.Hidden,
                list.Hidden + list.Total));
        }

        if (list.Archived > 0 && list.Archived != _archivedSessions)
        {
            _archivedSessions = list.Archived;

            _doors.Log(string.Format(
                CultureInfo.CurrentCulture,
                PanelStrings.PhoneSessionsArchivedLogFormat,
                list.Archived,
                list.Archived + list.Total));
        }

        if (list.Dropped > 0 && list.Dropped != _listDropped)
        {
            _listDropped = list.Dropped;

            _doors.Log(string.Format(
                CultureInfo.CurrentCulture,
                PanelStrings.PhoneRecordsDroppedLogFormat,
                list.Dropped,
                list.Dropped + list.Total));
        }

        if (list.Trimmed > 0 && list.Trimmed != _listTrimmed)
        {
            _listTrimmed = list.Trimmed;

            _doors.Log(string.Format(
                CultureInfo.CurrentCulture,
                PanelStrings.PhoneListTrimmedLogFormat,
                list.Trimmed,
                list.Shown));
        }

        if (list.Error.Length > 0)
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, list.Error));

            return PhoneHttpResponse.Words(502, false, Loc.T(PanelStrings.PhoneWebListUnreadable));
        }

        if (list.ShapeBroken)
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneSessionsShapeLogFormat, list.Shape));

            return PhoneHttpResponse.Words(502, false, Loc.T(PanelStrings.PhoneWebListUnreadable));
        }

        return PhoneHttpResponse.Json(200, list.Json);
    }

    /// <summary>
    /// ДОГОН: ПЕРЕСБОРКА ЗАПИСЕЙ ПО БЕЛОМУ СПИСКУ (контракт §2.4). Отказ движка по подчинённой
    /// (`session/agent-busy`) — это 403 СЛОВАМИ, а не 502: телефону говорят «открыты только обычные
    /// сессии»; всё остальное — «страница не прочиталась».
    /// </summary>
    private PhoneHttpResponse OlderAnswer(PhoneEngineAnswer engine)
    {
        var older = PhoneOlder.Build(engine.Body);

        if (!older.Ok)
        {
            _doors.Log(string.Format(
                CultureInfo.CurrentCulture, PanelStrings.PhoneListFailedLogFormat, older.Problem));

            if (string.Equals(older.Problem, "session/agent-busy", StringComparison.Ordinal))
                return PhoneHttpResponse.Words(403, false, Loc.T(PanelStrings.PhoneWebSubagentRefused));

            return PhoneHttpResponse.Words(502, false, Loc.T(PanelStrings.PhoneWebOlderFailed));
        }

        return PhoneHttpResponse.Json(200, older.Json);
    }

    /// <summary>
    /// СКОЛЬКО ЖИВЁТ ЗНАНИЕ «КТО ЧЕЙ РОДИТЕЛЬ». Тридцать секунд — не «как можно дольше»:
    /// подчинённых создают и закрывают на ходу, а спрашивать `session/list` на КАЖДЫЙ опрос
    /// вопроса (телефон опрашивает часто) значило бы гонять полсотни килобайт вхолостую.
    /// </summary>
    public static readonly TimeSpan SessionIndexLifetime = TimeSpan.FromSeconds(30);

    private PhoneSessionIndex _sessions = PhoneSessionIndex.Empty;
    private DateTimeOffset _sessionsAt = DateTimeOffset.MinValue;
    private bool _sessionsLoaded;

    /// <summary>Корень висящего вопроса — снимок, чтобы не спрашивать движок на каждый опрос.</summary>
    private string _questionRootEvent = string.Empty;
    private string _questionRoot = string.Empty;
    private bool _questionSubagent;

    /// <summary>ДОВОДЫ СПИСКА — одной строкой и одним местом (`_request`, замер §2).</summary>
    private static readonly string ListArguments =
        "{\"" + PhoneDecisions.ArgumentSessionList + "\":{}}";

    /// <summary>
    /// ЗНАНИЕ «КТО ЧЕЙ РОДИТЕЛЬ» — НА ВРЕМЯ, А НЕ НАВСЕГДА, и это важно:
    /// подчинённая сессия появляется и исчезает, а телефон может спросить сразу после этого.
    /// </summary>
    private PhoneSessionIndex Sessions()
    {
        lock (_gate)
        {
            if (_sessionsLoaded && _doors.Clock() - _sessionsAt < SessionIndexLifetime) return _sessions;
        }

        var engine = _doors.Engine(PhoneDecisions.SessionListEndpoint, ListArguments);
        var index = PhoneSessionIndex.Parse(engine.Status is >= 200 and < 300 ? engine.Body : null);

        Publish(index);

        return index;
    }

    /// <summary>ЗАПОМНИТЬ ИНДЕКС (и когда он прочитан) — под замком, одной парой.</summary>
    private void Publish(PhoneSessionIndex index)
    {
        lock (_gate)
        {
            _sessions = index;
            _sessionsAt = _doors.Clock();
            _sessionsLoaded = true;
        }
    }

    /// <summary>
    /// КОРЕНЬ ВИСЯЩЕГО ВОПРОСА. Знания нет — считаем корнем саму спросившую сессию: так строка
    /// помечается «ждёт ответа» хотя бы тогда, когда подъём по родителям не удался (лучше показать
    /// вопрос, чем спрятать его).
    /// </summary>
    private string PendingQuestionRoot(PhoneSessionIndex index)
    {
        string agent;

        lock (_gate) agent = _question?.AgentId ?? string.Empty;

        if (agent.Length == 0) return string.Empty;

        return index.TryRoot(agent, out var root, out _) && root.Length > 0 ? root : agent;
    }

    /// <summary>
    /// СКОЛЬКО ПОДЧИНЁННЫХ СЕССИЙ УБРАНО ИЗ СПИСКА В ПРОШЛЫЙ РАЗ (-1 — ещё ни разу).
    ///
    /// **Зачем помнить.** Журнал панели — не поток: список открывают повторно, и одна и та же строка
    /// «убрано 179 из 197» на каждое открытие утопила бы в себе остальное. Строка пишется тогда,
    /// когда число ИЗМЕНИЛОСЬ, — то есть когда у человека действительно что-то поменялось.
    /// </summary>
    private int _subordinateSessions = -1;

    /// <summary>СКОЛЬКО АРХИВНЫХ СЕССИЙ СКРЫТО В ПРОШЛЫЙ РАЗ (-1 — ещё ни разу).</summary>
