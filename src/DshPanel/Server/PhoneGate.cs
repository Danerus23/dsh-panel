    /// «СПИСОК МОГ ИЗМЕНИТЬСЯ» — ОДИН БИТ от <c>api-session/status</c> в уже открытом <c>$events</c>
    /// (S4a, R1 §5.2). Снимается при выдаче списка; ни адреса сессии, ни «идёт ли ход» в нём нет.
