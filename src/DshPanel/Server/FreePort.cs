using System.Net;
using System.Net.Sockets;

namespace DshPanel.Server;

/// <summary>
/// Свободный порт. Выбирается СВЯЗЫВАНИЕМ на порт 0 — то есть у системы спрашивают номер,
/// который она прямо сейчас готова отдать, а не перебирают «примерно свободные» вроде 3097.
///
/// Решение владельца 23.09.2026. Разница с v1 принципиальная: там порт брался из настроек
/// (по умолчанию 3080 — порт владельца), и изолированный прогон однажды погасил его сервер.
/// Здесь порт владельца предикатом ЗАПРЕЩЁН для всякого, кто просит «любой свободный»
/// (<see cref="ServerDecisions.IsAllowedPort"/>), а свой порт панель ни у кого не отбирает.
///
/// ⚠️ Случайный порт и порт владельца — разные вещи: право занять 3080 (решение владельца
/// 26.09.2026) есть только у обычного запуска человеком и только для СВОЕГО порта из настроек.
/// «Дай любой свободный» такого права не получает НИКОГДА: иначе самотест однажды встал бы
/// на 3080, то есть на канал сессии агента.
/// </summary>
public static class FreePort
{
    /// <summary>
    /// Найти свободный порт. <c>0</c> — не удалось (сокет не дался); вызывающий обязан
    /// отказаться от запуска, а не подставлять «какой-нибудь» номер.
    ///
    /// Между освобождением порта и его занятием движком есть окно гонки — оно измеряется
    /// миллисекундами и закрывается проверкой <see cref="CanBind"/> прямо перед запуском.
    /// Абсолютной гарантии тут не бывает ни у кого: порт — общий ресурс машины.
    /// </summary>
    public static int Find(int attempts = 5)
    {
        for (var i = 0; i < attempts; i++)
        {
            try
            {
                var listener = new TcpListener(IPAddress.Loopback, 0);
                listener.Start();
                var port = ((IPEndPoint)listener.LocalEndpoint).Port;
                listener.Stop();

                if (ServerDecisions.IsAllowedPort(port, mayOccupyOwnerPort: false)) return port;
            }
            catch (SocketException)
            {
                // Порт достался кому-то между Start и Stop — пробуем ещё раз.
            }
        }

        return 0;
    }

    /// <summary>
    /// Можно ли ПРЯМО СЕЙЧАС занять этот порт. «Кто-то слушает» — не то же самое: порт бывает
    /// зарезервирован системой (Hyper-V, WSL, обновления) и удержан службой, которая не слушает, —
    /// тогда движок не привяжется, а человек видел бы просто «сервер не поднялся» без причины.
    ///
    /// Право на порт владельца спрашивается ЗДЕСЬ тоже, хотя вызывающий уже привёл порт к разрешённому
    /// (<see cref="ServerDecisions.NormalizePort"/>): это вторая линия того же запрета, и она стоит
    /// там, где порт действительно занимают. Право — обязательный параметр без умолчания: забыть
    /// его выдать безопасно (порт владельца не займётся), забыть запретить — нет.
    /// </summary>
    public static bool CanBind(int port, bool mayOccupyOwnerPort)
    {
        if (!ServerDecisions.IsAllowedPort(port, mayOccupyOwnerPort)) return false;

        try
        {
            var listener = new TcpListener(IPAddress.Loopback, port);
            listener.Start();
            listener.Stop();
            return true;
        }
        catch (SocketException)
        {
            return false;
        }
    }
}
