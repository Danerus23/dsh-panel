using QRCoder;

namespace DshPanel.Server;

/// <summary>
/// QR ДЛЯ ТЕЛЕФОНА — КАРТИНКА, которую человек наводит камерой (этап F1, хвост 1).
///
/// **Что здесь решается и что НЕ здесь.** Кодирование адреса в QR — работа библиотеки
/// (<c>QRCoder</c>, лицензия MIT, чистый .NET, в сеть не ходит): свой генератор в панели
/// не пишется намеренно — «похожее на QR» человек наводит камерой и получает мусор
/// (решение владельца 11.10.2026). Здесь только три вещи: **что** закодировать, **каким
/// размером** и **как отдать готовые байты** окну.
///
/// ⚠️ **ЧТО ИМЕННО КОДИРУЕТСЯ — решает НЕ этот файл.** Правило одно и оно названо словами
/// в одном месте (<see cref="PanelsQrRule"/>): **QR кодирует ровно ту строку, которую раздел
/// показывает как адрес**. Дверь получает эту строку доводом и в неё не заглядывает: начни
/// она выбирать сама (взять порт, дописать схему, подставить выдуманное) — и правило
/// перестало бы быть проверяемым, а кадр `settings-phone` мог бы уехать в README
/// с настоящим номером машины (решение владельца 11.10.2026 о маске).
/// </summary>
public static class PhoneQr
{
    /// <summary>
    /// СКОЛЬКО ТОЧЕК НА ОДИН МОДУЛЬ. Модуль — клетка QR; при 8 точках адрес домашней сети
    /// даёт картинку 240–290 точек, и она читается камерой с экрана, оставаясь компактной
    /// в карточке раздела (то же число в проверке «размеры правдоподобны»).
    /// </summary>
    public const int PixelsPerModule = 8;

    /// <summary>
    /// УРОВЕНЬ ИСПРАВЛЕНИЯ ОШИБОК. <c>Q</c> (25 %) — не «на глаз»: QR вешают на экран,
    /// его снимают под углом и с бликом, а <c>H</c> (30 %) на коротком адресе разницы
    /// в размере почти не даёт. Короткая строка адреса влезает на любом уровне.
    /// </summary>
    public const QRCodeGenerator.ECCLevel Level = QRCodeGenerator.ECCLevel.Q;

    /// <summary>
    /// ПРАВИЛО КОДИРОВАНИЯ, НАЗВАННОЕ СЛОВАМИ В ОДНОМ МЕСТЕ.
    ///
    /// **QR кодирует `http://` + ровно ту строку адреса, которую раздел показывает, + `:` + порт
    /// калитки, который раздел показывает рядом.** Оба слагаемых человек видит на экране — значит
    /// и правило проверяемо: подменить их «на удобное» нельзя, не разойдясь с показом.
    ///
    /// Отсюда два следствия, и оба — исполнение решений владельца, а не удобство:
    ///
    /// * **в обычном запуске** это настоящий адрес машины и настоящий порт — человек наводит
    ///   камеру, и она ОТКРЫВАЕТ страницу телефона (`http://192.168.0.5:43127`);
    /// * **в прогоне съёмки** (`--shot settings-phone`) та же строка уже замаскирована
    ///   (<c>Program.MaskAddress</c> → <c>http://192.168.0.х:43127</c>), и в QR уезжает ИМЕННО ОНА:
    ///   кадр уходит в README, и настоящего номера адреса в нём быть не должно
    ///   (решение владельца 11.10.2026). Замаскированный адрес для телефона негоден —
    ///   и это честно: кадр не для наведения камеры, а для чтения.
    ///
    /// Строку собирает ОДНО место — <see cref="PhoneDecisions.QrText"/>: разложи её по двум
    /// местам, и однажды в код уехало бы не то, что показано.
    /// </summary>
    public const string PanelsQrRule =
        "QR кодирует http:// + ровно ту строку адреса, которую раздел показывает, + : + порт калитки, " +
        "который раздел показывает рядом: у человека — настоящий адрес, в прогоне съёмки — замаскированный.";

    /// <summary>
    /// НАРИСОВАТЬ QR С ЭТИМ ТЕКСТОМ — PNG-байтами, готовыми к показу.
    ///
    /// Пусто на входе — пусто и на выходе: **выдумывать адрес нельзя**, и «нарисовать код
    /// с ничем» было бы ровно этим. Пустая строка, мусор и слишком длинный текст дают
    /// <see cref="Array.Empty{T}"/> — отказ, а не исключение: падение окна из-за картинки
    /// недопустимо, а окно обязано сказать словами, что кода нет (см. `PhoneQrFailed`).
    ///
    /// Возвращает PNG целиком: рисует его библиотека (<c>PngByteQRCode</c>), а не панель.
    ///
    /// ⚠️ **Взято именно `PngByteQRCode`, а не `QRCode`/`BitmapByteQRCode`:** первый собирает PNG
    /// сам, а вторые идут через <c>System.Drawing</c>. Пакет объявляет `System.Drawing.Common`
    /// транзитивной зависимостью, но **в рантайме она не нужна** — это замерено: с убранным
    /// из вывода `System.Drawing.Common.dll` проверки <c>PhoneQrTests</c> проходят целиком
    /// (5 из 5). Своего PNG-кодировщика в панели нет и не будет — это была бы вторая библиотека
    /// ради одной картинки.
    ///
    /// И в сеть здесь никто не ходит: кодирование — это арифметика на месте (тоже замерено
    /// прогоном: проверки идут без сети и без ключа владельца).
    /// </summary>
    public static byte[] Png(string? text)
    {
        var payload = (text ?? string.Empty).Trim();

        if (payload.Length == 0) return Array.Empty<byte>();

        try
        {
            using var data = QRCodeGenerator.GenerateQrCode(payload, Level);

            return new PngByteQRCode(data).GetGraphic(PixelsPerModule);
        }
        catch (Exception)
        {
            // Слишком длинный текст (не влез ни в одну версию) и любой сбой библиотеки —
            // ОТКАЗ, а не падение окна: раздел скажет словами, что кода нет.
            return Array.Empty<byte>();
        }
    }
}
