namespace DshPanel.Update;

/// <summary>
/// КОГДА ПОДГОТОВКУ ОБНОВЛЕНИЯ МОЖНО НАЧАТЬ, А КОГДА НЕТ (2.4.0, DEF-006).
///
/// До 2.4.0 кнопка «Скачать и подготовить» не гасла в полёте: человек нажимал второй раз
/// и запускал ВТОРУЮ подготовку — при том что за ней стоит скачивание в сотни мегабайт,
/// распаковка и страховочная копия. Правило вынесено из окна ЧИСТОЙ функцией: в окне его
/// нечем проверить, не поднимая настоящую сеть и не нажимая дважды в одно мгновение,
/// а здесь оно проверяется перебором всех сочетаний — и мутация «не смотреть Busy» падает.
///
/// **Правило одно на два места:** им же подписана кнопка (<see cref="ButtonEnabled"/>) и им же
/// закрыта дверь (<see cref="MayStart"/>). Разойдись они — кнопка гасла бы, а дверь пускала,
/// и наоборот.
/// </summary>
public static class UpdatePrepareDecisions
{
    /// <summary>Нажимаема ли кнопка подготовки: есть что готовить, ничего не идёт и не готово.</summary>
    public static bool ButtonEnabled(bool ready, bool busy, bool prepared) => ready && !busy && !prepared;

    /// <summary>Можно ли начать подготовку: только если никакая не идёт.</summary>
    public static bool MayStart(bool busy) => !busy;
}
