using DshPanel.Views;

namespace DshPanel.Backup;

/// <summary>
/// Решение окна копий по вопросу «сервер работает — погасить?» и по тому, чем этот вопрос кончился.
///
/// Зачем это отдельный файл, а не пять строк в окне. В окне эти строки уже были — и были НЕВЕРНЫ:
/// выбор «погасить» не гасил ничего (вызов гашения не делался вовсе), а движку при этом сообщалось,
/// что сервер не работает, — то есть копия снималась с живого процесса и в отчёте выглядела целой.
/// Дефект держался именно потому, что решение жило в обработчике нажатия, где его ни одна проверка
/// без экрана достать не могла (найдено рабочим-подагентом 26.09.2026).
///
/// Здесь — чистый разбор без окон и без сервера: его можно проверить по одному случаю на исход.
/// </summary>
public static class BackupStopDecisions
{
    /// <summary>
    /// Чем кончилось решение человека и попытка гашения.
    /// </summary>
    /// <param name="Proceed">
    /// Делать ли работу дальше. <c>false</c> — человек отказался или сервер погасить не удалось;
    /// в обоих случаях копия НЕ снимается и накат НЕ начинается.
    /// </param>
    /// <param name="LiveCopy">
    /// Работа идёт по ЖИВОМУ серверу. Это значение уходит в движок и превращается там в честную
    /// строку отчёта «копия снята на ходу, сессии могли дописываться». Поэтому оно обязано быть
    /// правдой о сервере, а не выражением намерения человека: если гашение не удалось, сервер
    /// работает, и оговорка обязана остаться.
    /// </param>
    public readonly record struct StopOutcome(bool Proceed, bool LiveCopy);

    /// <summary>
    /// Разобрать исход вопроса.
    ///
    /// <paramref name="serverRunning"/> — работал ли сервер в тот момент, когда человек нажал кнопку.
    /// <paramref name="choice"/> — что человек выбрал (окно вопроса возвращает ровно это).
    /// <paramref name="stopSucceeded"/> — удалось ли погасить; спрашивается ТОЛЬКО при
    /// <see cref="StopChoice.StopAndContinue"/>, потому что в остальных случаях гашения не просят.
    /// </summary>
    public static StopOutcome Decide(bool serverRunning, StopChoice choice, bool stopSucceeded)
    {
        if (!serverRunning)
            return new StopOutcome(Proceed: true, LiveCopy: false);

        return choice switch
        {
            // Человек отказался: работа НЕ делается. Молчаливое «ну тогда на ходу» было бы
            // решением за него в вопросе о его данных.
            StopChoice.Cancel => new StopOutcome(Proceed: false, LiveCopy: false),

            // Копия «на ходу» выбрана осознанно, и это названо в отчёте.
            StopChoice.ContinueLive => new StopOutcome(Proceed: true, LiveCopy: true),

            // Просили погасить и погасили: только теперь оговорка снимается.
            StopChoice.StopAndContinue when stopSucceeded => new StopOutcome(Proceed: true, LiveCopy: false),

            // Просили погасить, а сервер остался жив (отказ в подтверждении, чужая ошибка, занятые
            // файлы). Работу не делаем: обещание «копия получается целой» не выполнено, а выдать
            // живую копию за цельную — это ровно та ложь, ради которой вопрос и задавался.
            _ => new StopOutcome(Proceed: false, LiveCopy: true),
        };
    }
}
