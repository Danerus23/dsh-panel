using System.Globalization;
using DshPanel.Shell;

namespace DshPanel.Backup;

/// <summary>
/// ГОТОВАЯ КОПИЯ В СПИСКЕ — то, что видно в окне «Копии». Перенесено из v1 «как есть»
/// (<c>..\dsh-tray\BackupService.cs:12–41</c>): поля те же.
///
/// Заполняет её перечисление папки (<see cref="BackupFolder"/>), а не движок копии: список — это
/// ВЗГЛЯД на папку, а не часть съёмки. Объявленная раньше кода, она была бы мёртвым объявлением.
///
/// ⚠️ **Строку для человека здесь больше НЕ собирают.** Прежде тут жил <c>Describe()</c> —
/// абзац «дата · вид · размер · файлы · особенности», перенесённый из v1. Владелец, посмотрев
/// панель живьём 28.09.2026, назвал именно его причиной замечания: *«правильно будет сделать
/// правкой строк с имеющимися копиями тоже в виде таблицы… не совсем понятно даже, что это
/// кликабельно»*. Абзац заменён таблицей (<c>Views\BackupTableView.cs</c>), и собирается она
/// ОДНИМ местом — чтобы «как выглядит строка» не решалось в двух местах сразу.
///
/// Пометки «копия панели 1.x» здесь тоже больше нет (решение владельца 28.09.2026): копии прежней
/// панели в список не попадают вовсе, поэтому и помечать в нём нечего.
/// </summary>
public sealed class BackupEntry
{
    public string Path { get; init; } = "";

    public string Name => System.IO.Path.GetFileName(Path);

    public DateTime CreatedAt { get; init; }

    public long Bytes { get; init; }

    public int Files { get; init; }

    public bool WithEngine { get; init; }

    public bool WithSessions { get; init; }

    public bool WithCredentials { get; init; }

    public bool Readable { get; init; }

    public string Error { get; init; } = "";

    /// <summary>
    /// Версия движка, которой снята копия (опись, поле <c>Versions["dsh"]</c>), пусто — в описи её нет.
    ///
    /// Зачем это видно человеку: находка В5 (<c>docs\ROADMAP.md</c>) — **копию, снятую одной версией
    /// движка, другая версия может не открыть** (сообщество описало отказы старых поколений сессий
    /// после обновления хоста). Данные для ответа опись уже несёт — недостаёт ПОКАЗА: без этой строки
    /// человек, у которого сессии не открылись, не понимает почему. Показ — строкой версии в плане
    /// восстановления (<c>RestoreEngine.VersionNote</c>).
    /// </summary>
    public string EngineVersion { get; init; } = "";

    /// <summary>
    /// Момент копии для порядка строк в списке — отметка из ИМЕНИ (<see cref="BackupNaming.ListedMoment"/>).
    /// <c>null</c> — имя неразборчиво; такая копия в списке видна, но в «свежие» не примеряется:
    /// даты у неё нет, и выдумывать её нельзя.
    ///
    /// ⚠️ Это НЕ <see cref="BackupNaming.TimeFromName"/>: тот отвечает на другой вопрос — «когда была
    /// прошлая НАША копия» — и потому читает только наши имена (см. его разбор).
    /// </summary>
    public DateTimeOffset? ListMoment => BackupNaming.ListedMoment(Name);
}
