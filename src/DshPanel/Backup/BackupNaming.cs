using System.Globalization;

namespace DshPanel.Backup;

/// <summary>
/// Что это за файл в папке копий. ЧЕТЫРЕ вида, и различать их обязательно — не ради красоты:
///
/// * **ротация удаляет только свои обычные копии** (<see cref="Copy"/>). Предохранительная копия
///   перед накатом — не «ещё одна копия», а последний путь назад, и трогать её ротации нечем;
/// * **копия панели 1.x (<see cref="Legacy"/>) — не наша.** Папка копий у 1.x и 2.0 ОБЩАЯ
///   (решение владельца 26.09.2026: папку не разводить), поэтому в одной папке лежат архивы двух
///   панелей. 2.0 их ПОКАЗЫВАЕТ и умеет накатывать, но **никогда не удаляет и не считает своими** —
///   ни в ротации, ни в расписании: чужой архив не повод убрать чужое, и он же не должен сбивать
///   наши часы. Ночью 26.09.2026 общая папка уже стоила владельцу архива: панель 1.x сняла свою
///   копию и своей же ротацией удалила архив 2.0 от 24.09, а 2.0 отсчитала свой интервал «каждые
///   24 ч» от ЧУЖОЙ копии («рано: прошло 23 ч 34 мин из 24 ч»);
/// * **чужой файл** (<see cref="Other"/>) — архив человека, документ, что угодно: не наше дело вовсе.
/// </summary>
public enum BackupFileKind
{
    /// <summary>Обычная копия ЭТОЙ панели: <c>dsh2-backup-…-full.zip</c>.</summary>
    Copy,

    /// <summary>Предохранительная копия ЭТОЙ панели, снятая ПЕРЕД накатом: <c>dsh2-before-restore-…</c>.</summary>
    Safety,

    /// <summary>
    /// Копия панели 1.x — ЛЮБАЯ из двух её имён: обычная <c>dsh-backup-…</c> и предохранительная
    /// <c>dsh-before-restore-…</c>. Оба её префикса сведены в ОДИН вид намеренно: для 2.0 они значат
    /// одно и то же — «архив прежней панели, её не трогаем». Различать внутри них нечего: ни ротация,
    /// ни расписание 2.0 в копии 1.x не заглядывают.
    /// </summary>
    Legacy,

    /// <summary>Не наше: файл, чьё имя не начинается ни с одного из четырёх известных префиксов.</summary>
    Other,
}

/// <summary>
/// ИМЯ КОПИИ, ПАПКА ПО УМОЛЧАНИЮ И ПАПКА ИЗ НАСТРОЙКИ.
///
/// ⚠️ **Префикс у 2.0 СВОЙ, и это причина правки (26.09.2026).** Панель 1.x (<c>dsh-tray</c>,
/// её не меняем) и 2.0 по умолчанию кладут копии в ОДНУ папку и раньше называли архивы одинаково
/// (<c>dsh-backup-…</c>). Каждая панель чистит папку «хранить N последних» по СВОЕМУ пределу и
/// считает чужой архив своим — то есть они воевали за одну папку, и это уже стоило владельцу
/// архива. Решение владельца: **папка остаётся ОБЩЕЙ, а имя у 2.0 своё** — <c>dsh2-backup-…</c>
/// для обычной копии и <c>dsh2-before-restore-…</c> для предохранительной.
///
/// Почему это разводит панели НАДЁЖНО, а не «на честном слове»: список и ротация 1.x смотрят строго
/// на свой префикс (<c>..\dsh-tray\BackupService.cs</c>: <c>List()</c> —
/// <c>Directory.GetFiles(Folder, Prefix + "*.zip")</c>, <c>Prune()</c> — по тому же списку), значит
/// наши <c>dsh2-…</c> она не увидит и не удалит. Обратная сторона — наша забота: список 2.0 обязан
/// показать и копии 1.x (<see cref="BackupFolder"/>), а ротация 2.0 — не тронуть их и не счесть
/// (<see cref="BackupRotation"/>).
///
/// Остальное имя перенесено из v1 «как есть» (<c>..\dsh-tray\BackupService.cs:204, 207, 230–237,
/// 357</c>) и по той же причине, по которой переносились единицы размера: **имя файла видит человек**.
/// Он ищет копию глазами в проводнике и уносит её на флешке, поэтому
/// <c>dsh2-backup-2026-09-26-013500-full.zip</c> — та же привычная форма, что была в 1.x, отличается
/// только префикс; менять отметку времени или хвост <c>-full</c> значило бы ломать привычку на ровном
/// месте.
///
/// Класс ЧИСТЫЙ: ни файловой системы, ни настроек, ни движка. Всё, что ему нужно, приходит
/// параметром, — поэтому правило имени проверяется тестом, а не глазами.
/// </summary>
public static class BackupNaming
{
    /// <summary>
    /// Начало имени готовой копии ЭТОЙ панели. Отличается от префикса 1.x одной цифрой — и этого
    /// достаточно: имена файлов сравниваются целиком, и «dsh2-…» никогда не попадёт в выборку
    /// «dsh-backup-*.zip», по которой работает 1.x.
    /// </summary>
    public const string Prefix = "dsh2-backup-";

    /// <summary>
    /// Предохранительная копия 2.0 — та, что снимается ПЕРЕД накатом. Тем же именем её зовёт и накат
    /// (<c>Restore\RestoreEngine</c>): список копий показывает её человеку, а ротация не трогает.
    /// </summary>
    public const string SafetyPrefix = "dsh2-before-restore-";

    /// <summary>
    /// Префикс обычной копии ПРЕЖНЕЙ панели (1.x, <c>..\dsh-tray\BackupService.cs:204</c>).
    ///
    /// Имя выбрано по СМЫСЛУ, а не по номеру версии: «прежняя панель» — то же слово, которым накат
    /// называет её архивы (<c>PanelStrings.RestoreOldPanelArchive</c>: «копия прежней панели»).
    /// Номер в имени обманчив: он ничего не говорит о том, что с этим префиксом делать (не удалять,
    /// не считать, но показывать), и устареет, как только панелей станет три.
    /// </summary>
    public const string LegacyPrefix = "dsh-backup-";

    /// <summary>
    /// Префикс предохранительной копии прежней панели (1.x, <c>..\dsh-tray\BackupService.cs:207</c>).
    /// Отдельной константой, а не «<see cref="LegacyPrefix"/> плюс слово»: это ДВА независимых
    /// префикса 1.x, и склеивать их значило бы гадать о её правилах вместо того, чтобы прочитать их.
    ///
    /// ⚠️ **Хвост имени у панелей разный** (названо холодным проверяющим 26.09.2026): 1.x пишет
    /// <c>dsh-before-restore-⟨штамп⟩-full|thin.zip</c> (<c>BackupService.cs:357</c>), а 2.0 —
    /// <c>dsh2-before-restore-⟨штамп⟩.zip</c>. Нам это не мешает и различать это не нужно: вид
    /// определяется префиксом, а момент времени — штампом сразу за ним (см. <see cref="MomentAfter"/>).
    /// </summary>
    public const string LegacySafetyPrefix = "dsh-before-restore-";

    /// <summary>Полная копия: с движком и Node (v1: <c>full</c>).</summary>
    public const string SuffixFull = "full";

    /// <summary>Тонкая копия: без движка и Node (v1: <c>thin</c>).</summary>
    public const string SuffixThin = "thin";

    /// <summary>
    /// Имя файла копии 2.0: <c>dsh2-backup-2026-09-26-013500-full.zip</c> — форма v1 без изменений,
    /// кроме префикса (<c>..\dsh-tray\BackupService.cs:357</c>). Время местное: копию человек ищет
    /// по своим часам.
    /// </summary>
    public static string ArchiveName(DateTimeOffset started, bool withEngine) =>
        $"{Prefix}{started:yyyy-MM-dd-HHmmss}-{(withEngine ? SuffixFull : SuffixThin)}.zip";

    /// <summary>
    /// Вид файла по имени. Нашим считается имя, которое начинается с нашего префикса И кончается
    /// на <c>.zip</c> — ровно то же условие, по которому список копий ищет архивы
    /// (<see cref="BackupFolder.List"/>). Так «<c>dsh2-backup-….zip.bak</c>» — файл, который человек
    /// зачем-то сохранил под другим именем, — остаётся ЧУЖИМ, и ротация его не тронет: удалить
    /// чужое страшнее, чем не убрать своё.
    ///
    /// Копия прежней панели — ОТДЕЛЬНЫЙ вид, а не «наша копия с другим именем»: по этому различию
    /// ротация решает, что удалять, а расписание — от чего считать интервал. Слей эти два вида —
    /// и панель снова начнёт убирать чужие архивы и отсчитывать свои сутки от чужой копии.
    ///
    /// Сверка БЕЗ учёта регистра: на Windows имена файлов и папок регистр не различают, и
    /// «Dsh2-Backup-…» обязано остаться нашей копией, а не превратиться в файл, который никто
    /// не удалит.
    /// </summary>
    public static BackupFileKind Kind(string? name)
    {
        var text = (name ?? string.Empty).Trim();
        if (!text.EndsWith(".zip", StringComparison.OrdinalIgnoreCase)) return BackupFileKind.Other;

        if (text.StartsWith(Prefix, StringComparison.OrdinalIgnoreCase)) return BackupFileKind.Copy;
        if (text.StartsWith(SafetyPrefix, StringComparison.OrdinalIgnoreCase)) return BackupFileKind.Safety;

        // Оба имени прежней панели — один вид (см. комментарий вида): для 2.0 они значат одно и то же.
        if (text.StartsWith(LegacyPrefix, StringComparison.OrdinalIgnoreCase)
            || text.StartsWith(LegacySafetyPrefix, StringComparison.OrdinalIgnoreCase))
        {
            return BackupFileKind.Legacy;
        }

        return BackupFileKind.Other;
    }

    /// <summary>НАША обычная копия ли это (по имени). Копия панели 1.x нашим не считается.</summary>
    public static bool IsCopy(string? name) => Kind(name) == BackupFileKind.Copy;

    /// <summary>НАША предохранительная копия ли это (по имени).</summary>
    public static bool IsSafety(string? name) => Kind(name) == BackupFileKind.Safety;

    /// <summary>
    /// Копия ПРЕЖНЕЙ панели (1.x) ли это — любая из двух её имён. Спрашивается там, где нужно
    /// показать её человеку, и никогда — там, где решается, что удалить или от чего считать часы.
    /// </summary>
    public static bool IsLegacy(string? name) => Kind(name) == BackupFileKind.Legacy;

    /// <summary>
    /// Момент копии, ВЫЧИТАННЫЙ ИЗ ИМЕНИ, — для ЧАСОВ 2.0: <c>dsh2-backup-2026-09-26-013500-full.zip</c>
    /// → 26.09.2026 01:35:00. Не разобралось — <c>null</c> («время неизвестно»), и это честный ответ:
    /// имя могло быть написано руками или остаться от прежней версии.
    ///
    /// ⚠️ **Читаются ТОЛЬКО наши имена.** Имя копии прежней панели времени не даёт вовсе, и это
    /// не придирка, а сама суть правки: 2.0 спрашивает «когда была ПРОШЛАЯ НАША копия», и ответ
    /// «вчера, но это копия 1.x» отменял бы нужную копию — именно так и вышло ночью 26.09.2026
    /// («рано: прошло 23 ч 34 мин из 24 ч»). Отказ здесь надёжнее фильтра у вызывающего: даже если
    /// кто-то однажды позовёт это для чужого архива, часов он не сдвинет.
    ///
    /// ⚠️ Время в имени — МЕСТНОЕ (<see cref="ArchiveName"/> пишет часы человека), поэтому
    /// и разбирается оно как местное. Читать его как UTC значило бы сдвинуть отсчёт расписания
    /// на разницу часовых поясов — то есть снимать копии не тогда, когда человек думает.
    ///
    /// Нужно это ДВУМЯ читателями, и оба про одно — «когда была прошлая копия?»: расписание
    /// (<see cref="BackupSchedule"/>) и ротация (<see cref="BackupRotation"/>). Описи для этого
    /// не годятся: чтобы узнать момент копии из описи, её надо открыть, а имя лежит на виду.
    ///
    /// ⚠️ **Ветка предохранительной копии сегодня не читается никем**, и это названо холодным
    /// проверяющим 26.09.2026, а не замечено само: расписание считает только обычные копии
    /// (<c>Kind == Copy</c> — фильтр в <c>BackupController.NewestCopyTime</c>), а ротация
    /// предохранительные вообще не удаляет, поэтому их момент ей не нужен. Оставлено осознанно —
    /// отвечать честно дешевле, чем объяснять потом, почему у своей предохранительной копии
    /// «времени нет»; но если ветка не понадобится и дальше, её надо убрать вместе с проверкой
    /// на неё (`BackupNamingTests`), а не оставлять мёртвой.
    /// </summary>
    public static DateTimeOffset? TimeFromName(string? name)
    {
        var text = (name ?? string.Empty).Trim();
        var kind = Kind(text);

        // Копия 1.x и чужой файл времени не дают — см. выше: часы 2.0 идут только от своих копий.
        if (kind is not (BackupFileKind.Copy or BackupFileKind.Safety)) return null;

        return MomentAfter(text, kind == BackupFileKind.Copy ? Prefix : SafetyPrefix);
    }

    /// <summary>
    /// Момент копии из имени — для СПИСКА, то есть для порядка «свежие сверху»
    /// (<see cref="BackupFolder.List"/>). В отличие от <see cref="TimeFromName"/> читает и имена
    /// прежней панели, и это правильно: отметку времени обе панели пишут ОДНУ И ТУ ЖЕ
    /// (<c>гггг-ММ-дд-ЧЧммсс</c> сразу после своего префикса), а человеку список обязан показывать
    /// архивы обеих панелей вперемешку по свежести, а не «сначала наши, потом чужие».
    ///
    /// Два разных вопроса — два разных имени метода, и это не дублирование: «когда была прошлая
    /// НАША копия» (часы) и «когда снят ЭТОТ файл в списке» (порядок строк) — вопросы разные, и ответ
    /// у них совпадает только для наших копий.
    /// </summary>
    public static DateTimeOffset? ListedMoment(string? name)
    {
        var text = (name ?? string.Empty).Trim();

        return Kind(text) switch
        {
            BackupFileKind.Copy => MomentAfter(text, Prefix),
            BackupFileKind.Safety => MomentAfter(text, SafetyPrefix),
            BackupFileKind.Legacy => MomentAfter(
                text,
                text.StartsWith(LegacyPrefix, StringComparison.OrdinalIgnoreCase)
                    ? LegacyPrefix
                    : LegacySafetyPrefix),
            _ => null,
        };
    }

    /// <summary>
    /// Отметка времени сразу за префиксом. Вынесено в одно место, потому что читателей теперь два
    /// (<see cref="TimeFromName"/> и <see cref="ListedMoment"/>), а формат обязан быть ОДИН: разойдись
    /// они — и список показывал бы одни даты, а часы считали по другим.
    /// </summary>
    private static DateTimeOffset? MomentAfter(string text, string prefix)
    {
        if (!text.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return null;

        var stamp = text[prefix.Length..];

        // Отметка времени — ровно 17 знаков («2026-09-26-013500»), и за ней обязан идти РАЗДЕЛИТЕЛЬ:
        // иначе «dsh2-backup-2026-09-26-0135000-full.zip» (лишний знак) прочитался бы как другая дата.
        //
        // Разделителей два, и оба настоящие: «-» стоит у обычной копии (за отметкой идёт «full» или
        // «thin»), «.» — у предохранительной (её имя кончается сразу на «.zip»). Одно правило на оба
        // случая: у копий прежней панели хвоста тоже нет, и требование «только -» молча оставило бы
        // копии 1.x без даты — то есть в списке они уезжали бы в конец, а не стояли по свежести.
        if (stamp.Length < 18 || (stamp[17] != '-' && stamp[17] != '.')) return null;

        if (!DateTime.TryParseExact(
                stamp[..17],
                "yyyy-MM-dd-HHmmss",
                CultureInfo.InvariantCulture,
                DateTimeStyles.None,
                out var parsed))
        {
            return null;
        }

        // Местное время — со смещением, которое действовало В ТОТ момент (у перевода часов
        // смещение бывает разным): поэтому DateTimeOffset строится от DateTimeKind.Local,
        // а не от «сейчас».
        return new DateTimeOffset(DateTime.SpecifyKind(parsed, DateTimeKind.Local));
    }

    /// <summary>
    /// Папка копий по умолчанию — «Документы\DeepSeekHarness-Backups», как в v1
    /// (<c>BackupService.DefaultFolder</c>): её легко найти и унести на флешке.
    ///
    /// ⚠️ Папка остаётся ОБЩЕЙ с панелью 1.x — таково решение владельца 26.09.2026. Разводятся
    /// не папки, а ИМЕНА: иначе человек искал бы свои копии в двух местах и не нашёл бы ни в одном.
    /// </summary>
    public static string DefaultFolder() => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "DeepSeekHarness-Backups");

    /// <summary>
    /// Куда панель кладёт копии: значение настройки, а пустое — умолчание v1.
    /// Переменные окружения раскрываются: так делала v1, и человек этим пользуется —
    /// <c>%USERPROFILE%\Копии DSH</c> обязано работать, а не создать папку с таким именем.
    /// </summary>
    public static string Folder(string? configured)
    {
        var text = (configured ?? string.Empty).Trim();
        if (text.Length == 0) return DefaultFolder();

        return Path.TrimEndingDirectorySeparator(Environment.ExpandEnvironmentVariables(text));
    }

    /// <summary>
    /// Папка взята из умолчания, а не названа человеком. Нужно окну: подставленное умолчание
    /// показывается словами («папка по умолчанию»), а не молча — иначе человек считает,
    /// что он эту папку когда-то выбрал.
    /// </summary>
    public static bool IsDefault(string? configured) => string.IsNullOrWhiteSpace(configured);
}
