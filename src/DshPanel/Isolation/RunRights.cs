namespace DshPanel.Isolation;

/// <summary>
/// Что этому прогону позволено. ОДНО место на всю панель — по образцу одного источника путей.
///
/// Права тут два, и они РАЗНЫЕ. Смешать их — значит однажды отдать прогону проверки то,
/// что принадлежит человеку; в v1 так и вышло: проверка замены файлов перевела боевую запись
/// автозапуска владельца на свою временную копию, а прогон наката показал в журнале его баланс.
///
/// | Право | Кому | Что открывает |
/// |---|---|---|
/// | <see cref="LocalData"/> | изолированному прогону (под своим корнем) и обычному запуску человеком | своё состояние панели и ключ модели: настройки, баланс |
/// | <see cref="MachineData"/> | **только** обычному запуску человеком | машинное окружение: запись автозапуска в реестре, настройки прежней панели |
/// | <see cref="MayOccupyOwnerPort"/> | **только** обычному запуску человеком | порт владельца (3080): на нём 2.0 поднимает свой сервер, но через него идёт канал сессии агента |
/// | <see cref="MayAutoStartServer"/> | **только** обычному запуску человеком | подъём сервера без просьбы человека — при старте панели |
/// | <see cref="MayOwnPhoneGate"/> | **только** обычному запуску человеком | владеть калиткой телефона (этап F): она существует и молчит, пока телефон выключен |
/// | <see cref="MayOpenPhoneGate"/> | **только** обычному запуску человеком, **и только если человек её включил** | калитка телефона (этап F): открыть наружу дверь к движку — своя сеть, свой порт 43127, свой пропуск |
/// | <see cref="MayChangeFirewall"/> | **только** обычному запуску человеком | правило брандмауэра Windows для калитки (этап F4): изменение на МАШИНЕ, с запросом подтверждения Windows |
/// | <see cref="MachineEngineData"/> | **только** обычному запуску человеком | ФАЙЛЫ машинной установки движка в свои артефакты (копия, архив, опись): находка C1 CH-08 — копия изолированного прогона унесла 276,0 МБ / 29 899 файлов машины |
///
/// Первое право изолированному прогону даётся не «на всякий случай»: у него свой корень,
/// и всё, что он там читает и пишет, никого не касается. Второе — не даётся никогда:
/// под своим корнем не бывает ни настоящего <c>HKCU\...\Run</c>, ни каталога прежней панели.
/// </summary>
public static class RunRights
{
    /// <summary>Своё состояние панели и ключ модели: изолированный прогон — под своим корнем, человек — у себя.</summary>
    public static bool LocalData(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);
        return context.IsIsolated || humanLaunch;
    }

    /// <summary>
    /// Машинное окружение — только настоящий запуск человеком. Право по умолчанию «нельзя»:
    /// забыть его выдать безопасно (панель просто ничего не меняет), забыть запретить было бы опасно.
    /// </summary>
    public static bool MachineData(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);
        return humanLaunch && !context.IsIsolated;
    }

    /// <summary>
    /// ФАЙЛЫ МАШИННОЙ УСТАНОВКИ ДВИЖКА — брать их в свои артефакты (копию, архив, опись).
    ///
    /// **От какого случая (находка C1 CH-08).** Изолированная копия (<c>--backup</c> с
    /// <c>--run-root</c>) унесла в архив каталоги МАШИНЫ — <c>%APPDATA%\npm</c> и
    /// <c>%ProgramFiles%\nodejs</c> — 276,0 МБ / 29 899 файлов. Личных данных там не было, но
    /// изоляция не держалась: у изолированного прогона появился путь за свой корень.
    ///
    /// Только обычный запуск человеком: у изолированного прогона установка движка вне его корня —
    /// не его данные, а у прогона проверки и вовсе нет артефактов. Умолчание — «нельзя»: забыть
    /// выдать право безопасно (копия соберётся без машинного движка и НАЗОВЁТ отказ), забыть
    /// запретить было бы опасно.
    ///
    /// ⚠️ **Запуск движка этим правом НЕ управляется**, и это граница, а не оговорка: самотесты
    /// в изоляции обязаны поднимать машинный движок и машинный Node (<c>--server-selftest</c>,
    /// <c>--backup-selftest</c>, <c>--phone-selftest</c>, <c>--engine-install-selftest</c>),
    /// и запрет в поиске движка отнял бы у них работу (вариант V1 разбора A4). Право — про ДАННЫЕ,
    /// а не про программу.
    ///
    /// ⚠️ Тело совпадает с <see cref="MachineData"/> и <see cref="MayChangeFirewall"/>, и это
    /// по-прежнему не повод свести их: там реестр, порт и сетевая дверь, здесь — файлы сторонней
    /// программы, и завтра у любого из них появится своё третье условие.
    /// </summary>
    public static bool MachineEngineData(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);
        return humanLaunch && !context.IsIsolated;
    }

    /// <summary>
    /// Занять порт владельца (<c>3080</c>) — право ОТДЕЛЬНОЕ и только у обычного запуска панели
    /// человеком.
    ///
    /// Решение владельца 26.09.2026: он убирает панель 1.x, и 2.0 поднимает свой сервер на 3080 —
    /// на том самом порту, где стояла 1.x. **Но через этот порт идёт канал сессии агента**, и
    /// оборвать его не имеет права ни один прогон проверки: ни <c>--shot</c>, ни
    /// <c>--shell-selftest</c>, ни самотест сервера. Поэтому право снято для ПРОДУКТА и осталось
    /// запретом для ПРОВЕРОК, и это закреплено кодом, а не «мы аккуратно».
    ///
    /// Тело совпадает с <see cref="MachineData"/>, и это не повод свести их в одну функцию:
    /// права РАЗНЫЕ по смыслу (одно про реестр и чужой каталог, другое про порт), и завтра
    /// у любого из них появится своё третье условие. Сведённые, они поехали бы вместе молча.
    /// </summary>
    public static bool MayOccupyOwnerPort(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);
        return humanLaunch && !context.IsIsolated;
    }

    /// <summary>
    /// Поднимать ли сервер САМОМУ при старте панели — то есть без просьбы человека.
    ///
    /// Два условия, и оба обязательны. Изолированный прогон не поднимает НИЧЕГО: он бы занял
    /// порт, а если его снимут силой, осиротевший <c>node</c> остался бы держать этот порт.
    /// Прогон проверки (<c>--shell-selftest</c> идёт ОБЫЧНЫМ путём панели, значит сюда доходит)
    /// — тоже: он работает на машине владельца, и его сервер помешал бы человеку.
    ///
    /// Отдельной функцией, а не строкой в <c>App</c>: условие «только человек» — это ПРАВО,
    /// и проверка, которая не может его уронить, ничего не стоит. Здесь оно перебирается тестом
    /// по всем четырём сочетаниям; вызов из <c>App</c> проверяется живым прогоном владельца.
    /// </summary>
    public static bool MayAutoStartServer(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);

        return IsolationRules.ShouldAutoStartServer(context.IsIsolated) && humanLaunch;
    }

    /// <summary>
    /// Показывать ли человеку то, что открывается ТОЛЬКО по его щелчку, — окно браузера с работой
    /// агента.
    ///
    /// Право то же, что у остальных «человеческих» дверей, и это не совпадение, а правило: панель
    /// не открывает окон на рабочем столе сама. Но одного «прогон не изолирован» здесь МАЛО, и это
    /// показала холодная проверка 27.09.2026: <c>--shell-selftest</c> идёт обычным путём панели и
    /// НЕ изолирован — по прежнему условию он имел право открыть браузер и не открывал его лишь
    /// потому, что ссылка в том прогоне пуста. То есть предохранитель держался случайностью
    /// (<c>ServerStateFiles.None</c>), а не правом. Теперь держится правом.
    ///
    /// ⚠️ Тело совпадает с <see cref="MayOccupyOwnerPort"/> и <see cref="MachineData"/>, и это
    /// по-прежнему не повод свести их: права РАЗНЫЕ по смыслу (порт / реестр и чужой каталог /
    /// окно на рабочем столе), и завтра у любого из них появится своё третье условие.
    /// </summary>
    public static bool MayOpenBrowser(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);

        return IsolationRules.ShouldAutoOpenBrowser(context.IsIsolated) && humanLaunch;
    }

    /// <summary>
    /// ВЛАДЕТЬ КАЛИТКОЙ ТЕЛЕФОНА — право ОТДЕЛЬНОЕ И САМОЕ СТРОГОЕ (уточнение владельца
    /// 11.10.2026, после живого прогона).
    ///
    /// **Зачем разделено надвое.** Прежде право было одно и отвечало сразу на два вопроса:
    /// «этот прогон вообще имеет дело с калиткой» и «калитка сейчас должна слушать». Из-за этого
    /// выключенный телефон означал, что калитки НЕТ ВОВСЕ: её нельзя было ни выпустить код
    /// сопряжения, ни запустить по щелчку рубильника — потому что объекта не существовало.
    /// Теперь их два, и они разные:
    ///
    /// * <see cref="MayOwnPhoneGate"/> — **этот прогон владеет калиткой** (объект существует, но
    ///   молчит, пока телефон выключен). Только обычный запуск панели человеком: изолированный
    ///   прогон и прогон проверки не владеют ею НИКОГДА — открытый ими порт торчал бы в сеть
    ///   владельца без его ведома, а осиротевший слушатель пережил бы и сам прогон;
    /// * <see cref="MayOpenPhoneGate"/> — **ей позволено СЛУШАТЬ**, и это владение ПЛЮС включённый
    ///   рубильник (<paramref name="enabled"/> — значение <c>phoneEnabled</c> из настроек человека).
    ///
    /// Тело владения совпадает с <see cref="MayAutoStartServer"/>, и это по-прежнему не повод свести
    /// их: там про СВОЙ процесс движка, здесь про дверь наружу — завтра у любого из них появится
    /// своё третье условие.
    /// </summary>
    public static bool MayOwnPhoneGate(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);

        return humanLaunch && !context.IsIsolated;
    }

    /// <summary>
    /// ОТКРЫВАТЬ КАЛИТКУ ТЕЛЕФОНА — право владения И включённый рубильник.
    ///
    /// Калитка (этап F) выставляет наружу дверь к движку: свой слушатель на порту <c>43127</c>,
    /// свой пропуск, белый список вызовов. Это **первая вещь в панели, которую видит ДРУГОЕ
    /// устройство**, поэтому мало «обычного запуска человеком» — нужно ещё, чтобы человек калитку
    /// **включил**. Выключенная калитка не открывается: «человек запустил панель» и «человек
    /// разрешил телефон» — разные вещи, вторая живёт в настройках и по умолчанию <c>false</c>.
    /// </summary>
    public static bool MayOpenPhoneGate(RunContext context, bool humanLaunch, bool enabled) =>
        MayOwnPhoneGate(context, humanLaunch) && enabled;

    /// <summary>
    /// МЕНЯТЬ ПРАВИЛО БРАНДМАУЭРА — право ОТДЕЛЬНОЕ (этап F4), и оно про ИЗМЕНЕНИЕ НА МАШИНЕ.
    ///
    /// Правило брандмауэра — не файл панели и не её состояние: это разрешение, которое получает
    /// входящее соединение ИЗ СЕТИ, и живёт оно в системе, а не в панели. Поэтому мало «прогон
    /// запущен не изолированно»: нужно, чтобы панель запустил ЧЕЛОВЕК.
    ///
    /// * **прогон проверки правила не меняет** — ни <c>--shot</c>, ни самотесты: они живут на машине
    ///   владельца, и открытая ими дыра пережила бы сам прогон;
    /// * **изолированный прогон — тоже нет**: под своим корнем брандмауэра нет, и «правило панели»
    ///   там не значит ничего;
    /// * **человек с улицы правилом не управляет и здесь**: право отвечает только на «чей это
    ///   прогон», а ЧТО именно ставить — решает <see cref="Server.FirewallDecisions"/>, и ставится
    ///   одно узкое правило на порт калитки по его щелчку.
    ///
    /// Тело совпадает с <see cref="MachineData"/>, и это не повод свести их: там про реестр и чужой
    /// каталог, здесь про сетевую дверь машины — завтра у любого из них появится своё третье условие.
    /// </summary>
    public static bool MayChangeFirewall(RunContext context, bool humanLaunch)
    {
        ArgumentNullException.ThrowIfNull(context);
        return humanLaunch && !context.IsIsolated;
    }

    /// <summary>
    /// УБИРАТЬ МЁРТВЫЙ ЗАМОК ДВИЖКА — право то же, что у прочих файлов панели
    /// (<see cref="LocalData"/>): изолированный прогон убирает замки в СВОЁМ корне, обычный запуск
    /// человеком — в его доме движка, а прогон проверки на машине владельца не трогает ничего.
    ///
    /// **Зачем отдельным именем, если тело то же.** Уборка замка — это УДАЛЕНИЕ ЧУЖОГО ФАЙЛА,
    /// и однажды у неё появится своё условие (например «только если движок не поднимался этой
    /// панелью»). Названное право читается на месте вызова как ответ на вопрос «а почему панель
    /// вообще лезет в чужие файлы», а тело, сведённое к <see cref="LocalData"/> здесь, — это
    /// признание, что сегодня условия совпадают, а не что они одно и то же.
    ///
    /// ⚠️ Замок ЖИВОГО владельца не убирается НИКОГДА и никаким правом: сам движок называет это
    /// причиной, по которой он не убирает замки сам («a contender never deletes a lock… an operator
    /// removes it only after verifying that no writer still owns it»), и панель ведёт себя так же.
    /// Право отвечает только на «в чьём доме», а не на «жив ли владелец».
    /// </summary>
    public static bool MayClearEngineLocks(RunContext context, bool humanLaunch) =>
        LocalData(context, humanLaunch);
}
