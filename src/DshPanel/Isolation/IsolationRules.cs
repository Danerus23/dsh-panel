namespace DshPanel.Isolation;

/// <summary>
/// Восемь предикатов изоляции.
///
/// Перенесены из v1 (<c>TrayHost.cs</c>) ДОСЛОВНО: тела не менялись ни на символ.
/// Это не стилистическое упражнение. Предикаты — чистые функции от булевых, и именно
/// поэтому их можно перебрать тестами по одному кейсу на каждое сочетание аргументов,
/// а не верить коду на слово. В v1 их логика стоила прогонов в виртуальной машине
/// и приёмок на живой машине; каждый из них вырос из случая, когда панель помешала
/// владельцу — открыла окно, показала шарик или заняла его порт.
///
/// Здесь ТОЛЬКО решения. Само действие живёт у вызывающего: предикат отвечает на вопрос
/// «показывать ли», а не показывает.
/// </summary>
public static class IsolationRules
{
    /// <summary>
    /// Показывать ли автоматическое сообщение этого вида.
    ///
    /// Вид в правиле не участвует НАМЕРЕННО: исключений нет ни для одного вида. Аргумент
    /// нужен, чтобы самопроверка обошла все виды, а не один. Мастер первой настройки видом
    /// сообщения не является — это запрошенное окно, и изоляция его касается отдельно
    /// (<see cref="ShouldAutoShowOnboarding"/>).
    /// </summary>
    public static bool ShouldNotify(NoticeKind kind, bool isolatedRun) => !isolatedRun;

    /// <summary>
    /// Показывать ли мастер первой настройки. Законных поводов ровно два: его попросили
    /// (<paramref name="requested"/>, ключом) — так работает проверка мастера; либо профиль
    /// настоящий (<paramref name="isolated"/> ложно) и мастер в нём ещё не пройден.
    /// В изолированном прогоне мастер сам не открывается: наши проверки поднимают панель
    /// без ключей на машине владельца, и модальное окно оказывалось на его рабочем столе.
    /// </summary>
    public static bool ShouldAutoShowOnboarding(bool onboarded, bool requested, bool isolated) =>
        requested || (!onboarded && !isolated);

    /// <summary>
    /// Открывать ли браузер самому. В изолированном прогоне — нет: ни один наш прогон
    /// не имеет права открыть окно браузера на рабочем столе владельца. Сервер при этом
    /// поднимается как обычно: проверка считает поднятый сервер и ссылку входа,
    /// а не окно браузера.
    /// </summary>
    public static bool ShouldAutoOpenBrowser(bool isolated) => !isolated;

    /// <summary>
    /// Показывать ли окно панели при старте. Окно открывается только у настоящего прогона
    /// с пройденным мастером: в изолированном панель живёт значком в трее и не кладёт
    /// окно поверх работы владельца.
    /// </summary>
    public static bool ShouldShowWindowOnStart(bool onboarded, bool isolated) => onboarded && !isolated;

    /// <summary>
    /// Поднимать ли сервер САМОМУ при старте. В изолированном прогоне — нет: прогон проверки
    /// не имеет права занять порт владельца (и уж тем более живой 3080), а если его снимут
    /// силой, осиротевший <c>node</c> останется держать порт.
    ///
    /// ✅ **Потребитель появился 27.09.2026** — этим предикатом спрашивает право
    /// <see cref="RunRights.MayAutoStartServer"/>, а им — автоподъём сервера в <c>App.StartPanel</c>
    /// (решение владельца 26.09.2026: 2.0 поднимает свой сервер сама). До этого предикат был
    /// перенесён из v1 дословно и стоял без потребителя; холодный агент 24.09.2026 справедливо
    /// заметил, что объявление без потребителя читается как работающий предохранитель.
    /// ⚠️ Одного его мало: прогон проверки НЕ изолирован (<c>--shell-selftest</c> идёт обычным
    /// путём панели), и второе условие — «это обычный запуск человеком» — лежит рядом.
    /// </summary>
    public static bool ShouldAutoStartServer(bool isolated) => !isolated;

    /// <summary>
    /// Показывать ли окно панели по запросу «покажи окно». Запрос шлёт второй запуск ярлыка,
    /// и в изолированном прогоне это не человек, а проверка: окна владельцу она не показывает,
    /// а пишет строку в журнал. Щелчок по значку трея остаётся — это осознанное действие
    /// человека, а не автоматика.
    /// </summary>
    public static bool ShouldShowPanelOnSignal(bool isolated) => !isolated;

    /// <summary>
    /// Показывать ли шарик «панель запущена — я в трее» (требование владельца 29.09.2026).
    ///
    /// Два условия, и каждое из случая:
    /// * <paramref name="windowShown"/> — если панель показала окно (значок не встал, и она живёт
    ///   окном), человек и так видит, что она работает, и шарик был бы вторым «здравствуйте»;
    /// * <paramref name="isolated"/> — прогон проверки молчит, как и обо всём остальном.
    ///
    /// ⚠️ Это ПЕРВЫЙ шарик, показываемый при обычном запуске БЕЗ просьбы человека. Прежнее
    /// правило было «шарик только когда есть что сказать по делу», и оно здесь нарушено
    /// сознательно: молчаливый уход в трей человек понял как «панель не запустилась».
    /// </summary>
    public static bool ShouldAnnouncePanelStarted(bool windowShown, bool isolated) =>
        !windowShown && !isolated;

    /// <summary>
    /// Выполнять ли фоновые задачи по расписанию: чтение счёта (ключ владельца уходит в сеть),
    /// проверку окон пика и автоматическую копию (она вычищает старые копии по своему счётчику).
    ///
    /// Гейтов окон и шариков для этого МАЛО, и это отдельный класс: они про то, что человек
    /// ВИДИТ, а здесь — про то, что панель ДЕЛАЕТ с его данными. Историческая находка: прогон
    /// проверки читал настоящий профиль владельца и показывал его баланс в журнале.
    /// </summary>
    public static bool ShouldRunScheduledWork(bool isolated) => !isolated;

    /// <summary>
    /// Решение двери: показывать ли автоматическое сообщение ЭТОГО вида.
    ///
    /// Отдельным методом — не для красоты. Тест умеет проверить только наличие ссылки,
    /// а смысл двери («в изолированном прогоне молчит каждый вид») проверяется её ЗНАЧЕНИЕМ,
    /// и значение берётся отсюда. Ссылок на предикат в двери для этого мало: дверь вида
    /// <c>ShouldNotify(kind, isolated &amp;&amp; NeverTrue())</c> их имеет, а показывает всё.
    /// </summary>
    public static bool DoorDecision(NoticeKind kind, bool isolated) => ShouldNotify(kind, isolated);
}