namespace DshPanel.Isolation;

/// <summary>
/// Виды автоматических сообщений панели.
///
/// Перенесено из v1 (<c>TrayHost.cs</c>, <c>enum NoticeKind</c>) дословно, включая порядок.
/// Перечень нужен не для красоты: правило изоляции — общее для ВСЕХ видов, и самопроверка
/// обязана обойти каждый вид, а не один. Если появится новый вид сообщения, он обязан
/// попасть сюда, иначе останется вне общего предохранителя.
/// </summary>
public enum NoticeKind
{
    /// <summary>На GitHub вышла версия новее этой.</summary>
    UpdateAvailable,

    /// <summary>Прошлое обновление не применилось: панель не вышла, мьютекс занят, откат.</summary>
    UpdateOutcome,

    /// <summary>Окна пика на странице цен разошлись с нашими.</summary>
    PeakWindows,

    /// <summary>
    /// Цены или окна пика НА СТРАНИЦЕ изменились относительно предыдущей записи истории
    /// (требование владельца 28.09.2026: шарик обязан называть, что именно изменилось).
    /// Пиковые окна со страницы расписание сами не меняют — они применяются по подтверждению
    /// человека, и шарик об этом говорит словами.
    /// </summary>
    PricingChanged,

    /// <summary>Баланс опустился ниже порога из настроек.</summary>
    BalanceLow,

    /// <summary>Скоро начнётся пик удорожания — за указанное в настройках время.</summary>
    PeakApproaching,

    /// <summary>Резервная копия не удалась.</summary>
    BackupFailed,

    /// <summary>
    /// Копия снята НА ХОДУ: сервер работал, и файлы могли дописываться. Решение владельца
    /// 26.09.2026 — работающий сервер ради копии не гасится, но человек об этом предупреждается
    /// (и ему сказано, что целостную копию снимают вручную, когда работа не идёт).
    /// </summary>
    BackupLiveCopy,

    /// <summary>Ошибка, которую человеку надо показать, а окна панели под рукой нет.</summary>
    Error,

    /// <summary>Запись автозапуска не удалось починить, и сам человек этого не увидит.</summary>
    AutostartBroken,

    /// <summary>
    /// Панель запустилась и ушла в трей. Требование владельца 29.09.2026: обычный запуск не
    /// показывает окна, и человек не понимает, работает панель или нет.
    ///
    /// ⚠️ Это ПЕРВЫЙ вид, который показывается при обычном запуске без просьбы человека.
    /// Поэтому он и назван здесь прямо, а не спрятан: плата за молчание оказалась выше, чем
    /// риск одного лишнего сообщения. Показывается один раз на запуск и только когда окна нет.
    /// </summary>
    PanelStarted,
}
