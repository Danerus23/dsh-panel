using DshPanel.Backup;
using DshPanel.Isolation;

namespace DshPanel.Restore;

/// <summary>
/// ГРАНИЦА ИЗОЛЯЦИИ ДЛЯ НАКАТА: в изолированном прогоне ни одна группа не раскладывается ЗА ПРЕДЕЛЫ
/// корня прогона.
///
/// Зачем это понадобилось. Цели групп движка и Node накат берёт НЕ из корня прогона, а с машины:
/// если движок на ней уже есть, целью становится <c>%APPDATA%\npm</c> и каталог Node —
/// то есть **глобальная установка владельца**, лежащая вне корня (`RestoreEngine.Target`).
/// Пока копию раскладывал только человек из окна, это было решением о его же машине. Но с ключом
/// <c>--restore --with-engine</c> то же самое делает **скрипт** — а изоляция обещает ровно обратное:
/// выведенные панелью пути лежат под корнем прогона (`docs\ISOLATION.md`, §3). Это тот же класс
/// случая, из-за которого в v1 проверка перевела боевую запись автозапуска владельца на свою
/// временную копию.
///
/// Правило одно и читается одной функцией: <see cref="Allows"/>. Она ЧИСТАЯ — ни диска, ни сети, —
/// потому что проверять её надо на состоянии, в котором дефект возможен: цель вне корня и прогон
/// изолирован. Источники ровно те, что названы в `docs\ISOLATION.md`: корень — <see cref="AppPaths.Root"/>,
/// признак изоляции — <c>RunContext.IsIsolated</c>. Второго определения изоляции в панели быть
/// не должно, поэтому и здесь его нет: значение приходит параметром.
///
/// ⚠️ **Обычный запуск человеком правило не трогает** (<paramref name="isolated"/> = <c>false</c>):
/// там движок возвращается по своему месту, как и было решено, — иначе сломалась бы работа
/// с окном копий.
///
/// ⚠️ **Чего это правило НЕ закрывает, и это названо, а не спрятано:** группа рабочей папки
/// (её цель — записанный в описи путь, то есть чужая машина, и он тоже бывает вне корня)
/// и каталоги ключей. Расширять правило на них — решение о данных человека, а не работа рабочего;
/// в отчёте они названы отдельно.
/// </summary>
public static class RestoreConfine
{
    /// <summary>
    /// Разрешена ли раскладка в эту цель.
    ///
    /// <paramref name="target"/> пустой — разрешено: группы с пустой целью и так не раскладываются
    /// (так помечают отказ согласия), и решать здесь нечего.
    /// </summary>
    public static bool Allows(string? target, AppPaths paths, bool isolated)
    {
        ArgumentNullException.ThrowIfNull(paths);

        // Обычный запуск человеком: поведение не меняется — движок возвращается по своему месту.
        if (!isolated) return true;

        // Раскладывать нечего — решать нечего.
        if (string.IsNullOrWhiteSpace(target)) return true;

        // Изоляция без корня — противоречие, а сомнение решается в пользу «нельзя».
        if (string.IsNullOrWhiteSpace(paths.Root)) return false;

        try
        {
            var root = Path.TrimEndingDirectorySeparator(Path.GetFullPath(paths.Root));
            var wanted = Path.TrimEndingDirectorySeparator(Path.GetFullPath(target));

            // Корень — тоже «внутри»: цель, равная корню, за его пределы не выходит.
            if (string.Equals(root, wanted, StringComparison.OrdinalIgnoreCase)) return true;
        }
        catch
        {
            // Кривой путь — не разрешаем: сомнение в вопросе изоляции решается в пользу «нельзя».
            return false;
        }

        return BackupPlanner.IsInside(target, paths.Root);
    }
}
