using Avalonia;

namespace DshPanel.Platform;

/// <summary>
/// Где сейчас указатель мыши — в ФИЗИЧЕСКИХ пикселях экрана, или «не знаю».
///
/// Зачем системный вызов, а не средства Avalonia: у неё позиция указателя спрашивается
/// у конкретного органа (<c>MouseDevice.GetPosition(visual)</c>), то есть «где мышь» без окна
/// под ней не отвечается вовсе. А панель спрашивает ровно это — причём как раз тогда, когда её
/// собственного окна НЕ ВИДНО: она убрана в трей (решение владельца 28.09.2026: «панель свёрнута
/// в трей — окно встаёт у курсора»).
///
/// ⚠️ Координаты — те же, что у рабочих областей экранов: физические пиксели относительно
/// начала виртуального рабочего стола (на мониторе слева они ОТРИЦАТЕЛЬНЫ). Поэтому точка отсюда
/// кладётся в <c>WindowPlacement</c> без пересчёта, а масштаб DPI применяется к РАЗМЕРУ окна,
/// а не к курсору — курсор уже в пикселях.
///
/// Не спросилось — <c>null</c>, и это честный ответ: место окна тогда считается без курсора
/// (панель в трее и курсор неизвестен — окно встаёт по центру главной области), а не «в угол
/// экрана по нулю».
/// </summary>
internal static class SystemCursor
{
    /// <summary>Позиция указателя в пикселях экрана или <c>null</c>, если Windows не ответила.</summary>
    public static PixelPoint? Position()
    {
        if (!NativeMethods.GetCursorPos(out var point)) return null;

        return new PixelPoint(point.X, point.Y);
    }
}
