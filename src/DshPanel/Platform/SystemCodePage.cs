using System.Runtime.InteropServices;

namespace DshPanel.Platform;

/// <summary>
/// ЧЕМ ПИШЕТ СИСТЕМА — одна дверь на всю панель: OEM-кодовая страница Windows.
///
/// **Зачем отдельная дверь.** Ответ <c>cmd</c>/<c>mklink</c> приходит не в UTF-8 и не в кодировке
/// культуры .NET, а в кодировке КОНСОЛИ СИСТЕМЫ, то есть в OEM-кодовой странице Windows.
/// Замерено 30.09.2026 на машине владельца (русская Windows, <c>GetOEMCP()</c> = 866,
/// <c>GetACP()</c> = 1251): ответ «соединение создано для …» приходит байтами
/// <c>e1 ae a5 a4 a8 ad a5 …</c> и в слова разбирается РОВНО кодовой страницей 866; кодовой
/// страницей культуры — нет: 437 даёт «ß«Ññ¿¡Ñ¡¿Ñ ß«ºñá¡« ñ½∩», 850 — «… ñ½´». Сами байты
/// при этом от культуры НЕ зависят: прогон при ru-RU, en-US и de-DE дал одни и те же байты, —
/// значит решает язык СИСТЕМЫ, а не культура процесса.
///
/// ⚠️ **Почему не <c>GetConsoleOutputCP</c>** (замер там же): у процесса БЕЗ консоли — а панель
/// это WinExe, и её <c>--restore</c> идёт оттуда же, <c>GetConsoleWindow()</c> = 0 — она отвечает
/// 0, а у процесса с консолью 65001 (консоль перенастраивает себе PowerShell). С байтами ответа
/// не совпало НИ ОДНО из этих значений; совпало только <c>GetOEMCP()</c>.
/// </summary>
public static class SystemCodePage
{
    /// <summary>
    /// Запасной путь, когда система не ответила вовсе: CP866 — кодовая страница русской Windows,
    /// то есть ровно тот случай, ради которого ответ и понадобился. Число это не выдумано здесь:
    /// его выдал сам Windows на машине владельца, а запасной путь для того и нужен, чтобы назвать
    /// ответ по-русски, если спросить не удалось.
    /// </summary>
    public const int RussianOem = 866;

    [DllImport("kernel32.dll", SetLastError = true)]
    private static extern uint GetOEMCP();

    /// <summary>
    /// OEM-кодовая страница Windows (<c>GetOEMCP</c>). 0 — спросить не удалось: система не
    /// ответила (другой платформы у панели нет, и это единственный честный ответ).
    /// </summary>
    public static int Oem()
    {
        try
        {
            return (int)GetOEMCP();
        }
        catch
        {
            return 0;
        }
    }

    /// <summary>
    /// ЧЕМ РАЗБИРАТЬ ОТВЕТ КОНСОЛИ: кодовой страницей, СПРОШЕННОЙ У СИСТЕМЫ.
    ///
    /// Функция ЧИСТАЯ — Windows здесь не спрашивается, число приходит снаружи, — поэтому её
    /// и перебирает прогон (см. <c>AnswerEncodingTests</c>). Культура процесса
    /// (<c>CultureInfo.CurrentCulture.TextInfo.OEMCodePage</c>) в этом решении не участвует
    /// НИКОГДА: культура — про язык панели, а ответ приходит на языке Windows. На английской
    /// Windows с русской культурой страница культуры (866) не та, которой система писала (437), —
    /// отсюда и «кракозябры» в ответе.
    ///
    /// 0 и меньше — «система не ответила»: тогда <see cref="RussianOem"/> (CP866).
    /// </summary>
    public static int ForAnswer(int systemCodePage) =>
        systemCodePage > 0 ? systemCodePage : RussianOem;
}
